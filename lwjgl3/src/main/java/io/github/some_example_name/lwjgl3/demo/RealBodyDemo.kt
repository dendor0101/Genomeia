    override fun create() {
        shapes = ShapeRenderer(60000)
        batch = SpriteBatch()
        font = BitmapFont()
        camera = OrthographicCamera()
        viewport = FitViewport(VIEW_WIDTH, VIEW_HEIGHT, camera)
        hudCamera = OrthographicCamera()

        // Зум колесом. Только он и требует InputProcessor: всё остальное опрашивается
        // напрямую, а прокрутка приходит событием и опросом её не поймать.
        Gdx.input.inputProcessor = object : com.badlogic.gdx.InputAdapter() {
            override fun scrolled(amountX: Float, amountY: Float): Boolean {
                // Мир под курсором запоминается ДО зума и возвращается ПОСЛЕ — так
                // приближение идёт к точке под мышью, а не к центру экрана.
                tmp.set(Gdx.input.x.toFloat(), Gdx.input.y.toFloat(), 0f)
                viewport.unproject(tmp)
                val wx = tmp.x
                val wy = tmp.y

                camera.zoom *= if (amountY > 0) 1.15f else 1f / 1.15f
                camera.zoom = camera.zoom.coerceIn(0.05f, 8f)
                camera.update()

                tmp.set(Gdx.input.x.toFloat(), Gdx.input.y.toFloat(), 0f)
                viewport.unproject(tmp)
                camera.position.x += wx - tmp.x
                camera.position.y += wy - tmp.y
                camera.update()
                return true
            }
        }

        buildFromFile()
        reset()
    }

    override fun resize(width: Int, height: Int) {
        viewport.update(width, height)
        // Позиция ставится ТОЛЬКО в первый раз: иначе изменение размера окна сбрасывало
        // бы панораму и зум, которые пользователь только что настроил.
        if (!cameraPlaced) {
            camera.position.set(viewCenterX(), 0.85f, 0f)
            cameraPlaced = true
        }
        camera.update()
        hudCamera.setToOrtho(false, width.toFloat(), height.toFloat())
    }

    private var cameraPlaced = false

    /** Центр кадра: середина между копиями, иначе вторая уезжает за край. */
    private fun viewCenterX(): Float {
        var lo = Float.MAX_VALUE; var hi = -Float.MAX_VALUE
        for (i in 0 until n) {
            val v = body.x[i]
            if (v < lo) lo = v
            if (v > hi) hi = v
        }
        return (lo + hi) * 0.5f
    }

    override fun render() {
        handleInput()

        // Мышцы обновляются ВНУТРИ паузы-гварда вместе с физикой. Иначе на паузе
        // активации продолжали бы ехать к цели, длины покоя менялись бы без решателя,
        // и при снятии паузы тело получало бы разом накопленную ошибку — рывок.
        if (!paused) {
            var steps = 0
            if (!fastForward) {
                // ФИКСИРОВАННЫЙ ШАГ С АККУМУЛЯТОРОМ.
                //
                // Раньше здесь был ровно один шаг на кадр отрисовки, и DT работал как
                // «предполагаемая длительность кадра». Пока DT совпадал с частотой
                // экрана, это сходилось; после перехода на 60 UPS при отрисовке в 144
                // кадра симуляция пошла бы в 2.4 раза быстрее реального времени, и
                // счётчик simTime врал бы ровно во столько же.
                //
                // DT НЕ ТРОГАЕТСЯ НИКОГДА: детерминизм требует фиксированного шага, а
                // скорость проигрывания меняется числом тиков, а не их длиной.
                // timeScale умножает РЕАЛЬНОЕ время, а не DT. Значит меняется число
                // тиков в секунду, а не их длина: на 0.5x получаются побитово те же
                // состояния, просто показанные на большем числе кадров.
                accumulator += Gdx.graphics.deltaTime.toDouble() * controls.timeScale
                // Потолок на догон. Без него после подвисания (перетаскивание окна,
                // сборка мусора) накопленный долг отрабатывается разом, и тело получает
                // пачку шагов подряд — выглядит как взрыв.
                if (accumulator > MAX_CATCHUP) accumulator = MAX_CATCHUP
                while (accumulator >= DT) {
                    stepOnce()
                    accumulator -= DT
                    steps++
                }
            } else {
                // Крутим шаги, пока не выйдет бюджет. Проверка ПОСЛЕ шага, а не до:
                // хотя бы один шаг за кадр обязан пройти, иначе при просроченном кадре
                // симуляция встанет совсем и это будет похоже на зависание.
                val deadline = System.nanoTime() + FAST_BUDGET_MS * 1_000_000L
                do {
                    stepOnce()
                    steps++
                } while (System.nanoTime() < deadline && steps < FAST_MAX_STEPS)
                // В ускорении долг не копим: реальное время тут ни при чём.
                accumulator = 0.0
            }
            // Доля тика, уже покрытая реальным временем: по ней fx()/fy() выбирают точку
            // в истории подшагов. В ускорении интерполировать нечего — там за кадр
            // проходит много тиков, показываем последнее состояние.
            renderAlpha = if (fastForward) 1.0 else (accumulator / DT).coerceIn(0.0, 1.0)

            // Сглаживание, иначе число в HUD прыгает и его невозможно прочесть.
            stepsAvg += (steps - stepsAvg) * 0.1f
        }
        prepareLerp()
        countInverted()

        ScreenUtils.clear(BG)
        Gdx.gl.glEnable(GL20.GL_BLEND)
        Gdx.gl.glBlendFunc(GL20.GL_SRC_ALPHA, GL20.GL_ONE_MINUS_SRC_ALPHA)
        shapes.projectionMatrix = camera.combined

        shapes.begin(ShapeRenderer.ShapeType.Filled)
        // Заливка идёт ПО ТРЕУГОЛЬНИКАМ: у гексагональной топологии нет ячеек, из которых
        // можно было бы собрать контур, а треугольники ограничения площади её и покрывают.
        for (t in 0 until body.triCount) {
            val i0 = body.triA[t]; val i1 = body.triB[t]; val i2 = body.triC[t]
            val m = triMuscle[t]
            val act = if (m >= 0) muscleActivation[m] else 0.0
            shapes.color = when {
                triInverted[t] -> INVERTED_FILL
                triTorn(i0, i1, i2) -> TEAR_FILL
                boneOf[i0] != -1 && boneOf[i0] == boneOf[i1] && boneOf[i0] == boneOf[i2] ->
                    if (bonesRigid) BONE_FILL else BONE_FILL_OFF
                m >= 0 -> if (act > 0.002) tmpColor.set(MUSCLE_IDLE).lerp(MUSCLE_FILL, act.toFloat()) else MUSCLE_IDLE
                else -> SOFT_FILL
            }
            shapes.triangle(fx(i0), fy(i0), fx(i1), fy(i1), fx(i2), fy(i2))
        }
        // Кости заливаются ещё и по своим связям: у мелких костей треугольников может
        // не быть вовсе, и без этого они на картинке пропадут.
        if (viewMode == 1) {
            for (i in 0 until n) {
                if (boneOf[i] == -1) continue
                shapes.color = if (bonesRigid) BONE_FILL else BONE_FILL_OFF
                shapes.circle(fx(i), fy(i), body.radius[i] * 0.9f, 10)
            }
        }
        shapes.color = ACTIVE
        if (hoverId >= 0) shapes.circle(fx(hoverId), fy(hoverId), body.meanLinkLength * 0.5f, 14)
        shapes.color = DOT
        // Точки рисуются СВОИМ радиусом, а не общим: иначе разница масс между клетками
        // не видна глазами, а она теперь влияет на физику.
        for (i in 0 until n) shapes.circle(fx(i), fy(i), body.radius[i] * 0.22f, 6)
        shapes.end()

        shapes.begin(ShapeRenderer.ShapeType.Filled)
        shapes.color = GROUND_COLOR
        shapes.rectLine(-1f, GROUND_Y.toFloat(), 5f, GROUND_Y.toFloat(), 0.006f)
        shapes.color = LINK
        for (c in 0 until conCount) {
            val i = conA[c]; val j = conB[c]
            shapes.rectLine(fx(i), fy(i), fx(j), fy(j), 0.0015f)
        }

        // КОНТАКТНЫЕ ЧАСТИЦЫ. Рисуются кружком СВОЕГО радиуса, умноженного на
        // CONTACT_SCALE, — то есть ровно тем кругом, которым клетка и сталкивается.
        // Так видно настоящую геометрию контакта, а не приблизительную метку: если
        // круги налезли друг на друга, значит контакт обязан был сработать.
        // Кости сюда попадают наравне с мягкой тканью: граница у них общая.
        val ctDraw = contacts
        if (contactsOn && ctDraw != null) {
            shapes.color = CONTACT_COLOR
            for (e in 0 until boundCount) {
                for (v in intArrayOf(boundA[e], boundB[e])) {
                    shapes.circle(fx(v), fy(v), ctDraw.contactRadiusOf(v).toFloat(), 12)
                }
            }
            // Свободные частицы рисуем отдельно: они не лежат ни на одном граничном
            // ребре, и цикл выше их просто не видит.
            for (i in 0 until n) {
                if (!isFree[i]) continue
                shapes.circle(fx(i), fy(i), ctDraw.contactRadiusOf(i).toFloat(), 12)
            }
        }

        // Граница: то, что реально омывается средой и создаёт тягу.
        shapes.color = BOUNDARY_COLOR
        for (e in 0 until boundCount) {
            val i = boundA[e]; val j = boundB[e]
            shapes.rectLine(fx(i), fy(i), fx(j), fy(j), 0.005f)
        }

        // Пары изгиба — только в отладочном режиме и только когда стадия включена:
        // иначе они закрывают контур сплошной сеткой и мешают смотреть на само тело.
        if (viewMode == 1 && bendLevel > 0) {
            shapes.color = BEND_COLOR
            for (c in 0 until bendCount) {
                val i = bendA[c]; val j = bendB[c]
                shapes.rectLine(fx(i), fy(i), fx(j), fy(j), 0.002f)
            }
        }
        shapes.end()

        drawHud()
    }

    private fun drawHud() {
        batch.projectionMatrix = hudCamera.combined
        batch.begin()
        var y = Gdx.graphics.height - 14f
        val line = 18f

        font.color = HUD_TEXT
        font.draw(batch, "REAL BODY FROM GENOME EDITOR  -  XPBD + shape matching", 16f, y); y -= line * 1.4f

        font.color = HUD_MUTED
        font.draw(batch, "cells = $n   links = $conCount   area triangles = ${body.triCount}" +
            "   (%.2f per cell)".format(body.triCount.toFloat() / n), 16f, y); y -= line
        font.draw(batch, "substeps = $SUBSTEPS   soft compliance = $SOFT_COMPLIANCE   viscosity = $VISCOSITY /s", 16f, y); y -= line
        font.draw(batch, "medium drag = $MEDIUM_DRAG /s (isotropic, no thrust)   normal drag = $NORMAL_DRAG on $boundCount boundary edges", 16f, y); y -= line

        font.color = if (degenerateBones > 0 || boneCapHits > 0) HUD_WARN else HUD_MUTED
        font.draw(batch, "bones: ${rigidBones.size} rigid clusters" +
            "   ${degenerateBones} single-cell IGNORED   step cap hits = $boneCapHits", 16f, y); y -= line

        font.color = HUD_MUTED
        font.draw(batch, "muscles: ${body.muscleClusters.size} clusters   hovered = $hoveredMuscle", 16f, y); y -= line

        font.color = if (invertedPeak > 0) INVERTED_FILL else HUD_MUTED
        font.draw(batch, "INVERTED triangles: now = $invertedNow   peak = $invertedPeak", 16f, y); y -= line

        // --- наблюдение за дрейфом ---
        //
        // Дрейф показывается В КЛЕТКАХ (в средних длинах связи), а не в мировых единицах:
        // «уехал на 0.04» само по себе ни о чём не говорит, а «уехал на одну клетку»
        // сразу понятно. Импульс рядом нужен, чтобы отличить две разные вещи: тело ещё
        // едет по инерции (|P| большой, дрейф растёт) или уже стоит, а уехало раньше
        // (|P| около нуля при выросшем дрейфе). Это ровно то различие, на котором в
        // PhysicsAudit держится вся проверка честности.
        val ddx = comX() - startCx
        val ddy = comY() - startCy
        val drift = sqrt(ddx * ddx + ddy * ddy)
        var pxSum = 0.0; var pySum = 0.0
        for (i in 0 until n) { pxSum += vx[i]; pySum += vy[i] }
        val momentum = sqrt(pxSum * pxSum + pySum * pySum)
        font.color = HUD_TEXT
        font.draw(batch, "sim time = %.1f s   drift = %.4f (%.2f cells)   |P| = %.3f"
            .format(simTime, drift, drift / body.meanLinkLength, momentum), 16f, y); y -= line

        // Изгиб контура: показывается всегда, потому что он МЕНЯЕТ ФИЗИКУ и по картинке
        // это не всегда очевидно — тело просто становится упрямее.
        // Контакты: число сработавших, обрезок CCD и обоих потолков. Потолки в норме
        // должны быть нулями — ненулевое значит удар или что-то пошло не так.
        font.color = if (contactsOn) HUD_TEXT else HUD_MUTED
        val ct = contacts
        font.draw(batch, if (contactsOn)
            "CONTACTS [K] on   now = %d   ccd clamps = %d   link cap = %d   speed cap = %d   torn = %d"
                .format(ct?.lastContacts ?: 0, ct?.lastToiClamps ?: 0, linkCapHits, speedCapHits,
                    if (::linkTorn.isInitialized) linkTorn.count { it } else 0)
        else "K -- self-contact (OFF)", 16f, y); y -= line

        font.color = if (bendLevel > 0) HUD_WARN else HUD_MUTED
        font.draw(batch, if (bendLevel > 0)
            "CONTOUR BEND [E] = %.0e on %d pairs  -- thrust cost, see BEND_LEVELS"
                .format(bendCompliance(), bendCount)
        else "E -- contour bend (OFF, %d pairs available)".format(bendCount), 16f, y); y -= line

        font.color = if (controls.timeScale != 1.0) HUD_WARN else HUD_MUTED
        font.draw(batch, "TIME SCALE [T] = x%.2f   INTERP [I] = %s".format(controls.timeScale,
            when (interpMode) {
                0 -> "off (raw physics state)"
                1 -> "tick bounds (2 snapshots/tick)"
                else -> "by substeps (%d snapshots/tick)".format(SUBSTEPS + 1)
            }), 16f, y); y -= line

        font.color = if (fastForward) HUD_WARN else HUD_MUTED
        font.draw(batch, if (fastForward)
            "FAST FORWARD [F] -- x%.0f  (%.0f steps/frame, budget %d ms)"
                .format(stepsAvg, stepsAvg, FAST_BUDGET_MS)
        else "F -- fast forward (real time now)", 16f, y); y -= line * 1.4f

        font.color = HUD_MUTED
        font.draw(batch, "LMB drag   HOVER a muscle edge   1..9 hold a muscle   0 hold ALL   " +
            "G auto-gait" + if (gait) " [ON, period $GAIT_PERIOD]" else "", 16f, y); y -= line
        font.draw(batch, "SPACE pause   F fast   E bend   R reset   B bones   C view   P bullet   O slam   RMB/MMB pan   wheel zoom",
            16f, y); y -= line
        if (paused) { font.color = HUD_WARN; font.draw(batch, "PAUSED", 16f, y) }
        batch.end()

        // Диалог рисуется ПОСЛЕДНИМ, поверх всего: он и логически сверху, и свои
        // begin/end у него собственные — рисовать его внутри чужой пары нельзя.
        controls.render(shapes, batch, font, Gdx.graphics.width)
    }

    override fun dispose() {
        shapes.dispose(); batch.dispose(); font.dispose()
    }
}

/** Запуск: зелёная стрелка. Путь к выгрузке можно передать аргументом. */
fun main(args: Array<String>) {
    if (StartupHelper.startNewJvmIfRequired()) return
    val path = if (args.isNotEmpty()) args[0] else "body-export.txt"
    val config = Lwjgl3ApplicationConfiguration().apply {
        setTitle("Организм из редактора — XPBD + shape matching")
        setWindowedMode(1100, 720)
        useVsync(true)
        setForegroundFPS(144)
    }
    Lwjgl3Application(RealBodyDemo(path), config)
}
