    private fun buildFromFile() {
        body = BodyFile.load(bodyPath, copies = ORGANISMS, freeParticles = FREE_PARTICLES)
        n = body.count

        px = DoubleArray(n); py = DoubleArray(n)
        prevX = DoubleArray(n); prevY = DoubleArray(n)
        vx = DoubleArray(n); vy = DoubleArray(n)
        invMass = DoubleArray(n); matchWeight = DoubleArray(n)
        inContact = BooleanArray(n)

        boneOf = IntArray(n) { -1 }
        muscleOf = IntArray(n) { -1 }

        // Жёсткими считаются кластеры от трёх клеток: две дают лишь жёсткий стержень,
        // то есть ровно то же, что обычная связь, и заводить ради них проекцию незачем.
        val rigid = body.boneClusters.filter { it.size >= 3 }
        degenerateBones = body.boneClusters.size - rigid.size
        rigidBones = rigid.toTypedArray()
        rigidBones.forEachIndexed { b, ids -> for (i in ids) boneOf[i] = b }
        buildBoneRestPose()

        body.muscleClusters.forEachIndexed { m, ids -> for (i in ids) muscleOf[i] = m }
        muscleActivation = DoubleArray(body.muscleClusters.size)
        muscleTarget = DoubleArray(body.muscleClusters.size)

        // --- связи: внутрикостные не создаются, их держит проекция ---
        val a = ArrayList<Int>(body.linkCount)
        val b = ArrayList<Int>(body.linkCount)
        val rest = ArrayList<Double>(body.linkCount)
        val mus = ArrayList<Int>(body.linkCount)
        for (k in 0 until body.linkCount) {
            val i = body.linkA[k]
            val j = body.linkB[k]
            if (boneOf[i] != -1 && boneOf[i] == boneOf[j]) continue
            val dx = body.x[i] - body.x[j]
            val dy = body.y[i] - body.y[j]
            a.add(i); b.add(j); rest.add(sqrt((dx * dx + dy * dy).toDouble()))
            // Мышца — только если ОБА конца в одном кластере. Связь от мышцы к обычной
            // ткани или к кости длину не меняет: она и передаёт тягу наружу.
            mus.add(if (muscleOf[i] != -1 && muscleOf[i] == muscleOf[j]) muscleOf[i] else -1)
        }
        conCount = a.size
        conA = a.toIntArray(); conB = b.toIntArray()
        conRest = rest.toDoubleArray(); conMuscle = mus.toIntArray()

        triMuscle = IntArray(body.triCount) { t ->
            val i0 = body.triA[t]; val i1 = body.triB[t]; val i2 = body.triC[t]
            if (muscleOf[i0] != -1 && muscleOf[i0] == muscleOf[i1] && muscleOf[i0] == muscleOf[i2])
                muscleOf[i0] else -1
        }
        triInverted = BooleanArray(body.triCount)

        buildBoundary()
        buildBend()
        buildMasses()
        buildOrganisms()
        buildContacts()
        histX = Array(SUBSTEPS + 1) { DoubleArray(n) }
        histY = Array(SUBSTEPS + 1) { DoubleArray(n) }

        pickRadius = body.meanLinkLength * PICK_FACTOR
        edgePickRadius = body.meanLinkLength * EDGE_PICK_FACTOR

        println("[RealBodyDemo] " + body.describe())
        println("[RealBodyDemo] rigid bones = ${rigidBones.size}, degenerate clusters dropped = $degenerateBones" +
            ", largest = ${rigidBones.maxOfOrNull { it.size } ?: 0} cells (drag on it is that many times weaker)")
    }

    /**
     * Пары изгиба вдоль границы: соседи «через одну» и расстояние между ними в позе покоя.
     *
     * Обходить контур по порядку не требуется и было бы хрупко — у рваных краёв и
     * развилок порядок неоднозначен. Достаточно локального признака: вершина, у которой
     * ровно ДВА граничных ребра, лежит внутри гладкого участка контура, и её соседи
     * через одну образуют пару. Вершины развилок (три и более граничных ребра)
     * пропускаются: там «изгиб» не определён.
     */
    /**
     * МАССА ИЗ РАДИУСА КЛЕТКИ. Раньше у всех стояла единица, а body.radius разбирался
     * из файла и не использовался нигде.
     *
     * Масса берётся пропорционально ПЛОЩАДИ, то есть квадрату радиуса — мир двумерный,
     * и клетка вдвое большего радиуса весит вчетверо больше, а не вдвое.
     *
     * НОРМИРОВКА НА СРЕДНЮЮ МАССУ ОБЯЗАТЕЛЬНА. Все подобранные константы — податливости,
     * сопротивление среды, вязкость, скорости мышц — взаимодействуют с массой. Если
     * задать массу в абсолютных единицах радиуса, весь набор придётся подбирать заново
     * просто оттого, что редактор сохранил клетки другого размера. При нормировке
     * средняя масса всегда единица, и константы остаются переносимыми между телами.
     *
     * НА ТЕКУЩЕМ ТЕЛЕ ЭТО ТОЖДЕСТВЕННОЕ ПРЕОБРАЗОВАНИЕ: у всех 370 клеток радиус 0.5,
     * значит после нормировки у всех ровно 1.0, и ни одно измеренное число не меняется.
     * Это и хорошо — механизм заводится, а настройки не сбиваются. Разница появится
     * на телах, где геном вырастил клетки разного размера.
     */
    /**
     * Строит самоконтакт и предельные длины связей.
     *
     * Предел длины считается на КАЖДУЮ связь отдельно, а не общим числом: радиусы у
     * клеток разные, и общий предел был бы неверен для обеих сторон сразу.
     */
    /** Связные компоненты графа связей — это и есть отдельные организмы. */
    private fun buildOrganisms() {
        organismOf = IntArray(n) { -1 }
        val adjHead = IntArray(n) { -1 }
        // По ПОЛНОМУ списку связей из файла, а не по conA/conB: внутрикостные связи
        // в решатель намеренно не попадают (их держит проекция кости), и по ним кости
        // распались бы на отдельные компоненты. На двух телах это давало 126
        // «организмов» вместо двух.
        val adjNext = IntArray(body.linkCount * 2)
        val adjTo = IntArray(body.linkCount * 2)
        var e = 0
        for (c in 0 until body.linkCount) {
            val a = body.linkA[c]; val b = body.linkB[c]
            adjTo[e] = b; adjNext[e] = adjHead[a]; adjHead[a] = e; e++
            adjTo[e] = a; adjNext[e] = adjHead[b]; adjHead[b] = e; e++
        }
        val queue = IntArray(n)
        var comp = 0
        for (s in 0 until n) {
            if (organismOf[s] != -1) continue
            var head = 0; var tail = 0
            organismOf[s] = comp; queue[tail++] = s
            while (head < tail) {
                val v = queue[head++]
                var k = adjHead[v]
                while (k != -1) {
                    val u = adjTo[k]
                    if (organismOf[u] == -1) { organismOf[u] = comp; queue[tail++] = u }
                    k = adjNext[k]
                }
            }
            comp++
        }
        organismCount = comp
        organismSize = IntArray(comp)
        for (i in 0 until n) organismSize[organismOf[i]]++
        flowVX = DoubleArray(comp)
        flowVY = DoubleArray(comp)
        comAccX = DoubleArray(comp)
        comAccY = DoubleArray(comp)
        println("[RealBodyDemo] organisms = $comp (own flow reservoir each)")
    }

    private fun buildContacts() {
        radius = DoubleArray(n) { body.radius[it].toDouble() }
        isFree = BooleanArray(n) { true }
        for (k in body.linkA.indices) { isFree[body.linkA[k]] = false; isFree[body.linkB[k]] = false }
        conMaxLen = DoubleArray(conCount) { c ->
            LINK_MAX_STRETCH * conRest[c]
        }
        linkTorn = BooleanArray(conCount)
        // Карта пары вершин в номер связи: нужна отрисовке, чтобы покрасить
        // ТРЕУГОЛЬНИК по его рёбрам. Строится один раз, в кадре только чтение.
        linkOfPair = HashMap(conCount * 2)
        for (c in 0 until conCount) {
            val a = minOf(conA[c], conB[c]).toLong()
            val b = maxOf(conA[c], conB[c]).toLong()
            linkOfPair[a * 1000003L + b] = c
        }
        contacts = BoundaryContacts.build(
            n, conA, conB, conCount, boundA, boundB, boundCount, radius,
            CONTACT_SCALE, CCD_CORE, CONTACT_RESTITUTION, CONTACT_FRICTION,
            body.x, body.y,
            body.meanLinkLength.toDouble(), CONTACT_MAX_STEP, isFree,
        )
        println("[RealBodyDemo] contact particles = ${boundCount} boundary edges, " +
            "contact radius from boundary edges, seal margin")
    }

    private fun buildMasses() {
        restInvMass = DoubleArray(n)
        var meanArea = 0.0
        for (i in 0 until n) {
            val r = body.radius[i].toDouble()
            meanArea += r * r
        }
        meanArea /= n
        for (i in 0 until n) {
            val r = body.radius[i].toDouble()
            val m = if (meanArea > 0.0) (r * r) / meanArea else 1.0
            restInvMass[i] = if (m > 1e-12) 1.0 / m else 1.0
        }
    }

    private fun buildBend() {
        val nb0 = IntArray(n) { -1 }
        val nb1 = IntArray(n) { -1 }
        val deg = IntArray(n)
        for (e in 0 until boundCount) {
            val i = boundA[e]; val j = boundB[e]
            if (deg[i] == 0) nb0[i] = j else if (deg[i] == 1) nb1[i] = j
            deg[i]++
            if (deg[j] == 0) nb0[j] = i else if (deg[j] == 1) nb1[j] = i
            deg[j]++
        }
        val a = ArrayList<Int>(); val b = ArrayList<Int>(); val r = ArrayList<Double>()
        for (v in 0 until n) {
            if (deg[v] != 2) continue
            val i = nb0[v]; val j = nb1[v]
            if (i < 0 || j < 0 || i == j) continue
            val dx = (body.x[i] - body.x[j]).toDouble()
            val dy = (body.y[i] - body.y[j]).toDouble()
            a.add(i); b.add(j); r.add(sqrt(dx * dx + dy * dy))
        }
        bendCount = a.size
        bendA = a.toIntArray(); bendB = b.toIntArray(); bendRest = r.toDoubleArray()
        println("[RealBodyDemo] bend pairs = $bendCount on $boundCount boundary edges")
    }

    /**
     * Поза покоя костей: смещения от центроида кластера, один раз и навсегда.
     *
     * Центроид считается в double НАМЕРЕННО: это подготовка, а не горячий путь, и
     * именно здесь дешевле всего убить сокращение разрядов. В движке это делает
     * запекатель BakedLayout, в рантайме double не появляется.
     *
     * Сумма смещений досаживается в ноль итерацией: после вычитания среднего во float
     * сумма остаётся порядка 1e-6, второй проход убирает и её. Без этого проекция кости
     * каждый подшаг сдвигала бы кость на этот остаток — а это и был дрейф.
     */
    private fun buildBoneRestPose() {
        boneRestQx = Array(rigidBones.size) { DoubleArray(rigidBones[it].size) }
        boneRestQy = Array(rigidBones.size) { DoubleArray(rigidBones[it].size) }
        var maxSize = 1
        rigidBones.forEachIndexed { b, ids ->
            if (ids.size > maxSize) maxSize = ids.size
            val qx = boneRestQx[b]; val qy = boneRestQy[b]
            var cx = 0.0; var cy = 0.0
            for (i in ids) { cx += body.x[i]; cy += body.y[i] }
            cx /= ids.size; cy /= ids.size
            for (k in ids.indices) {
                qx[k] = body.x[ids[k]] - cx
                qy[k] = body.y[ids[k]] - cy
            }
            for (pass in 0 until 3) {
                var sx = 0.0; var sy = 0.0
                for (k in ids.indices) { sx += qx[k]; sy += qy[k] }
                if (sx == 0.0 && sy == 0.0) break
                val dx = sx / ids.size; val dy = sy / ids.size
                for (k in ids.indices) { qx[k] -= dx; qy[k] -= dy }
            }
        }
        boneDx = DoubleArray(maxSize)
        boneDy = DoubleArray(maxSize)
    }

    /**
     * Граница тела — рёбра, входящие ровно в ОДИН треугольник.
     *
     * Внутреннее ребро делят два треугольника, граничное — только один. Это работает на
     * любой топологии, включая рваные края и отростки, и не требует ни обхода контура,
     * ни знания порядка вершин.
     *
     * Считается по ВСЕМ треугольникам, а не по списку связей решателя: внутрикостных
     * связей мы не создаём, но поверхность кости средой омывается точно так же.
     */
    private fun buildBoundary() {
        val useCount = HashMap<Long, Int>(body.triCount * 3)
        fun key(a: Int, b: Int): Long {
            val lo = minOf(a, b).toLong()
            val hi = maxOf(a, b).toLong()
            return (lo shl 32) or hi
        }
        for (t in 0 until body.triCount) {
            val i0 = body.triA[t]; val i1 = body.triB[t]; val i2 = body.triC[t]
            useCount.merge(key(i0, i1), 1, Int::plus)
            useCount.merge(key(i1, i2), 1, Int::plus)
            useCount.merge(key(i2, i0), 1, Int::plus)
        }
        // Обход идёт по ВСЕМ связям, а не по ключам карты треугольников. Связь в тонком
        // отростке (шириной в одну клетку) не входит НИ В ОДИН треугольник, в карту не
        // попадает вовсе — и, считая только по карте, я терял такие рёбра целиком.
        // А это как раз хвост и плавники, то есть основная гребущая поверхность.
        val a = ArrayList<Int>(); val b = ArrayList<Int>()
        for (k in 0 until body.linkCount) {
            val i = body.linkA[k]; val j = body.linkB[k]
            if ((useCount[key(i, j)] ?: 0) <= 1) { a.add(i); b.add(j) }
        }
        boundCount = a.size
        boundA = a.toIntArray(); boundB = b.toIntArray()
        println("[RealBodyDemo] boundary edges = $boundCount")
    }

