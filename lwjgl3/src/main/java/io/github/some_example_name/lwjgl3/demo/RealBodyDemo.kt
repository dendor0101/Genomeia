    /**
     * Во сколько раз сжат кластер мышцы: 1 в покое, MUSCLE_CONTRACTION при полном
     * сокращении. -1 (не мышца, шов между кластерами) — всегда 1.
     *
     * Именно ЭТО и есть вся модель мышцы: меняется длина покоя ограничения, а не сила.
     * Жёсткость остаётся прежней, поэтому мышца тянет ровно с той силой, которая нужна,
     * чтобы дотащить ткань до новой длины, и упирается, если ей мешают. Прямой аналог
     * degreeOfShortening в движке.
     */
    private fun muscleScale(m: Int) =
        if (m < 0) 1.0 else 1.0 - muscleActivation[m] * (1.0 - MUSCLE_CONTRACTION)

    private fun solveConstraints(h: Double) {
        val alpha = SOFT_COMPLIANCE / (h * h)
        // Направление обхода ЧЕРЕДУЕТСЯ. См. sweepBackwards.
        val order = if (sweepBackwards) (conCount - 1) downTo 0 else 0 until conCount
        for (c in order) {
            val i = conA[c]; val j = conB[c]
            val wi = invMass[i]; val wj = invMass[j]
            val w = wi + wj
            if (w == 0.0) continue
            var dx = px[i] - px[j]
            var dy = py[i] - py[j]
            val len = sqrt(dx * dx + dy * dy)
            if (len < 1e-12) continue
            dx /= len; dy /= len
            val rest = conRest[c] * muscleScale(conMuscle[c])
            val dL = -(len - rest) / (w + alpha)
            px[i] += dx * dL * wi; py[i] += dy * dL * wi
            px[j] -= dx * dL * wj; py[j] -= dy * dL * wj
        }
    }

    /**
     * Изгиб границы: обычное ограничение расстояния между соседями через одну.
     * Стоит ПОСЛЕ площадей и перед проекцией кости, вместе с остальными позиционными.
     * См. BEND_LEVELS — по умолчанию стадия выключена и выходит на первой же строке.
     */
    /**
     * ПРЕДЕЛ ДЛИНЫ СВЯЗИ. Жёстко, без податливости — см. LINK_MAX_LENGTH.
     *
     * Односторонний: сжатию не мешает вовсе, срабатывает только на растяжении сверх
     * суммы радиусов. Стоит СРАЗУ ПОСЛЕ solveConstraints, чтобы мягкая пружина не могла
     * оставить связь растянутой до конца подшага.
     *
     * В движке ровно это условие — сигнал к разрыву связи. Здесь рвать нечем, поэтому
     * связь просто бесконечно крепкая.
     */
    private fun solveLinkMaxLength() {
        for (c in 0 until conCount) {
            val i = conA[c]; val j = conB[c]
            val wi = invMass[i]; val wj = invMass[j]
            val w = wi + wj
            if (w == 0.0) continue
            var dx = px[i] - px[j]
            var dy = py[i] - py[j]
            val len = sqrt(dx * dx + dy * dy)
            val max = conMaxLen[c]
            if (len <= max || len < 1e-12) continue
            // Пик недобора за всё время: сколько связь хотела сверх предела.
            if (len - max > LINK_TEAR_STRAIN * conRest[c]) linkTorn[c] = true
            dx /= len; dy /= len
            // Тот же потолок поправки за подшаг, что и у контакта, и по той же
            // причине: стадия ЖЁСТКАЯ, перерастяжение она снимает целиком за один
            // подшаг, а updateVelocities делит поправку на крошечное h. При загибе
            // связи растягиваются сильно, и отсюда шёл остаток выброса скорости.
            // Делится по паре в тех же долях, поэтому импульс пары сохраняется.
            var dL = -(len - max) / w
            val capL = CONTACT_MAX_STEP * body.meanLinkLength / w
            if (dL < -capL) dL = -capL
            px[i] += dx * dL * wi; py[i] += dy * dL * wi
            px[j] -= dx * dL * wj; py[j] -= dy * dL * wj
            linkCapHits++
        }
    }

    /** Сколько раз предел длины связи сработал с последнего сброса. Видно в HUD. */
    private var linkCapHits = 0

    /** Связь хоть раз требовала растяжения сверх порога разрыва. См. LINK_TEAR_STRAIN. */
    private lateinit var linkTorn: BooleanArray
    private var linkOfPair = HashMap<Long, Int>()

    /** Какую свободную частицу заряжать следующей. См. fireBullet. */
    private var nextBullet = 0

    /**
     * Запустить свободную частицу справа налево на потолке скорости.
     *
     * Берутся по кругу уже существующие свободные частицы: заводить новые значило бы
     * менять n на ходу, а от n зависят все массивы решателя и разбиение на организмы.
     */
    /**
     * ТАРАН [O]: два самых крупных организма разгоняются НАВСТРЕЧУ друг другу.
     *
     * Пуля проверяет мембрану на одиночной лёгкой клетке, и этого мало: там масса
     * ничтожная, ткань даже не напрягается. Здесь на контур наваливается вся масса
     * второго тела, и это уже настоящее условие — самое тяжёлое столкновение,
     * какое в симуляции вообще возможно при действующем потолке скорости.
     *
     * Импульс задаётся КАЖДОЙ частице организма, а не одной: тело должно лететь
     * целиком, как брошенное, а не растягиваться за разогнанным краем.
     */
    private fun slamOrganisms() {
        // Два самых крупных организма — это тела; свободные частицы отсеиваются
        // сами, они размером в одну клетку.
        val order = (0 until organismCount).sortedByDescending { organismSize[it] }
        if (order.size < 2) return
        val a = order[0]; val b = order[1]
        if (organismSize[b] < 2) return

        var ax = 0.0; var ay = 0.0; var an = 0
        var bx = 0.0; var by = 0.0; var bn = 0
        for (i in 0 until n) {
            when (organismOf[i]) {
                a -> { ax += px[i]; ay += py[i]; an++ }
                b -> { bx += px[i]; by += py[i]; bn++ }
            }
        }
        if (an == 0 || bn == 0) return
        ax /= an; ay /= an; bx /= bn; by /= bn

        var dx = bx - ax; var dy = by - ay
        val d = sqrt(dx * dx + dy * dy)
        if (d < 1e-12) return
        dx /= d; dy /= d

        val speed = BULLET_SPEED_FRACTION * MAX_SPEED_CELLS_PER_TICK * body.meanLinkLength / DT
        for (i in 0 until n) {
            when (organismOf[i]) {
                a -> { vx[i] = dx * speed; vy[i] = dy * speed }
                b -> { vx[i] = -dx * speed; vy[i] = -dy * speed }
            }
        }
        println("[RealBodyDemo] таран: организмы $a и $b, по " +
            "%.1f клеток/тик навстречу".format(speed * DT / body.meanLinkLength))
    }

    private fun fireBullet() {
        val ids = (0 until n).filter { isFree[it] }
        if (ids.isEmpty()) return
        val i = ids[nextBullet % ids.size]
        nextBullet++

        // Справа от всего, что есть на сцене, на высоте середины тел.
        var maxX = -Double.MAX_VALUE
        var sumY = 0.0; var cnt = 0
        for (k in 0 until n) {
            if (isFree[k]) continue
            if (px[k] > maxX) maxX = px[k]
            sumY += py[k]; cnt++
        }
        if (cnt == 0) return
        val speed = BULLET_SPEED_FRACTION * MAX_SPEED_CELLS_PER_TICK * body.meanLinkLength / DT
        px[i] = maxX + body.meanLinkLength * 8.0
        py[i] = sumY / cnt
        prevX[i] = px[i]; prevY[i] = py[i]
        vx[i] = -speed; vy[i] = 0.0
        println("[RealBodyDemo] пуля: клетка #$i, скорость " +
            "%.1f клеток/тик".format(speed * DT / body.meanLinkLength))
    }

    /** Порвалась ли хоть одна из трёх сторон треугольника. */
    private fun triTorn(i0: Int, i1: Int, i2: Int): Boolean =
        pairTorn(i0, i1) || pairTorn(i1, i2) || pairTorn(i0, i2)

    private fun pairTorn(a: Int, b: Int): Boolean {
        val c = linkOfPair[minOf(a, b).toLong() * 1000003L + maxOf(a, b).toLong()] ?: return false
        return linkTorn[c]
    }

    /**
     * ПОТОЛОК СКОРОСТИ — см. MAX_SPEED_CELLS_PER_TICK.
     *
     * Не физика, а гарантия для коллизий: путь за подшаг обязан оставаться конечным,
     * иначе DDA упрётся в размер буфера, а оценка «широкую фазу можно строить раз в
     * тик» перестанет быть верхней границей.
     */
    private fun clampSpeed() {
        val maxV = MAX_SPEED_CELLS_PER_TICK * body.meanLinkLength / DT
        val maxV2 = maxV * maxV
        for (i in 0 until n) {
            val v2 = vx[i] * vx[i] + vy[i] * vy[i]
            if (v2 > peakSpeed2) peakSpeed2 = v2
            if (v2 <= maxV2) continue
            val s = maxV / sqrt(v2)
            vx[i] *= s; vy[i] *= s
            speedCapHits++
        }
    }

    /** Сколько раз потолок скорости сработал. Видно в HUD. */
    private var speedCapHits = 0

    /** Наибольшая увиденная скорость в квадрате, ДО обрезки. Замер, а не гадание. */
    private var peakSpeed2 = 0.0

    private fun solveBend(h: Double) {
        val compliance = bendCompliance()
        if (compliance < 0.0) return
        val alpha = compliance / (h * h)
        for (c in 0 until bendCount) {
            val i = bendA[c]; val j = bendB[c]
            val wi = invMass[i]; val wj = invMass[j]
            val w = wi + wj
            if (w == 0.0) continue
            var dx = px[i] - px[j]
            var dy = py[i] - py[j]
            val len = sqrt(dx * dx + dy * dy)
            if (len < 1e-12) continue
            dx /= len; dy /= len
            val dL = -(len - bendRest[c]) / (w + alpha)
            px[i] += dx * dL * wi; py[i] += dy * dL * wi
            px[j] -= dx * dL * wj; py[j] -= dy * dL * wj
        }
    }

    private fun solveAreas(h: Double) {
        val alpha = AREA_COMPLIANCE / (h * h)
        // Вывернутым треугольникам своя, нулевая — см. AREA_COMPLIANCE_INVERTED.
        val alphaInverted = AREA_COMPLIANCE_INVERTED / (h * h)
        val maxStep = AREA_MAX_STEP * body.meanLinkLength
        for (t in 0 until body.triCount) {
            val i0 = body.triA[t]; val i1 = body.triB[t]; val i2 = body.triC[t]
            val x0 = px[i0]; val y0 = py[i0]
            val x1 = px[i1]; val y1 = py[i1]
            val x2 = px[i2]; val y2 = py[i2]

            val g0x = y1 - y2; val g0y = x2 - x1
            val g1x = y2 - y0; val g1y = x0 - x2
            val g2x = y0 - y1; val g2y = x1 - x0

            val w0 = invMass[i0]; val w1 = invMass[i1]; val w2 = invMass[i2]
            val denom = w0 * (g0x * g0x + g0y * g0y) +
                w1 * (g1x * g1x + g1y * g1y) +
                w2 * (g2x * g2x + g2y * g2y)
            if (denom < 1e-18) continue

            // Площадь покоя едет вместе с длинами: иначе мышца тянет треугольник вниз,
            // а несжимаемая площадь держит его на месте, и ткань запирает.
            val s = muscleScale(triMuscle[t])
            val restArea2 = body.triRestArea2[t].toDouble() * s * s
            val area2 = (x1 - x0) * (y2 - y0) - (y1 - y0) * (x2 - x0)
            // Плавный переход вместо ступеньки — см. AREA_SMOOTH_RAMP.
            val a = if (AREA_SMOOTH_RAMP) {
                val t = (area2 / restArea2).coerceIn(0.0, 1.0)
                alphaInverted + (alpha - alphaInverted) * t * t
            } else if (area2 < 0.0) alphaInverted else alpha
            var dL = -(area2 - restArea2) / (denom + a)
            // Потолок на длину поправки — см. AREA_MAX_STEP.
            if (maxStep > 0.0) {
                val corr = abs(dL) * sqrt(denom)
                if (corr > maxStep) dL *= maxStep / corr
            }

            px[i0] += w0 * dL * g0x; py[i0] += w0 * dL * g0y
            px[i1] += w1 * dL * g1x; py[i1] += w1 * dL * g1y
            px[i2] += w2 * dL * g2x; py[i2] += w2 * dL * g2y
        }
    }

    /**
     * ТЯГА МЫШИ — СИЛА, А НЕ ТЕЛЕПОРТ. Зовётся ПОСЛЕ updateVelocities.
     *
     * Раньше тяга правила ПОЗИЦИЮ прямо среди позиционных стадий, и из этого росли
     * сразу две беды, обе видимые руками.
     *
     * ПЕРВАЯ: сквозь тело можно было протащить что угодно. Контакт расталкивает
     * позиционно, но на следующем подшаге тяга снова ставила клетку туда же, куда
     * тянет курсор. Позиционная тяга ничем не ограничена и просто перетягивала
     * контакт, сколько бы тот ни отталкивал. Ткань при этом даже не напрягалась —
     * поэтому и синие треугольники не появлялись: рвать было нечего, клетка ехала
     * насквозь, а не продавливала.
     *
     * ВТОРАЯ: тяга за кость выходила тем сильнее, чем кость крупнее. projectBone
     * идёт ПОСЛЕ тяги и подтягивает ВЕСЬ кластер к сдвинутой клетке, так что одна
     * позиционная поправка двигала всю костную массу целиком.
     *
     * Обе беды снимает одно и то же: тяга задаёт СКОРОСТЬ, а положение получается
     * из неё через integrate на следующем подшаге. Тогда
     *   - контакт решает позиционно и ПОСЛЕДНИМ, значит выигрывает всегда;
     *   - кость сама делит тягу на свой размер: shape matching разносит смещение
     *     одной клетки по всему кластеру, и кость из N клеток трогается примерно
     *     в N раз медленнее. Делить вручную не нужно, это выходит из сохранения
     *     импульса.
     *
     * Ограничение по УСКОРЕНИЮ, а не по силе: тянуть надо одинаково отзывчиво и
     * лёгкую клетку, и тяжёлую, иначе мелкие клетки улетали бы от курсора. Деление
     * тяги по массе всё равно происходит, но уровнем ниже — в кости и в связях.
     */
    private fun applyDragVelocity(h: Double) {
        val i = dragId
        if (i < 0 || invMass[i] == 0.0) return
        val dx = mouseX - px[i]
        val dy = mouseY - py[i]
        val d = sqrt(dx * dx + dy * dy)
        if (d < 1e-12) return

        // РУКА ДАЁТ ПОСТОЯННУЮ СИЛУ, а не постоянное ускорение. Это и есть причина
        // несоразмерности тяги за кость.
        //
        // Раньше кость получала ТО ЖЕ УСКОРЕНИЕ, что одиночная клетка. Ускорение то
        // же, а масса в N раз больше — значит импульс в N раз больше, и чем крупнее
        // кластер, тем сильнее рывок. Именно это и наблюдалось: за самую большую
        // кость тело улетало несоизмеримо резче, чем за мягкую ткань.
        //
        // Теперь ограничена СИЛА. Одиночная клетка средней массы получает прежнее
        // ускорение, а кость из N клеток — в N раз меньшее, потому что тяжёлое и
        // разгоняется медленнее. Импульс за подшаг при насыщении выходит одинаковым
        // в обоих случаях, force * h, то есть тяга стала честной по импульсу.
        //
        // Массы нормированы так, что средняя клетка весит единицу (см. restInvMass),
        // поэтому эталонная масса здесь и есть единица, и отдельной константы для
        // неё не нужно.
        val b = if (bonesRigid) boneOf[i] else -1

        var mTotal = 0.0
        var cx = 0.0; var cy = 0.0
        val ids = if (b >= 0) rigidBones[b] else null
        if (ids != null) {
            for (k in ids) {
                if (invMass[k] <= 0.0) continue
                val m = 1.0 / invMass[k]
                mTotal += m; cx += m * px[k]; cy += m * py[k]
            }
            if (mTotal <= 0.0) return
            cx /= mTotal; cy /= mTotal
        }

        val force = DRAG_ACCEL * body.meanLinkLength / (DT * DT)
        val aMax = if (ids != null) force / mTotal else force * invMass[i]

        // Целевая скорость: добраться до курсора за тик, но не быстрее потолка.
        var vWant = d / DT
        if (vWant > MAX_DRAG_SPEED) vWant = MAX_DRAG_SPEED
        val tx = dx / d * vWant
        val ty = dy / d * vWant

        // Догоняем целевую скорость, но не быстрее, чем позволяет сила.
        var ax = (tx - vx[i]) / h
        var ay = (ty - vy[i]) / h
        val a = sqrt(ax * ax + ay * ay)
        if (a > aMax) { val s = aMax / a; ax *= s; ay *= s }

        val vLimit = DRAG_SPEED_LIMIT * MAX_SPEED_CELLS_PER_TICK * body.meanLinkLength / DT

        if (ids == null) {
            var nvx = vx[i] + ax * h
            var nvy = vy[i] + ay * h
            val v = sqrt(nvx * nvx + nvy * nvy)
            if (v > vLimit) { val sc = vLimit / v; nvx *= sc; nvy *= sc }
            vx[i] = nvx; vy[i] = nvy
            return
        }

        // КОСТЬ ТЯНЕТСЯ ЦЕЛИКОМ, а не через одну свою клетку.
        //
        // Дать скорость одной клетке жёсткой кости нельзя: projectBone тут же
        // вернёт её на жёсткую позу, updateVelocities сделает из возврата скорость
        // ПРОТИВОПОЛОЖНУЮ тяге, а на следующем подшаге тяга надавит снова. Кость
        // начинает перекачиваться сама с собой на частоте подшагов — отсюда и
        // хаотичная скорость, и разрывы ткани там, где рука её не касалась.
        //
        // Правильно — приложить импульс В ТОЧКУ ЗАХВАТА ко всему твёрдому телу и
        // разнести его как положено: поступательная часть J/M одинакова для всех,
        // вращательная (r x J)/I добавляет скорость по радиусу. Тогда поза кости
        // не нарушается вовсе, проекции нечего исправлять, и качаться нечему.
        //
        // Величина импульса подобрана так, чтобы кость получала ТО ЖЕ линейное
        // ускорение, что получила бы одиночная клетка. Значит тяжёлую кость тянуть
        // так же отзывчиво, как лёгкую, а вот тело вокруг неё сопротивляется по
        // своей массе — что и требуется.
        var inertia = 0.0
        var maxR = 0.0
        for (k in ids) {
            if (invMass[k] <= 0.0) continue
            val rx = px[k] - cx; val ry = py[k] - cy
            val r2 = rx * rx + ry * ry
            inertia += r2 / invMass[k]
            if (r2 > maxR) maxR = r2
        }
        maxR = sqrt(maxR)

        val jx = ax * h * mTotal
        val jy = ay * h * mTotal
        val rgx = px[i] - cx; val rgy = py[i] - cy
        var dOmega = if (inertia > 1e-18) (rgx * jy - rgy * jx) / inertia else 0.0

        // Вращение ограничивается тем же потолком: у длинной кости дальняя клетка
        // иначе получила бы куда больше, чем разрешено ускорением тяги.
        val vEdge = abs(dOmega) * maxR
        val vCap = sqrt(ax * ax + ay * ay) * h
        if (vEdge > vCap && vEdge > 1e-18) dOmega *= vCap / vEdge

        // Прикидываем итог и, если самая быстрая клетка кости выходит за потолок,
        // ослабляем ВЕСЬ импульс — и поступательную часть, и вращательную. Резать
        // скорости по одной здесь нельзя: это сломало бы и жёсткость позы, и
        // сохранение импульса, ради которого весь этот кусок и написан.
        var worst = 0.0
        for (k in ids) {
            if (invMass[k] <= 0.0) continue
            val rx = px[k] - cx; val ry = py[k] - cy
            val nvx = vx[k] + jx / mTotal - dOmega * ry
            val nvy = vy[k] + jy / mTotal + dOmega * rx
            val v = sqrt(nvx * nvx + nvy * nvy)
            if (v > worst) worst = v
        }
        var sc = 1.0
        if (worst > vLimit && worst > 1e-18) sc = vLimit / worst

        for (k in ids) {
            if (invMass[k] <= 0.0) continue
            val rx = px[k] - cx; val ry = py[k] - cy
            vx[k] += sc * (jx / mTotal - dOmega * ry)
            vy[k] += sc * (jy / mTotal + dOmega * rx)
        }
    }

    private var dragShiftX = 0.0
    private var dragShiftY = 0.0

    /**
     * Направление обхода связей в solveConstraints. Переворачивается каждый подшаг.
     *
     * ЭТО ЛЕЧИТ ВТОРОЙ ИСТОЧНИК БЛУЖДАНИЯ — паразитный МОМЕНТ, который к точности
     * счёта отношения не имеет вовсе.
     *
     * Откуда он берётся. Отдельно взятое ограничение расстояния момента не создаёт
     * никогда: поправка идёт вдоль связи, а плечо у неё — сама связь, и векторное
     * произведение равно нулю ТОЧНО. Но Гаусс-Зейдель обходит связи подряд, и каждая
     * следующая видит позиции, уже сдвинутые предыдущими. Плечо, относительно которого
     * поправка была безмоментной, к этому времени уже уехало. Ошибка второго порядка по
     * величине поправки, но она СИСТЕМАТИЧЕСКАЯ — знак у неё задаёт порядок нумерации
     * связей, а он от кадра к кадру один и тот же.
     *
     * ЗАМЕР, который это доказывает. Мышца сокращена и удерживается 2000 кадров,
     * внешних сил нет вовсе, всё в double (чтобы округление не мешало):
     *
     *     обход вперёд   ->  L = +4.4269
     *     обход назад    ->  L = -4.3953      знак ПЕРЕВЕРНУЛСЯ
     *     чередуя        ->  L = +0.0813      в 54 раза меньше
     *
     * Знак переворачивается вместе с порядком — значит дело именно в порядке, а не в
     * физике и не во float. Отсюда и лекарство: чередовать. Это симметричный
     * Гаусс-Зейдель, стандартный приём, а не подпорка; стоит он ровно ноль — цикл тот
     * же, просто индекс идёт в другую сторону.
     *
     * ЧТО БЫЛО БЕЗ ЭТОГО: омега 4.4e-2 рад/с, то есть тело само разворачивалось на
     * полный круг за 144 секунды симуляции. На ускорении это минута с небольшим.
     *
     * АЛЬТЕРНАТИВА, которая тоже работает, но дороже: поднять число подшагов. Замер
     * (double, обход вперёд): 4 -> L 4.43, 8 -> 1.15, 16 -> 0.29, 32 -> 0.017. То есть
     * восемь подшагов вместо чередования дадут вчетверо худший результат при вдвое
     * большей цене. Чередование лучше по обоим счётам.
     */
    private var sweepBackwards = false

    /**
     * Убирает смещение центра масс, накопленное ВНУТРЕННИМИ стадиями подшага.
     *
     * [beforeX]/[beforeY] — сумма координат до них. Внутренние ограничения обязаны
     * сохранять центр масс точно, поэтому вся разница (за вычетом честного вклада
     * мыши) — это округление float32, и её можно вычесть без всякой физики.
     */
    private fun cancelInternalDrift(beforeX: Double, beforeY: Double) {
        var afterX = 0.0
        var afterY = 0.0
        for (i in 0 until n) { afterX += px[i]; afterY += py[i] }
        val dx = (afterX - beforeX - dragShiftX) / n
        val dy = (afterY - beforeY - dragShiftY) / n
        for (i in 0 until n) { px[i] -= dx; py[i] -= dy }
    }

    /**
     * Shape matching, alpha = 1. Проекция кости на позу покоя.
     *
     * ГЛАВНЫЙ ИСТОЧНИК ПАРАЗИТНОГО ДРЕЙФА БЫЛ ИМЕННО ЗДЕСЬ — и это была не физика,
     * а сокращение значащих разрядов float32. Замер на этом теле, 600 кадров удержания
     * мышцы, суммарное смещение центра масс от каждой стадии (идеал — ноль):
     *
     *     стадия              как было      после починки
     *     solveConstraints    1.1e-05        1.8e-05
     *     solveAreas          6.0e-05        (см. AREA_COMPLIANCE)
     *     projectBone        -1.1e-02       -9.5e-06      в 1170 раз меньше
     *
     * То есть проекция кости текла в ТЫСЯЧУ раз сильнее, чем оба ограничения вместе.
     * updateVelocities делит это смещение на h, то есть умножает на 576, и оно попадает
     * прямо в скорость: суммарный импульс тела за 600 кадров был |P| = 9.8 при массе 370.
     * Отсюда и «мышца дёрнулась пару раз, а тело потом само куда-то уплывает».
     *
     * ПОЧЕМУ ТЕКЛО. Всё считалось в МИРОВЫХ координатах: px около 1.55, а смещение от
     * центра кости около 0.05. Разность двух чисел величиной 1.55 несёт ошибку 1e-7
     * АБСОЛЮТНУЮ, то есть 2e-6 ОТНОСИТЕЛЬНО самого смещения. В сумме по кластеру эти
     * ошибки не гасятся, и сумма w*q, которая обязана быть нулём по определению
     * центроида, оказывается порядка 1e-5. Ровно на неё центр масс кости и съезжает —
     * каждый подшаг, всегда примерно в одну сторону, потому что поза покоя постоянна.
     *
     * ТРИ ЛЕКАРСТВА, по вкладу (замер выше; разбирающий их стенд был одноразовым и
     * удалён, цифры перенесены сюда):
     *   1. локальное начало отсчёта — числа порядка размера кости, а не мира: 24x;
     *   2. смещения позы покоя q0 предпосчитаны и досажены суммой в ноль: само по себе
     *      почти ничего не даёт, но нужно для п.3 и убирает работу с горячего пути;
     *   3. суммарная поправка обнуляется ЯВНО: ещё 45x, итого 1170x.
     *
     * Зачёт УГЛОВОЙ поправки тоже пробовался и оказался вреден: линейная утечка от него
     * выросла с 9.5e-6 до 9.8e-5, а угловая не улучшилась. Дело в том, что оптимальный
     * угол best-fit сам по себе даёт нулевой угловой импульс — это условие
     * стационарности того максимума, который ищет полярное разложение. Угловая утечка
     * живёт не здесь, а в solveAreas.
     *
     * ЧЕМ ЗА ЭТО ЗАПЛАЧЕНО, честно. Прежняя версия в позе покоя давала РОВНО ноль:
     * она собирала позицию обратно из тех же самых сумм, из которых считала центроид,
     * и промахи взаимно уничтожались до бита. Здесь q0 предпосчитан, поэтому цель
     * отличается от body.x на 1e-7, и в покое остаётся ненулевая поправка. Замер,
     * 2400 кадров без всякой активности мышц: смещение центра масс 1.3e-3, и это
     * СЛУЧАЙНОЕ БЛУЖДАНИЕ (знак меняется), а не снос. Против 0.742 за 70 секунд после
     * одного сокращения — то есть проиграно 500x там, где выиграно 16x. Вернуть точный
     * ноль в покое, не отказываясь от предпосчитанного r0, у меня не получилось:
     * пробовал и мировые координаты вместо локальных (утечка в покое 1.7e-3, а выбег
     * ХУЖЕ: |P| 0.49 против 0.14), и отказ от досаживания суммы q0 в ноль (3.3e-3 и
     * |P| 0.42). Обе хуже по обоим показателям сразу.
     */
    private fun projectBone(b: Int) {
        val ids = rigidBones[b]
        val q0x = boneRestQx[b]
        val q0y = boneRestQy[b]

        // Начало отсчёта — первая вершина кости. Дальше все числа порядка размера
        // кости, и сокращения значащих разрядов больше нет.
        val ox = px[ids[0]]; val oy = py[ids[0]]

        var cx = 0.0; var cy = 0.0; var wsum = 0.0
        for (i in ids) {
            val w = matchWeight[i]
            cx += w * (px[i] - ox); cy += w * (py[i] - oy)
            wsum += w
        }
        cx /= wsum; cy /= wsum

        var s = 0.0; var t = 0.0
        for (k in ids.indices) {
            val i = ids[k]
            val w = matchWeight[i]
            val ppx = (px[i] - ox) - cx; val ppy = (py[i] - oy) - cy
            s += w * (q0x[k] * ppx + q0y[k] * ppy)
            t += w * (q0x[k] * ppy - q0y[k] * ppx)
        }
        val norm = sqrt(s * s + t * t)
        if (norm < 1e-12) return
        val cos = s / norm; val sin = t / norm

        // Считаются ПОПРАВКИ, а не сразу позиции: только по ним и можно обнулить
        // утечку. Сама поправка мала (1e-6), поэтому её сумма считается точно.
        var sdx = 0.0; var sdy = 0.0
        for (k in ids.indices) {
            val i = ids[k]
            val tx = ox + cx + cos * q0x[k] - sin * q0y[k]
            val ty = oy + cy + sin * q0x[k] + cos * q0y[k]
            boneDx[k] = tx - px[i]; boneDy[k] = ty - py[i]
            val w = matchWeight[i]
            sdx += w * boneDx[k]; sdy += w * boneDy[k]
        }
        val mdx = sdx / wsum; val mdy = sdy / wsum

        // ПОТОЛОК НА СМЕЩЕНИЕ ЗА ПОДШАГ — см. BONE_MAX_STEP.
        //
        // Масштабируется ВЕСЬ набор поправок ОДНИМ множителем, и это принципиально:
        // сумма поправок уже обнулена выше, а умножение нуля на что угодно остаётся
        // нулём. Обрезать поправки по отдельности было бы нельзя — сохранение центра
        // масс, ради которого весь этот код и переписан, сломалось бы сразу.
        var maxD2 = 0.0
        for (k in ids.indices) {
            val dx = boneDx[k] - mdx
            val dy = boneDy[k] - mdy
            val d2 = dx * dx + dy * dy
            if (d2 > maxD2) maxD2 = d2
        }
        var scale = 1.0
        val cap = BONE_MAX_STEP * body.meanLinkLength
        if (maxD2 > cap * cap) {
            scale = cap / sqrt(maxD2)
            boneCapHits++
        }

        for (k in ids.indices) {
            val i = ids[k]
            px[i] += (boneDx[k] - mdx) * scale
            py[i] += (boneDy[k] - mdy) * scale
        }
    }

    /** Сколько раз потолок кости сработал с последнего сброса. Показывается в HUD. */
    private var boneCapHits = 0

    private fun integrate(h: Double) {
        for (i in 0 until n) {
            prevX[i] = px[i]; prevY[i] = py[i]; inContact[i] = false
            if (invMass[i] == 0.0) continue
            vy[i] += GRAVITY * h
            px[i] += vx[i] * h
            py[i] += vy[i] * h
            if (py[i] < GROUND_Y) {
                px[i] += (prevX[i] - px[i]) * GROUND_FRICTION
                py[i] = GROUND_Y
                inContact[i] = true
            }
        }
    }

    private fun updateVelocities(h: Double) {
        for (i in 0 until n) {
            if (invMass[i] == 0.0) { vx[i] = 0.0; vy[i] = 0.0; continue }
            vx[i] = (px[i] - prevX[i]) / h
            vy[i] = (py[i] - prevY[i]) / h
        }
    }

    /** Продольная вязкость: гасит скорость деформации, жёсткое движение не трогает. */
    private fun applyViscosity(h: Double) {
        var k = VISCOSITY * h
        if (k > 0.5) k = 0.5
        for (c in 0 until conCount) {
            val i = conA[c]; val j = conB[c]
            val wi = invMass[i]; val wj = invMass[j]
            val w = wi + wj
            if (w == 0.0) continue
            var nx = px[j] - px[i]
            var ny = py[j] - py[i]
            val len = sqrt(nx * nx + ny * ny)
            if (len < 1e-12) continue
            nx /= len; ny /= len
            val dv = (vx[j] - vx[i]) * nx + (vy[j] - vy[i]) * ny
            val si = k * wi / w; val sj = k * wj / w
            vx[i] += dv * nx * si; vy[i] += dv * ny * si
            vx[j] -= dv * nx * sj; vy[j] -= dv * ny * sj
        }
    }

    /**
     * Анизотропное сопротивление среды на границе тела — то, что и создаёт тягу.
     *
     * Для каждого граничного ребра берётся скорость его середины, из неё выделяется
     * составляющая ВДОЛЬ НОРМАЛИ к ребру, и гасится только она. Тангенциальная остаётся
     * нетронутой: ребро, скользящее вдоль себя, среду не гребёт.
     *
     * Знак нормали не важен: выражение (v·n)·n не меняется при n -> -n, поэтому обходить
     * контур и выяснять, где у тела «наружу», не требуется.
     *
     * Сила пропорциональна ДЛИНЕ ребра: это площадь омываемой поверхности, и без неё
     * мелкие рёбра гребли бы наравне с крупными.
     *
     * Это ВНЕШНЯЯ сила, она осознанно не сохраняет импульс — среда его и уносит.
     */
    private fun applyNormalDrag(h: Double) {
        var kd = FLOW_DECAY * h
        if (kd > 1.0) kd = 1.0

        // --- ЗАПАС СРЕДЫ. Догоняет скорость ЦЕНТРА МАСС, см. flowVX. ---
        //
        // Считается ДО цикла по рёбрам и ровно один раз: это одна степень свободы на
        // организм, а не на ребро. Вращение сюда не попадает — у чистого вращения
        // скорость центра масс равна нулю.
        if (FLOW_ENTRAIN > 0.0 && FLOW_MASS > 0.0) {
            // Скорость центра масс КАЖДОГО организма по отдельности.
            //
            // Раньше здесь было одно среднее по всем частицам мира, и это была прямая
            // ошибка: два тела делили один запас среды, поэтому движение одного толкало
            // другое на любом расстоянии, а тяга у обоих падала — запас следовал за
            // средней скоростью пары, а не за собственной скоростью тела.
            for (o in 0 until organismCount) { comAccX[o] = 0.0; comAccY[o] = 0.0 }
            for (i in 0 until n) {
                val o = organismOf[i]
                comAccX[o] += vx[i]; comAccY[o] += vy[i]
            }

            // Это демпфер между телом и запасом: за шаг относительная скорость падает
            // на kf * (1 + FLOW_MASS). Выше единицы — переброс через ноль, то есть
            // раскачка, поэтому коэффициент здесь и ограничивается. С этим ограничением
            // модель устойчива при ЛЮБОЙ массе среды, и подбирать её можно свободно.
            var kf = FLOW_ENTRAIN * h
            val limit = 0.9 / (1.0 + FLOW_MASS)
            if (kf > limit) kf = limit

            for (o in 0 until organismCount) {
                val comVX = comAccX[o] / organismSize[o]
                val comVY = comAccY[o] / organismSize[o]
                val dfx = (comVX - flowVX[o]) * kf
                val dfy = (comVY - flowVY[o]) * kf
                flowVX[o] += dfx
                flowVY[o] += dfy
                comAccX[o] = dfx      // переиспользуем под плату, чтобы не заводить массив
                comAccY[o] = dfy
                // Рассеяние запаса в объём жидкости: только сток, никогда источник.
                // Без него запас был бы вечным аккумулятором импульса и тело не
                // остановилось бы никогда.
                flowVX[o] -= flowVX[o] * kd
                flowVY[o] -= flowVY[o] * kd
            }

            // Разгон среды телу СТОИТ: импульс FLOW_MASS * dFlow на каждую частицу.
            // Именно эта строка делает обмен честным — тело не может получить от среды
            // больше, чем вложило.
            for (i in 0 until n) {
                val o = organismOf[i]
                vx[i] -= FLOW_MASS * comAccX[o]
                vy[i] -= FLOW_MASS * comAccY[o]
            }
        }

        for (e in 0 until boundCount) {
            val i = boundA[e]; val j = boundB[e]
            val ex = px[j] - px[i]
            val ey = py[j] - py[i]
            val len = sqrt(ex * ex + ey * ey)
            if (len < 1e-12) continue

            val nx = -ey / len
            val ny = ex / len

            // Скорость середины ребра ОТНОСИТЕЛЬНО увлечённой среды: гребёт ребро целиком,
            // а не каждый конец отдельно. Вычитание общего вектора и даёт длинный накат —
            // когда среда догнала корпус, сопротивление его движению обнуляется, а
            // локальные взмахи плавника по-прежнему гребут в полную силу.
            // Запас берётся СВОЕГО организма: у каждого тела он свой, см. flowVX.
            val o = organismOf[i]
            val vmx = (vx[i] + vx[j]) * 0.5 - flowVX[o]
            val vmy = (vy[i] + vy[j]) * 0.5 - flowVY[o]
            val vn = vmx * nx + vmy * ny

            // Линейная плюс квадратичная. Квадратичная сила равна NORMAL_DRAG_Q * vn*|vn|,
            // поэтому в коэффициенте (он делится на vn) остаётся |vn|.
            var k = (NORMAL_DRAG + NORMAL_DRAG_QUADRATIC * abs(vn)) * len * h
            if (k > 0.5) k = 0.5      // выше — переброс скорости через ноль, то есть раскачка

            val dv = -vn * k
            vx[i] += dv * nx; vy[i] += dv * ny
            vx[j] += dv * nx; vy[j] += dv * ny
        }
    }

    /**
     * Гашение отскока от пола: у контактной вершины убирается скорость ВВЕРХ.
     *
     * Это численный эффект, а не физика: контакт зажал позицию, решатель вернул её
     * обратно, а updateVelocities превратил разность позиций в настоящую скорость.
     * При GRAVITY = 0 стадия холостая — тело до пола не доходит.
     */
    private fun applyRestitution() {
        for (i in 0 until n) if (inContact[i] && vy[i] > 0.0) vy[i] *= GROUND_RESTITUTION
    }

    /**
     * Изотропное сопротивление среды. Нормировано на h, поэтому от числа подшагов
     * не зависит. Тягу не создаёт — см. комментарий у MEDIUM_DRAG.
     */
    private fun applyMediumDrag(h: Double) {
        var keep = 1.0 - MEDIUM_DRAG * h
        if (keep < 0.0) keep = 0.0
        for (i in 0 until n) { vx[i] *= keep; vy[i] *= keep }
    }

    private fun simulate() {
        val h = DT / SUBSTEPS
        // Нулевой слот — состояние на НАЧАЛО тика. Промежуточные пишутся ТОЛЬКО когда
        // их кто-то будет читать: в обычном режиме это лишние 242 КБ копирования за
        // тик, вымывающие кэш решателя. См. interpMode.
        val keepSubsteps = interpMode == 2
        histSnap(0)
        histCount = SUBSTEPS + 1
        histHasSubsteps = keepSubsteps
        for (step in 0 until SUBSTEPS) {
            integrate(h)

            // Скобка вокруг ВНУТРЕННИХ стадий: центр масс до и после. Внешние силы
            // (среда, пол, вязкость) идут ниже по скоростям и в скобку не попадают.
            var beforeX = 0.0
            var beforeY = 0.0
            // Только когда тело не держат: при активной тяге посылка «центр масс не
            // должен двигаться» неверна, и поправка даёт растяжение (см. константу).
            val cancel = CANCEL_INTERNAL_DRIFT && dragId < 0
            if (cancel) {
                for (i in 0 until n) { beforeX += px[i]; beforeY += py[i] }
                dragShiftX = 0.0; dragShiftY = 0.0
            }

            // Обход связей меняет направление КАЖДЫЙ подшаг — см. sweepBackwards.
            // Ставится здесь, а не внутри solveConstraints, чтобы фаза шла ровно по
            // подшагам и не зависела от того, сколько раз стадию позвали снаружи.
            val ct = contacts

            sweepBackwards = !sweepBackwards
            solveConstraints(h)
            solveLinkMaxLength()
            solveAreas(h)
            solveBend(h)
            if (bonesRigid) for (b in rigidBones.indices) projectBone(b)

            // ПРЕДЕЛ ДЛИНЫ ПОВТОРНО, УЖЕ ПОСЛЕ КОСТИ.
            //
            // Первый вызов стоит после solveConstraints, но проекция кости идёт ПОЗЖЕ
            // и способна снова растянуть связь сверх предела — она ставит вершины на
            // жёсткую позу, ни на что не оглядываясь. А от этого предела зависит
            // непроницаемость границы: два соседних граничных круга перекрываются,
            // только пока расстояние между ними не больше суммы радиусов. Растянутая
            // костью связь оставляет в мембране щель, и сквозь неё можно воткнуть
            // чужое тело — что и наблюдалось при резком рывке за кость.
            solveLinkMaxLength()

            // КОНТАКТЫ ПОСЛЕДНИМИ СРЕДИ ПОЗИЦИОННЫХ, и это принципиально.
            // projectBone перезаписывает позиции жёсткой позой; поставь контакты
            // раньше — и кость проходила бы сквозь тело, потому что её проекция
            // просто затирала бы расталкивание. Ценой идёт лёгкая нежёсткость кости
            // в момент удара: следующий подшаг возвращает её на место, а при 16
            // подшагах это незаметно.
            //
            // СПИСОК КОНТАКТОВ СТРОИТСЯ ЗДЕСЬ ЖЕ, а не сразу после integrate, и это
            // была настоящая дыра в непроницаемости.
            //
            // Широкая фаза, DDA и CCD раньше работали по позициям СРАЗУ ПОСЛЕ
            // integrate, то есть по чисто баллистическому предсказанию. А дальше
            // solveDrag и projectBone двигали клетки ещё раз, и порой очень далеко:
            // проекция кости жёсткая, рывок мышью за кость даёт огромное смещение.
            // Перекрытия, возникшие ИМЕННО от этого движения, в список не попадали —
            // и solvePositions про них просто не знал. Не «CCD не справился» и не
            // «частицы мягкие»: пары до решателя не доходили вовсе. Замер на рывке за
            // кость показывал 23 таких пары и проникновение на 0.58 порога.
            //
            // prevX/prevY по-прежнему держат начало подшага, поэтому DDA заметает
            // весь настоящий путь клетки за подшаг, включая ту часть, которую добавили
            // перетаскивание и кость. Это ровно то, ради чего свип и делался.
            if (ct != null && contactsOn) {
                ct.prepare(px, py, prevX, prevY, vx, vy)
                ct.solvePositions(px, py, invMass)
            }

            if (cancel) cancelInternalDrift(beforeX, beforeY)

            updateVelocities(h)
            applyDragVelocity(h)
            // Отскок и трение — по скоростям, поэтому только после их восстановления.
            if (ct != null && contactsOn) ct.solveVelocities(vx, vy, invMass, h)
            applyViscosity(h)
            applyNormalDrag(h)
            applyRestitution()
            applyMediumDrag(h)
            clampSpeed()
            if (keepSubsteps || step == SUBSTEPS - 1) histSnap(step + 1)
        }
    }

    /**
     * Один шаг модели: команды мышцам, их активации, потом физика.
     *
     * Вынесено из render() потому, что при ускорении повторять надо ВСЮ тройку, а не
     * только simulate(). Иначе gaitFrame и активации остались бы на частоте кадров,
     * гребок относительно физики замедлился бы в десять раз, и наблюдал бы ты совсем
     * другой режим, чем тот, который мерил стенд.
     */
    private fun stepOnce() {
        updateMuscleTargets()
        updateMuscles(DT)
        simulate()
        simTime += DT
    }

    /**
     * Позиция для отрисовки — ИНТЕРПОЛИРОВАННАЯ, по истории подшагов.
     *
     * ЗАЧЕМ. Физика идёт 30 раз в секунду, экран рисует 60..240. Без интерполяции одно
     * и то же состояние показывалось бы по 2..8 кадров подряд, и движение выглядело бы
     * рваным, хотя сама физика ровная. Это чисто визуальная проблема, и решается она
     * чисто визуально: рисуем не «последнее состояние», а точку между двумя
     * сохранёнными, соответствующую тому, сколько реального времени уже накоплено.
     *
     * ПОЧЕМУ ПО ПОДШАГАМ, А НЕ ПО ГРАНИЦАМ ТИКОВ. За тик тело успевает заметно
     * повернуться и изогнуться, и прямая между началом и концом тика срезает эту дугу.
     * История по подшагам (17 состояний при 16 подшагах) даёт ту же дугу кусочно, и
     * срезание падает во столько же раз. Память тут копеечная: 17 * n * 2 double.
     *
     * ЭТО НЕ ВЛИЯЕТ НА ФИЗИКУ ВООБЩЕ. Интерполяция только читает историю; решатель
     * работает с px/py, как и работал.
     */
    /**
     * Какие два слота истории смешивать и с каким весом. Одна формула на обе оси,
     * иначе x и y однажды разойдутся при правке.
     *
     * Режим 1 берёт только границы тика: слот 0 и последний. Режим 2 идёт по подшагам.
     */
    // -1 значит «истории ещё нет, брать сырые px/py». Важно именно -1, а не 0:
    // до первого prepareLerp() слот 0 заполнен нулями, и выбор мышью на первом кадре
    // целился бы в начало координат.
    private var lerpLo = -1
    private var lerpHi = 0
    private var lerpU = 0.0

    private fun prepareLerp() {
        if (interpMode == 0 || histCount < 2) { lerpLo = -1; return }
        if (interpMode == 1 || !histHasSubsteps) {
            lerpLo = 0
            lerpHi = histCount - 1
            lerpU = renderAlpha
            return
        }
        val f = renderAlpha * (histCount - 1)
        var a = f.toInt()
        if (a > histCount - 2) a = histCount - 2
        lerpLo = a
        lerpHi = a + 1
        lerpU = f - a
    }

    private fun fx(i: Int): Float =
        if (lerpLo < 0) px[i].toFloat()
        else (histX[lerpLo][i] + (histX[lerpHi][i] - histX[lerpLo][i]) * lerpU).toFloat()

    private fun fy(i: Int): Float =
        if (lerpLo < 0) py[i].toFloat()
        else (histY[lerpLo][i] + (histY[lerpHi][i] - histY[lerpLo][i]) * lerpU).toFloat()

    /** Снимок состояния в слот истории. Вызывается из simulate(). */
    private fun histSnap(slot: Int) {
        val hx = histX[slot]; val hy = histY[slot]
        for (i in 0 until n) { hx[i] = px[i]; hy[i] = py[i] }
    }

    private fun countInverted() {
        var c = 0
        for (t in 0 until body.triCount) {
            val i0 = body.triA[t]; val i1 = body.triB[t]; val i2 = body.triC[t]
            val area2 = (px[i1] - px[i0]) * (py[i2] - py[i0]) - (py[i1] - py[i0]) * (px[i2] - px[i0])
            val inv = area2 < 0f
            triInverted[t] = inv
            if (inv) c++
        }
        invertedNow = c
        if (c > invertedPeak) invertedPeak = c
    }

    /**
     * Кто сейчас командует мышцами. Источников три и они складываются по ИЛИ:
     * наведение мышью, удержание цифровой клавиши и автоматический гребок.
     */
    private fun updateMuscleTargets() {
        muscleTarget.fill(0.0)

        // Проверка верхней границы не лишняя: тело может не иметь мышц вовсе
        // (у текущей выгрузки muscle = 0), и тогда массив пуст.
        if (hoveredMuscle in muscleTarget.indices) muscleTarget[hoveredMuscle] = 1.0

        // Цифры 1..9 — держать соответствующую мышцу сокращённой.
        val keys = minOf(9, muscleTarget.size)
        for (m in 0 until keys) {
            if (Gdx.input.isKeyPressed(Input.Keys.NUM_1 + m)) muscleTarget[m] = 1.0
        }
        // 0 — все сразу.
        if (Gdx.input.isKeyPressed(Input.Keys.NUM_0)) muscleTarget.fill(1.0)

        // Автоматический гребок. Доля рабочей фазы — GAIT_DUTY, минимум один кадр:
        // при коротком периоде округление вниз может дать ноль, и гребка не будет вовсе.
        if (gait) {
            gaitFrame++
            val duty = (GAIT_PERIOD * GAIT_DUTY).toInt().coerceAtLeast(1)
            if (gaitFrame % GAIT_PERIOD < duty) muscleTarget.fill(1.0)
        }
    }

    private fun updateMuscles(dt: Double) {
        for (m in muscleActivation.indices) {
            val target = muscleTarget[m]
            // Сокращение и распрямление идут с РАЗНОЙ скоростью — см. константы.
            val rate = if (target > muscleActivation[m]) MUSCLE_RATE_CONTRACT else MUSCLE_RATE_RELAX
            var k = rate * dt
            if (k > 1.0) k = 1.0
            muscleActivation[m] += (target - muscleActivation[m]) * k
        }
    }

