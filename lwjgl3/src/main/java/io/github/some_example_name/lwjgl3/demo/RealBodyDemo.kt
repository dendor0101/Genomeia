        /**
         * КВАДРАТИЧНАЯ часть сопротивления: сила растёт как v*|v|, а не как v.
         *
         * Два механизма тяги здесь РАЗНЫЕ и складываются.
         *
         * Линейная работает по Пёрселлу — за счёт СМЕНЫ ОРИЕНТАЦИИ поверхности за цикл.
