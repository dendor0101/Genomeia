         * до секунды. Если правило «не выпрямился за N тиков — рвём ткань» будет
         * настроено жёстко, этот порог придётся поднимать вместе с потолком.
         */
        private const val AREA_MAX_STEP = 0.2

        /**
         * Плавный переход между мягкой и жёсткой ветками площади вместо ступеньки.
         *
         * Лечит ДРЕБЕЗГ. Ступенька означает разрыв жёсткости в 55 раз ровно на нулевой
         * площади, и треугольник, болтающийся около неё, каждый подшаг попадает то в
         * одну ветку, то в другую. Замер числа перещёлкиваний знака площади за
         * распрямление: 895 со ступенькой против 405 с плавным переходом при том же
         * потолке 0.2, то есть вдвое меньше. Заодно распрямление идёт быстрее (12 кадров
         * против 13) — ткань не тратит время на дрожь около нуля.
         *
         * Форма перехода квадратичная по доле площади: t = clamp(area2/restArea2, 0, 1),
         * alpha = alphaInv + (alpha - alphaInv) * t^2. Квадрат, а не линия, чтобы
         * жёсткость нарастала не сразу и почти вырожденные треугольники (площадь близка
         * к нулю, но ещё положительна) тоже получали защиту — так они реже успевают
         * вывернуться вообще.
         */
        private const val AREA_SMOOTH_RAMP = true

        /**
         * ИЗГИБ ГРАНИЧНОГО КОНТУРА — податливости, которые перебирает клавиша E.
         * -1 — стадия выключена. ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНА, см. почему ниже.
         *
         * ЗАЧЕМ. Единственное дешёвое, что вообще способно сделать дорогим заворот
         * ткани, при котором НИ ОДИН треугольник не вывернулся. Знаковая площадь —
         * признак ЛОКАЛЬНЫЙ: сложенный пополам лист нигде не выворачивается наизнанку,
         * каждый треугольник в нём положителен. Замер на этом теле: заворот при нулевом
         * числе вывернутых, и искажение формы не уходит, а РАСТЁТ — 1.09 клетки сразу
         * после скручивания и 2.79 через две секунды.
         *
         * КАК СЧИТАЕТСЯ, и это дешевле, чем кажется. Угол при вершине считать не нужно:
         * он однозначно связан с расстоянием между её двумя соседями, потому что стороны
         * уже держат обычные связи. Значит хватает ограничения РАССТОЯНИЯ «через одну»
         * вдоль границы — тот же решатель, ни одной новой формулы, никаких acos.
         *
         * ПОЧЕМУ ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ. Работает как задумано, но стоит ТЯГИ, и много.
         * Замер (стенд FoldRecovery, тело 947 клеток):
         *
         *      податливость   искажение через 2 с   тяга за цикл
         *      выключено             2.788             0.06502
         *      1e-3                  2.846             0.05586    -14%
         *      1e-4                  1.841             0.03400    -48%
         *      1e-5                  0.796             0.01768    -73%
         *
         * Причина прямая и неустранимая в лоб: мышца плывёт тем, что ИЗГИБАЕТ тело, а
         * тяга берётся с нормальной скорости граничных рёбер. Ограничение изгиба
         * сопротивляется ровно этому движению — это не побочный эффект, это одно и то же
         * движение. Сильнее всего бьёт по кончику хвоста, где кривизна меняется больше
         * всего и где гребок самый цепкий.
         *
         * ПРЕЖДЕ ЧЕМ ВКЛЮЧАТЬ НАСОВСЕМ — переподобрать параметры плавания: нынешние
         * искал SwimTuner без этой стадии, и новая жёсткость смещает весь оптимум.
         * bendCompliance уже заведена геном, диапазон включает «почти выключено».
         * И делать это имеет смысл уже вместе с пограничными коллизиями, иначе
         * подбирать придётся дважды.
         */
        private val BEND_LEVELS = doubleArrayOf(-1.0, 1.0e-3, 1.0e-4, 1.0e-5, 1.0e-6, 1.0e-7, 0.0)

        /**
         * ОТКУДА ВЗЯТЫ ЗНАЧЕНИЯ ГИДРОДИНАМИКИ И МЫШЦ (ниже и до конца companion).
