/**
 * СТЕНД ФИЗИКИ ДЛЯ GENOMEIA: XPBD + shape matching на реальной топологии генома.
 *
 * Тело грузится из body-export.txt (выгружает BodyExport в модуле core при сохранении
 * генома в редакторе; разбирает и достраивает BodyFile рядом). Ничего синтетического:
 * связи, кости и мышцы такие, какие вырастил геном.
 *
 * =====================================================================================
 *  ЭТОТ ФАЙЛ — ОБРАЗЕЦ ДЛЯ ПЕРЕНОСА В ОСНОВНУЮ СИМУЛЯЦИЮ.
 *  Ниже всё, что нужно, чтобы повторить его в движке, не читая историю разработки.
 * =====================================================================================
 *
 * ЧТО ЗДЕСЬ РЕАЛИЗОВАНО
 * ---------------------
 *   1. Ограничение расстояния (XPBD)        - заменяет пружины Гука из processLink
 *   2. Ограничение знаковой площади (XPBD)  - прямой аналог processTriangles
 *   3. Shape matching для костей, alpha = 1 - новое, аналога в движке нет
 *   4. Мышцы через длину покоя              - аналог degreeOfShortening
 *   5. Анизотропное сопротивление среды     - обобщение клетки Fin на всю поверхность
 *   6. Продольная вязкость ткани            - новое
 *
 * ПОРЯДОК ВНУТРИ ПОДШАГА (см. simulate) - МЕНЯТЬ НЕЛЬЗЯ
 * -----------------------------------------------------
 *      integrate            позиции += v * h, гравитация, пол
 *      solveConstraints     расстояния
 *      solveAreas           знаковая площадь
 *      projectBone          ПОСЛЕДНЯЯ из позиционных: всё после неё нарушит жёсткость
 *      updateVelocities     v = (x - prevX) / h
 *      applyDragVelocity    тяга мыши — СКОРОСТЬЮ, после позиционных (в движке не нужна)
 *      applyViscosity       \
 *      applyNormalDrag       |  по СКОРОСТЯМ и только после их восстановления
 *      applyRestitution      |
 *      applyMediumDrag      /
 *
 * Почему проекция кости последняя: она ставит вершины на жёсткую цель ровно, и любая
 * позиционная поправка после неё эту жёсткость ломает буквально. Поэтому и пол
 * обрабатывается в integrate, а не после решателя.
 *
 * Почему диссипация после восстановления скоростей: до него скоростей ещё нет,
 * updateVelocities перезапишет их из позиций и затрёт любую правку.
 *
 * ЧЕМ ЭТО ВСЁ ПРОВЕРЯЕТСЯ
 * -----------------------
 * Каждое число в комментариях ниже получено одним из четырёх стендов, и любое из них
 * можно перепроверить, а не принимать на веру:
 *
 *      gradlew :lwjgl3:physicsAudit    сохранение импульса и момента по стадиям
 *                                      решателя; 8 тестов с опорными числами
 *      gradlew :lwjgl3:swimTune        эволюционный подбор параметров плавания
 *                                      (скорость против блуждания)
 *      gradlew :lwjgl3:solverBench     цена double на полном конвейере при разном
 *                                      размере арены
 *      gradlew :lwjgl3:precisionScale  точность против масштаба мира и способа
 *                                      хранения позиций
 *
 * SwimTuner держит СВОЮ копию конвейера (константы здесь `const val`, в рантайме их
 * не поменять) и первым делом сверяет её с этим файлом ПОБИТОВО. Если правите решатель,
 * а сверка перестала сходиться — значит копия отстала, и подбор оптимизирует не то,
 * что поедет.
 *
 * СООТВЕТСТВИЕ СУЩНОСТЯМ ДВИЖКА
 * -----------------------------
 *      px, py, vx, vy           -> ParticleEntity.x/y/vx/vy, но ТИП МЕНЯЕТСЯ на double
 *                                  (см. первый пункт списка ниже). Заодно меняются
 *                                  prevX/prevY и всё, что участвует в накоплении позиции.
 *                                  Топология, цвета и отрисовка остаются во float:
 *                                  ShapeRenderer всё равно принимает float, конверсия
 *                                  одна на вершину в кадре.
 *      invMass                  -> в движке неявная единица; при переносе завести массив
 *      conA/conB/conRest        -> LinkEntity + linksNaturalLength
 *      body.triA/B/C, restArea2 -> BakedLayout.triangleSlots / triangleRestArea2
 *      boneOf, rigidBones       -> НОВОЕ: запечь в BakedLayout смещения позы покоя r0
 *                                  и принадлежность слота кости
 *      muscleOf, muscleScale    -> cellEntity.degreeOfShortening
 *      boundA/boundB            -> cellEntity.isOnEdge (уже есть)
 *      h = DT / SUBSTEPS        -> SIM_STEP / SUBSTEPS
 *
 * ЧТО ОБЯЗАТЕЛЬНО ЗАЛОЖИТЬ ПРИ ПЕРЕНОСЕ (проверено замерами, детали у констант)
 * ----------------------------------------------------------------------------
 *  - ПОЗИЦИИ И СКОРОСТИ В DOUBLE. Это первый пункт, потому что от него зависят
 *    остальные: во float часть описанных ниже починок просто не имеет смысла.
 *
 *    Замер (стенд PrecisionScale, полный внутренний шаг, ВНЕШНИХ СИЛ НЕТ, старт из
 *    покоя, 4000 подшагов ~ 17 секунд). Импульс обязан остаться ровно нулём, поэтому
 *    любое ненулевое значение здесь — это утечка и ни с чем не путается:
 *
 *        хранение                          |P|        сдвиг ЦМ     время
 *        float, мир 1024                   616        3.755        1.00x
 *        float, локальные координаты       0.106      5.19e-04     1.00x
 *        float + компенсация Кэхэна        2.81e-04   2.79e-07     1.43x
 *        double                            1.56e-07   1.47e-09     1.16x
 *
 *    Первая строка и есть приговор float: сдвиг 3.755 мировых единиц, то есть почти
 *    ЧЕТЫРЕ КЛЕТКИ за 17 секунд, при полном отсутствии внешних сил. Организм уезжает
 *    сам по себе, и это ровно то «блуждание», за которым в стенде и охотились.
 *
 *    ЦЕНА: 14..16% на полном конвейере. Замерено отдельно (стенд SolverBench) при
 *    разном размере арены: 1.19x на одном организме, 1.14x на 16, 1.15x на 256,
 *    1.23x на 1024 (там рабочий набор вываливается из L3 и счёт идёт по байтам).
 *    SIMD при этом не теряется: циклы идут через косвенную адресацию conA/conB,
 *    а такое не векторизуется ни во float, ни в double.
 *
 *    ЭТИ 14..16% ИЗМЕРЕНЫ НА ДЕСКТОПЕ. НА ANDROID ПЕРЕМЕРИТЬ ОБЯЗАТЕЛЬНО, до того как
 *    решение станет необратимым. Это не перестраховка: double УДВАИВАЕТ рабочий набор,
 *    а у мобильных ровно те три особенности, из-за которых лишний трафик в память там
 *    стоит дороже:
 *      * последний уровень кэша меньше и ДЕЛИТСЯ С GPU (SLC 4..8 МБ против 16..32 МБ
 *        L3 на десктопе). Заметьте, L1 при этом НЕ меньше — у Apple с A14 он 128 КБ,
 *        то есть больше типичных 32..48 КБ на x86. Дело не в «кэши меньше», а именно
 *        в последнем уровне и в том, что за него конкурирует отрисовка;
 *      * LPDDR заметно уже десктопной памяти, а предвыборка слабее и меньше промахов
 *        держится в полёте — неаккуратный доступ там прощается хуже;
 *      * обращение к DRAM дорого по ЭНЕРГИИ, а устойчивая производительность на
 *        телефоне ограничена троттлингом. Лишний трафик бьёт не только по мгновенному
 *        FPS, но и по тому, как долго он держится.
 *
 *    КАК МЕРИТЬ. Стенд SolverBench для этого и написан: он гоняет один и тот же
 *    конвейер во float и в double при аренах от 1 до 1024 организмов и печатает объём
 *    горячего состояния в КБ. Смотреть надо не на одно число, а на то, ГДЕ отношение
 *    double/float начинает расти — это и есть точка, где набор перестал помещаться.
 *    На десктопе она видна на 1024 копиях (1.23x против 1.14x в середине); на телефоне
 *    она наступит раньше и, возможно, будет круче.
 *
 *    Задачу придётся завести в модуле android — через :lwjgl3 она не запустится, это
 *    не одна команда. Замер того стоит: если на устройстве выйдет не 15%, а, скажем,
 *    40%, разговор про смешанную точность и фиксированную точку надо открывать заново.
 *    Тогда пригодится, что фиксированная точка ИЗМЕРЕНА: ровно нулевая утечка при
 *    2.93x на десктопе (см. ниже). При подорожавшем double разрыв сократится, и та
 *    таблица будет выглядеть иначе, чем сейчас.
 *
 *    ЧЕГО ДЕЛАТЬ НЕ НАДО — три варианта, каждый проверен и каждый хуже:
 *      * СМЕШИВАТЬ ТОЧНОСТЬ (позиции double, скорости float): экономии НЕТ вовсе,
 *        1.15x против 1.14x, а утечка в 55 раз хуже. Дорогая часть шага — разбросанный
 *        доступ по позициям, он остаётся double в любом случае, а преобразования
 *        float<->double на каждую частицу съедают сэкономленную ширину.
 *      * ПРИЁМЫ ПОВЫШЕННОЙ ТОЧНОСТИ НА FLOAT (компенсированное суммирование и прочая
 *        эмуляция двойной мантиссы): 1.43x против 1.16x у double, памяти столько же
 *        (два float на координату — те же 8 байт), а точность всё равно в 1800 раз
 *        хуже. Причина общая: на x86-64 double-сложение и умножение имеют ТУ ЖЕ
 *        латентность и пропускную способность, что float, поэтому любая эмуляция
 *        делает строго больше работы, чем просто double. Такие приёмы придуманы для
 *        видеокарт, где double идёт в 32 раза медленнее.
 *      * ФИКСИРОВАННАЯ ТОЧКА int64: утечка получается РОВНО ноль (сложение целых
 *        точно, `p[i] += d; p[j] -= d` сокращается бит в бит), но 2.93x по времени
 *        из-за преобразований int<->float на каждую связь. Красиво и не окупается.
 *
 *    ХРАНИТЬ КООРДИНАТЫ УЖЕ В BYTE/SHORT НЕЛЬЗЯ в принципе: поправка к позиции за
 *    подшаг порядка 3e-4 мировых единиц, а байт на организм размером 32 единицы даёт
 *    разрешение 0.125 — поправка округлится в ноль и тело замрёт. Нужно ~24 бита,
 *    то есть мантисса float это МИНИМУМ, а не запас, который можно ужать. Для
 *    КОНСТАНТ (смещения позы покоя r0 в shape matching) короткие типы годятся: они
 *    не накапливаются, квантование даёт разовую ошибку формы.
 *
 *    ЛОКАЛЬНЫЕ КООРДИНАТЫ НА ОРГАНИЗМ при double для точности НЕ нужны: дают 8% на
 *    величине, которая и так на девять порядков ниже наблюдаемого. Делать их стоит,
 *    только если они нужны архитектурно — под арены, отсечение, адресацию. А вот если
 *    когда-нибудь понадобится вернуться к float, они становятся ОБЯЗАТЕЛЬНЫМ первым
 *    шагом: 616 против 0.106, разница в 5800 раз.
 *
 *    И ЧЕГО ТОЧНО НЕ БЫВАЕТ: «нормализовать мир, чтобы влезло точнее». Пересчёт
 *    координат из 0..1024 в 0..1 даёт утечку 1.228e-03 — до последней цифры ту же,
 *    что и без пересчёта. У float точность ОТНОСИТЕЛЬНАЯ, 24 бита мантиссы независимо
 *    от порядка, и умножение всего на степень двойки сдвигает только экспоненты.
 *
 *    Про детерминизм, раз он обычно всплывает рядом: double его НЕ добавляет. На JVM
 *    с Java 17 вся плавающая арифметика строго IEEE-754, и float уже побитово
 *    воспроизводим на любой платформе. Double добавляет точность, а не повторяемость.
 *    Отдельно: Math.sin/cos/exp/pow побитово НЕ переносимы (допускается 1..2 ulp),
 *    переносим только StrictMath; sqrt округляется точно. В горячем решателе сейчас
 *    только sqrt. И порядок редукции между потоками и аренами — самостоятельный
 *    источник недетерминизма, его не чинит ни float, ни double.
 *
 *  - ВСЯ ТОПОЛОГИЯ ЗДЕСЬ СТРОИТСЯ ОДИН РАЗ. В ДВИЖКЕ ОНА ЖИВАЯ.
 *
 *    Это самое крупное расхождение стенда с движком, и его легко упустить, потому что
 *    в стенде оно нигде не мешает. Тело здесь грузится готовым и не меняется никогда.
 *    В движке организм РАСТЁТ от одной клетки до полного тела и РАЗРУШАЕТСЯ по ходу:
 *    гибнет клетка, рвётся связь, отваливается кусок по правилу «загнулся дольше N
 *    тиков». Значит всё, что buildFromFile считает однократно, обязано уметь
 *    обновляться ИНКРЕМЕНТАЛЬНО, а не пересчитываться целиком на каждое изменение.
 *
 *    Что как ведёт себя при изменении:
 *
 *      треугольники      только ДОБАВЛЯЮТСЯ при росте: новая клетка образует их со
 *                        своими соседями. Локально и дёшево. При гибели клетки —
 *                        удалить те, что её содержат.
 *      граница           меняется ЛОКАЛЬНО: ребро перестаёт быть граничным, когда у
 *                        него появляется второй треугольник, и наоборот. Полный
 *                        пересчёт стоит O(треугольников), инкрементальный — O(соседей).
 *      пары изгиба       выводятся из границы, поэтому ровно то же самое.
 *      кластеры костей   связные компоненты. Рост может СЛИТЬ два кластера — это
 *      и мышц            дёшево, union-find. А вот удаление может РАЗБИТЬ кластер на
 *                        два, и вот это дорого: придётся пересчитывать компоненту
 *                        целиком. Зато только её.
 *      поза покоя r0     привязана к центроиду кластера, значит при любом изменении
 *                        состава кластера пересчитывается — но опять же только для
 *                        затронутого.
 *      RCM-порядок       В движке клетка и связь вставляются в арену СРАЗУ на своё
 *                        место по RCM, поэтому порядок не деградирует вообще —
 *                        пересортировка не нужна ни изредка, ни когда-либо.
 *
 *                        Внимания требует не порядок, а ПЕРЕСЧЁТ ИНДЕКСОВ: вставка в
 *                        середину сдвигает всё, что на клетки ссылается. Забытый массив
 *                        не падает, а молча начинает указывать на чужую клетку, и ищется
 *                        такое потом долго. В стенде на клетки ссылаются:
 *
 *                          conA, conB              концы связей
 *                          conMuscle               мышца связи (индекс кластера)
 *                          triA, triB, triC        вершины треугольников
 *                          triMuscle               мышца треугольника
 *                          boundA, boundB          граничные рёбра
 *                          bendA, bendB            пары изгиба контура
 *                          rigidBones[b][k]        состав костных кластеров
 *                          boneRestQx/Qy[b][k]     поза покоя, ПАРАЛЛЕЛЬНО rigidBones
 *                          boneOf, muscleOf        обратная ссылка клетка -> кластер
 *
 *                        Отдельно про предпоследнюю строку: boneRestQ идёт параллельно
 *                        rigidBones по одному и тому же k. Переставить состав кластера
 *                        и не переставить позу покоя — значит тихо приписать вершинам
 *                        чужие смещения, и кость начнёт тянуть тело в сторону. Эти два
 *                        массива обязаны двигаться только вместе.
 *
 *                        Что при этом всё же портится — ПЛОТНОСТЬ, а не порядок: окна от
 *                        погибших клеток. Они ломают не локальность, а заполнение
 *                        кэш-линии: в неё влезает 8 double, и если три мёртвые, 37%
 *                        линии загружено впустую. Лечится уплотнением, которое порядок
 *                        сохраняет. Если окна используются как запас под вставку, это
 *                        осознанный размен, и вопрос только в том, сколько запаса
 *                        держать, — величина измеримая.
 *
 *    ОТДЕЛЬНАЯ ЛОВУШКА — МАССЫ. Здесь они нормированы на среднюю по телу (см.
 *    buildMasses), и это правильно для стенда: константы не зависят от того, клетки
 *    какого размера сохранил редактор. Но в движке добавление клетки МЕНЯЕТ СРЕДНЮЮ,
 *    то есть пересчитывает массы ВСЕМ частицам тела разом — а это не локальная правка
 *    и вдобавок незаметно двигает физику при каждом росте. В движке нормировку надо
 *    брать не по телу, а глобальную и постоянную: например от эталонного радиуса
 *    клетки, а не от текущего среднего.
 *
 *    И последнее: любое изменение топологии сбрасывает состояние сна острова и
 *    инвалидирует построенную широкую фазу. Разбудить и перестроить — часть той же
 *    операции, иначе organism проснётся уже сломанным.
 *
 *  - ИНТЕРПОЛЯЦИЯ ОТРИСОВКИ: ДВА СНИМКА НА ТИК В ОБЫЧНОЙ ИГРЕ, ПО ПОДШАГАМ — ТОЛЬКО
 *    НА СИЛЬНОМ ЗАМЕДЛЕНИИ. Это не «лучше и хуже», а два разных режима.
 *
 *    Два снимка (начало и конец тика) — то, что нужно почти всегда. В шейдер уходят
 *    prev и current, alpha = accumulator / DT идёт юниформой, истории хранить не надо.
 *    Хорда вместо дуги врёт тем сильнее, чем больше тело поворачивается за тик, а при
 *    верхней границе скорости 4 и 30 UPS за тик проходится 0.13 при клетке 1 — срезать
 *    нечего.
 *
 *    По подшагам начинает окупаться на ЗАМЕДЛЕНИИ. При timeScale около 0.05 accumulator
 *    ползёт в двадцать раз медленнее, renderAlpha подолгу держится далеко от границ, и
 *    прямая через весь тик становится видна. Семнадцать состояний дают ту же дугу
 *    кусочно, и тело едет плавно.
 *
 *    НО НА ОБЫЧНОЙ СКОРОСТИ ЭТОТ ЖЕ РЕЖИМ ВРЕДЕН: он показывает пилу внутри тика.
 *    Всё, что бьётся с частотой подшагов — тяга мышью против проекции кости, контакты,
 *    — на границах тика в выборку не попадает, а по подшагам видно каждый зуб. То есть
 *    режим не «точнее», он показывает другое.
 *
 *    ПРАКТИЧЕСКОЕ ПРАВИЛО: включать историю подшагов, когда timeScale ниже примерно
 *    0.25, и выключать выше. Цена платится только пока замедление активно, а в
 *    замедлении кадров и так с избытком. В стенде это клавиша I, в движке логичнее
 *    привязать к самому timeScale.
 *
 *    И ещё: выбор мышью обязан идти по НАРИСОВАННЫМ позициям, а не по сырым. На
 *    обычной скорости разницы нет, а на замедлении подсветка уезжает от клетки, в
 *    которую целишься, — для отладки поведения это критично. См. nearestParticle().
 *
 *  - ОБЯЗАТЕЛЬНО ЗАВЕСТИ ПРАВИЛО «НЕ РАСПРЯМИЛСЯ ЗА N ТИКОВ — РВЁМ ТКАНЬ».
 *    Это не украшение и не геймплейная вольность, а ЗАКРЫТИЕ ДЫРЫ, которую физика
 *    закрыть не может в принципе.
 *
 *    ПОЧЕМУ НЕ МОЖЕТ. Знаковая площадь — признак ЛОКАЛЬНЫЙ. Лист, сложенный пополам,
 *    нигде не выворачивается наизнанку: каждый треугольник в нём положителен, хотя
 *    ткань лежит сама на себе. Замерено на настоящем теле: заворот, при котором
 *    вывернутых треугольников НОЛЬ, и искажение формы не уходит, а РАСТЁТ — 1.09
 *    клетки сразу после скручивания и 2.79 через две секунды. Ужесточение ветки для
 *    вывернутых тут бесполезно: ловить нечего, ловилка смотрит не туда.
 *
 *    ЧТО ЭТО ЗНАЧИТ ДЛЯ ТРИГГЕРА. Считать одни вывернутые треугольники НЕДОСТАТОЧНО —
 *    описанный случай так не поймать. Нужен ещё признак ухода ФОРМЫ от позы покоя:
 *    например, среднеквадратичное отклонение позиций от позы покоя после снятия
 *    поворота и сдвига (это уже считает shape matching для костей, для мягкой ткани
 *    формула та же). Заворот виден по нему сразу, независимо от знаков площадей.
 *
 *    ПОЧЕМУ ИМЕННО «ЗА N ТИКОВ», А НЕ ПО ФАКТУ. Кратковременные вывороты при сильном
 *    сокращении мышцы — норма, они расходятся сами: складка в 75% тела уходит в ноль
 *    за 0.4 секунды. Рвать по факту выворота означало бы рвать здоровую ткань каждый
 *    гребок.
 *
 *    КАК КАЛИБРОВАТЬ N. Порог обязан быть заметно больше времени честного
 *    распрямления, а оно напрямую зависит от AREA_MAX_STEP: при 0.2 складка уходит за
 *    12 кадров, при 0.05 — за 147. Меняете потолок — пересчитывайте порог, иначе
 *    поведение молча превратится в «рвём всё подряд». Замеры — стенд FoldRecovery.
 *  - ПОДАТЛИВОСТЬ ПЛОЩАДИ РАЗДЕЛИТЬ: мягкая обычным треугольникам, НУЛЕВАЯ вывернутым.
 *    Без этого сложенная ткань застревает сама в себе и не расходится никогда: после
 *    складывания половины тела остаётся 1..2 вывернутых треугольника, и за 35 секунд
 *    они не уходят. С разделением — ноль за две секунды. Заодно при удержании мышцы
 *    вывернутых становится 0 вместо 18, а вращение падает в 30 раз. Обоснование не
 *    «так работает», а по смыслу податливости: она фильтрует шум float РЯДОМ С
 *    РАВНОВЕСИЕМ, а вывернутый треугольник от равновесия бесконечно далеко.
 *    Детали и оговорка — у AREA_COMPLIANCE_INVERTED.
 *  - НАПРАВЛЕНИЕ ОБХОДА СВЯЗЕЙ ЧЕРЕДОВАТЬ КАЖДЫЙ ПОДШАГ (симметричный Гаусс-Зейдель).
 *    Обход только вперёд даёт L = +4.43, только назад L = -4.40 — знак переворачивается
 *    вместе с порядком, значит дело в порядке, а не в физике. Чередование: L = +0.081,
 *    в 54 раза меньше. Стоит ровно ноль, цикл тот же. Подробности у sweepBackwards.
 *    Для движка это важно вдвойне: там порядок связей задаёт RCM-сортировка и разбиение
 *    по аренам, то есть тот же самый рычаг работает сам по себе и незаметно.
 *  - SOFT_COMPLIANCE НИКОГДА не ноль. Ноль усиливает шум float32 в 1/h раз и
 *    раскручивает организм при сокращении мышцы: момент -896 против +12. Это общее
 *    свойство XPBD на float, а не особенность стенда.
 *  - AREA_COMPLIANCE ТОЖЕ НИКОГДА не ноль, и по той же причине. У площади утечка не
 *    линейная, а УГЛОВАЯ: плечо у градиента площади не нулевое, и невязка уходит в
 *    раскрутку тела. Величина своя, в триста раз меньше: сравнивать надо не с
 *    SOFT_COMPLIANCE, а с суммой w*|grad|^2 своей стадии.
 *  - SHAPE MATCHING СЧИТАТЬ В ЛОКАЛЬНЫХ КООРДИНАТАХ И ОБНУЛЯТЬ СУММУ ПОПРАВКИ.
 *    Это оказалось ГЛАВНЫМ источником паразитного дрейфа во всём стенде — сильнее
 *    ограничений расстояния и площади в тысячу раз. Причина не физическая:
 *    вычитание мировой координаты (1.55) из мировой координаты даёт смещение (0.05)
 *    с относительной ошибкой 2e-6, и сумма w*q, обязанная быть нулём, ею и оказывается.
 *    Дальше updateVelocities умножает это на 1/h. Подробности и три лекарства — в
 *    комментарии projectBone. В движке это тем важнее, чем ДАЛЬШЕ организм от начала
 *    координат: ошибка растёт пропорционально абсолютной координате. Замерено: на
 *    координате 1024 утечка в 280 раз больше, чем на 1.55, где стоит стенд.
 *  - ПАМЯТЬ СРЕДЫ ХРАНИТЬ ВЕКТОРОМ В МИРОВЫХ ОСЯХ, а не скаляром вдоль нормали ребра.
 *    Скаляр в поворачивающейся рамке возит запасённый импульс среды за телом бесплатно:
 *    на чистом повороте тела он выдаёт 2.35 единицы скорости из ниоткуда. И общий запас
 *    это НЕ лечит, если заряжать его от рёбер: помогает только зарядка от скорости
 *    ЦЕНТРА МАСС, у которой вращение обращается в ноль тождественно. См. flowVX.
 *  - Площадь покоя треугольника ОБЯЗАНА масштабироваться вместе с длинами при
 *    сокращении мышцы, квадратично (s^2). Сейчас в движке processLink меняет
 *    linksNaturalLength, а restArea2 остаётся - с жёстким ограничением площади
 *    это запрёт ткань намертво.
 *  - Число подшагов считается, а не подбирается:
 *        SUBSTEPS >= v_max * dt / (0.5 * характерное расстояние между клетками)
 *    Нарушение даёт необратимое смятие тела при ударе.
 *  - Кость из одной или двух клеток жёстким телом быть не может: у точки нет ориентации.
 *    В тестовом теле таких 96 из 102 кластеров - это вопрос к геному, а не к физике.
 *  - Кость и мышца - СВЯЗНЫЕ КОМПОНЕНТЫ одноимённых клеток, а не прямоугольники.
 *    Два отдельных костных отростка обязаны быть двумя жёсткими телами, иначе одна
 *    проекция свяжет их намертво и организм не согнётся в этом месте.
 *  - Внутри кости связи и треугольники НЕ создаются: проекция всё равно перезапишет
 *    результат. Кость выходит дешевле мягкой ткани, а не дороже.
 *  - Изотропное сопротивление среды тяги не создаёт НИКОГДА, сколько его ни поднимай.
 *    Плавание даёт только анизотропия: гасить нормальную составляющую и не трогать
 *    тангенциальную.
 *
 * ЧЕГО ЗДЕСЬ НЕТ (и что в движке уже есть или ещё понадобится)
 * -----------------------------------------------------------
 *  - самоконтакт: тело свободно проходит сквозь себя. В движке это закрывает repulse.
 *  - разрыв связей: аналога linkMaxLength2 нет.
 *  - многопоточность: один организм, один поток. В движке фаза связей уже разложена
 *    по аренам, и подшаги укладываются ВНУТРЬ рабочего элемента - лишних барьеров нет.
 *  - ограничение изгиба ОБЪЁМНОЕ: реализовано в SoftBodyWithBoneDemo, выключено,
 *    польза не подтверждена (на ударе делает хуже). Это НЕ то же самое, что изгиб
 *    контура ниже.
 *  - ограничение изгиба ГРАНИЧНОГО КОНТУРА: единственное дешёвое, что вообще способно
 *    сделать заворот без выворота дорогим. Написано и замерено в SwimSolver
 *    (Topology.bendA, solveBend, параметр bendCompliance), здесь НЕ реализовано и по
 *    умолчанию выключено — поэтому демо оно сейчас никак не трогает.
 *
 *    Реализация дешевле, чем кажется. Угол при вершине считать не нужно: он однозначно
 *    связан с расстоянием между её двумя соседями, потому что стороны уже держат связи.
 *    Значит хватает обычного ограничения РАССТОЯНИЯ «через одну» вдоль границы — тот же
 *    решатель, ни одной новой формулы, никаких acos. Контур обходить по порядку тоже не
 *    надо: вершина ровно с двумя граничными рёбрами лежит на гладком участке, её соседи
 *    и дают пару, развилки пропускаются. На теле 947 клеток это 190 пар, +7% к связям.
 *
 *    ПОЧЕМУ НЕ ВКЛЮЧЕНО. Работает как задумано (искажение за 2 секунды 0.80 против 2.79
 *    без него), но стоит ТЯГИ, и много: при податливости 1e-5 минус 73%, при 1e-4 минус
 *    48%. Причина прямая — мышца плывёт тем, что изгибает тело, а тяга берётся с
 *    нормальной скорости граничных рёбер; ограничение изгиба сопротивляется ровно этому
 *    движению. Это не побочный эффект, это одно и то же движение.
 *
 *    Прежде чем включать, ПЕРЕПОДБЕРИТЕ параметры плавания: нынешние искал SwimTuner без
 *    этой стадии, и новая жёсткость смещает весь оптимум. bendCompliance уже заведена
 *    геном, диапазон включает «почти выключено», чтобы поиск мог от изгиба отказаться.
 *  - самоконтакт границы: изгиб контура и коллизии закрывают РАЗНОЕ. Изгиб делает
 *    дорогим локальное скручивание, коллизии ловят встречу далёких друг от друга кусков
 *    тела, которую изгиб не видит совсем. Нужны оба.
 *  - float: стенд переведён на double, и в движке это ОБЯЗАТЕЛЬНО — см. отдельный
 *    пункт ниже. Прежняя строка здесь говорила «для движка не рекомендовано»;
 *    она была написана до замеров и оказалась неверна.
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ SoftBodyWithBoneDemo
 * --------------------------------------
 * Там регулярная сетка: у каждой ячейки одна диагональ и два треугольника, всё выводится
 * из номера строки и столбца. Здесь топология гексагональная и неровная - степень вершины
 * от 2 до 8, длины связей отличаются в 6.8 раза, - и всё выводится из графа. Тот файл
 * проще для чтения, этот ближе к движку.
 *
 * УПРАВЛЕНИЕ
 * ----------
 * ЛКМ - тянуть вершину, наведение на ребро мышцы - сокращение её кластера,
 * 1..9 - держать мышцу сокращённой, 0 - все сразу, G - автоматический гребок,
 * SPACE - пауза, F - ускорение до максимума машины, T - диалог скорости (ползунок
 * x0..x10), Y - вернуть x1, E - изгиб контура (перебор),
 * I - режим интерполяции (выкл / по тикам, по умолчанию / по подшагам),
 * K - самоконтакт граничного контура,
 * R - сброс (включая камеру),
 * B - жёсткость костей, C - режим отрисовки,
 * ПКМ или средняя кнопка - панорама, колесо - зум к точке под курсором.
 */
class RealBodyDemo(private val bodyPath: String) : ApplicationAdapter() {

    companion object {
        private const val DT = 1.0 / 30.0

        /**
         * Подшагов на тик. ВМЕСТЕ С DT задаёт единственную величину, у которой есть
         * физический смысл: h = 1 / (UPS * SUBSTEPS), здесь 1/480.
         *
         * UPS И SUBSTEPS ПО ОТДЕЛЬНОСТИ ФИЗИКУ НЕ ОПРЕДЕЛЯЮТ. Замер (стенд TickRate):
         * при одном бюджете 576 подшагов/с деления от 288x2 до 18x32 дают невязку
         * 15.4867% против 15.4860% и |L| 1.374e-01 против 1.358e-01 — то есть одно и
         * то же с точностью до шума, и цена та же. Делить бюджет можно свободно.
         *
         * ТОГДА ЧЕМ ВЫБИРАТЬ КАЖДОЕ. Произведение — качеством сходимости (ниже).
         * Само UPS — тем, что привязано к ТИКУ: в движке это нейросеть, геном и
         * управление мышцами, они считаются раз в тик, а не раз в подшаг. Чем ниже UPS,
         * тем они дешевле, и физика от этого не страдает.
         *
         * СТАРЫЙ КРИТЕРИЙ ПРО ТУННЕЛИРОВАНИЕ («за подшаг не проскочить дальше половины
         * расстояния между клетками») БОЛЬШЕ НЕ ВЕДУЩИЙ, если в движке есть CCD: там
         * непрерывная детекция закрывает проскок сама. Проверка на числах движка:
         * v_max = 4, dt = 1/30, клетка 1 — путь за тик 0.133, то есть критерий проходит
         * даже при ОДНОМ подшаге. Оставлять его как ограничение снизу стоит только там,
         * где CCD нет.
         *
         * НАСТОЯЩИЙ КРИТЕРИЙ — СХОДИМОСТЬ. Податливость задаёт целевую жёсткость, но
         * решатель добирается до неё за несколько подшагов: мало подшагов — ткань мягче,
         * чем задано, и сильнее угловая утечка. Замер при периоде гребка, удержанном
         * равным 0.722 с (иначе сравнивались бы разные существа):
         *
         *      подш./с   невязка    |L|        вывернутых   мкс/с
         *        144     15.903%    7.73e-01       10         3182
         *        288     15.543%    2.55e-01        8         6276
         *        480     15.493%    1.49e-01        5        10294   <- стоит сейчас
         *        576     15.487%    1.38e-01       11        12217
         *       1152     15.477%    1.20e-01        0        28740
         *       2304     15.475%    1.12e-01        0        48377
         *
         * Невязка сходится к 15.475% — это не недосчёт, а заданная SOFT_COMPLIANCE
         * мягкость материала. К 480..576 она добрана. Угловая утечка после 576
         * улучшается уже всего на 15% и 6%, а цена растёт линейно — колено там.
         *
         * ПРЕДЕЛ СНИЗУ У UPS задаёт не решатель, а КВАНТОВАНИЕ УПРАВЛЕНИЯ: активация
         * мышцы меняется раз в тик. При MUSCLE_RATE_RELAX = 35.3 постоянная времени
         * распрямления 28 мс, и на 36 UPS тик уже равен ей — гребок вырождается в
         * ступеньку. По замеру выбега слом виден ровно там: 0.49 при 72 UPS, 0.73 при
         * 48, 1.73 при 36. Отсюда 60 UPS — с запасом над порогом.
         *
         * ХОТИТЕ 30 UPS — это возможно, но не даром: порог держат скорости мышц,
         * которые тюнер выбирал свободно. Зафиксируйте UPS в поиске и ограничьте их
         * сверху величиной около 1/(2*dt), тогда найдётся существо, честно живущее на
         * 30 тиках.
         */
        private const val SUBSTEPS = 16

        /**
         * НЕ СТАВИТЬ В НОЛЬ. Ноль раскручивает организм при сокращении мышцы.
         *
         * Сокращение мышцы — воздействие ВНУТРЕННЕЕ, и в точной арифметике оно сохраняет
         * и импульс, и момент: поправка ограничения расстояния идёт вдоль связи, значит
         * плечо у неё нулевое, а поправки площади и проекции кости в сумме дают ноль.
         * Проверено по стадиям — все три действительно сохраняющие.
         *
         * Течёт float. В равновесии невязка `len - rest` это чистое округление float32,
         * порядка 1e-7. При alpha = 0 поправка равна `-(len - rest) / w`, и дальше
         * updateVelocities умножает её на 1/h = 1152. То есть шум округления попадает
         * в скорости с усилением в 1152 раза и копится в настоящий момент импульса.
         *
         * Ненулевая податливость его отфильтровывает: alpha = compliance/h^2 = 1e-4 * 1152^2
         * это 132 против w = 2 в знаменателе, то есть та же невязка даёт поправку в 66 раз
         * меньше. Замер на этом теле, гравитация 0, без вязкости и сопротивления среды,
         * мышца 0 сокращена, 600 кадров:
         *
         *     compliance = 0       ->  момент  -896   (омега около -10 рад/с, видимая раскрутка)
         *     compliance = 1.0e-4  ->  момент   +12   (омега около 0.14 рад/с)
         *
         * Разница в 75 раз. То же самое относится и к движку: compliance = 0 в XPBD на
         * float32 при большом числе подшагов — это усилитель собственного шума, а не
         * «максимальная жёсткость даром».
         */
        private const val SOFT_COMPLIANCE = 1.0e-5

        /**
         * ТОЖЕ НЕ СТАВИТЬ В НОЛЬ, по той же причине, что и SOFT_COMPLIANCE.
         *
         * Тут долго стоял ноль — при том что у SOFT_COMPLIANCE прямо написано, что ноль
         * усиливает шум float32. Ограничение площади ровно так же на этом стоит, только
         * утечка у него не линейная, а УГЛОВАЯ: градиент площади направлен по нормали к
         * противолежащей стороне, плечо у него не нулевое, и остаточная невязка уходит
         * не в дрейф, а в РАСКРУТКУ тела.
         *
         * Замер, 600 кадров удержания мышцы, суммарный r x dx по стадии (идеал — ноль):
         *
         *     AREA_COMPLIANCE = 0       ->  +3.4e-03   момент тела L = +1.28
         *     AREA_COMPLIANCE = 3.0e-7  ->  -2.6e-04   L = -0.096      в 13 раз меньше
         *
         * Заодно падает и утечка ограничения РАССТОЯНИЯ (-1.3e-3 -> +9.2e-5): жёсткая
         * площадь подкидывала шум ему на вход.
         *
         * ВЕЛИЧИНА. Сравнивать надо не с SOFT_COMPLIANCE, а со знаменателем своей стадии:
         * у расстояния это w = 2, у площади это сумма w*|grad|^2, то есть порядка
         * 3 * 0.045^2 = 6e-3, в триста раз меньше. Поэтому и податливость должна быть
         * во столько же раз меньше — 1e-4 здесь запёрло бы ткань наглухо.
         *
         * Развёртка (кость уже починена), метрика — ПОВТОРЯЕМОСТЬ гребка, разброс шага
         * центра масс по 6 одинаковым циклам, и тяга за цикл:
         *
         *          0     разброс 6.1%   тяга 0.194
         *      1e-08     разброс 3.8%   тяга 0.180
         *      1e-07     разброс 2.8%   тяга 0.156
         *      3e-07     разброс 2.4%   тяга 0.144
         *      1e-06     разброс 1.0%   тяга 0.137   <- стоит сейчас
         *      3e-06     разброс 4.0%   тяга 0.135
         *      1e-05     разброс 3.3%   тяга 0.133
         *
         * Тяга падает монотонно и полого, разброс имеет чёткий минимум на 1e-6. Часть
         * потерянной «тяги» тягой и не была: при нуле тело вдобавок само раскручивалось,
         * и метрика записывала это себе в плюс.
         */
        private const val AREA_COMPLIANCE = 1.0e-6

        /**
         * Податливость площади для ВЫВЕРНУТЫХ треугольников — отдельная и НУЛЕВАЯ.
         *
         * Лечит застревание сложенной ткани. Ограничение площади вывернутый треугольник
         * выправлять УМЕЕТ: restArea2 положительна, area2 знаковая, значит цель это
         * +restArea2, и для вывернутого невязка огромна, а знак поправки правильный.
         * Мешала ему ровно та податливость, которую мы поставили ради честности счёта:
         * при alpha = 1e-6 знаменатель (denom + alpha) больше самого denom в 55 раз, и
         * выправляющая поправка слабеет во столько же.
         *
         * ПОЧЕМУ РАЗДЕЛЯТЬ ЗАКОННО, а не подгонка. Податливость нужна, чтобы не усиливать
         * шум float32 РЯДОМ С РАВНОВЕСИЕМ: там невязка это чистое округление, и жёсткое
         * ограничение раздувает его в 1/h раз. Вывернутый треугольник от равновесия
         * бесконечно далеко — его невязка порядка удвоенной площади покоя, на четыре
         * порядка больше шума. Фильтровать там нечего, мягкость только вредит. Как только
         * треугольник вывернулся обратно, он снова попадает в мягкую ветку.
         *
         * ЗАМЕР (стенд FoldRecovery: ткань складывается зеркалом, мышцы не активны,
         * считаются вывернутые треугольники; было 399 и 478 сразу после складывания):
         *
         *      сложено 50%                   сразу  0.4с   2с    8с   35с
         *      площадь 1e-6 всем (было)        399    18    2     2     1   ЗАСТРЯЛО
         *      площадь 0 всем                  399     0    0     0     0
         *      раздельно (стоит сейчас)        399     4    0     0     0
         *
         *      сложено 75%
         *      площадь 1e-6 всем (было)        478    14    3     1     1   ЗАСТРЯЛО
         *      раздельно (стоит сейчас)        478     7    0     0     0
         *
         * Единица в последнем столбце и есть та самая застрявшая складка: за 35 секунд
         * она не расходится и дальше не разойдётся. «Площадь 0 всем» её тоже лечит, но
         * возвращает угловую утечку, ради которой податливость и вводилась (замер у
         * AREA_COMPLIANCE: r x dx вырастает с -2.6e-04 до +3.4e-03). Раздельная ветка
         * даёт и то и другое: честное равновесие и распрямление складки.
         *
         * НА ПОЛНОМ КОНВЕЙЕРЕ СТАЛО ЛУЧШЕ И ПО ВРАЩЕНИЮ ТОЖЕ (PhysicsAudit, тест 3,
         * мышца держится сокращённой 2400 кадров):
         *
         *                      вывернутых на 200   на 2400    omega на 2400
         *      было                    7             18          +3.24e-03
         *      раздельно               0              0          +1.08e-04
         *
