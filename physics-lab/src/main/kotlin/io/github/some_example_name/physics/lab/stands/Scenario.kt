package io.github.some_example_name.physics.lab.stands

/** Что сцена вправе делать с энергией. */
enum class Energy {
    /** Закрытая сцена: кинетическая энергия не превышает внесённую толчками. */
    CLOSED,
    /** Сцена стартует сжатой (набитая полость): расти энергии можно, но к концу она обязана уйти. */
    SETTLES,
    /** Энергию вносят мышцы, мышь или рост: правило роста энергии не применяется. */
    DRIVEN,
}

/**
 * ЧТО СЦЕНЕ РАЗРЕШЕНО. Правила монитора одни на все сцены; различается только то, что считать
 * нарушением: в покое нельзя ничего, при таране на полной скорости ткань вправе порваться.
 * Числа и проникновения не разрешены никому.
 *
 * ПОВРЕЖДЕНИЯ — ДОЛЕЙ, А НЕ «МОЖНО ИЛИ НЕЛЬЗЯ» (15.11, по замечанию автора игры: сильный удар
 * вправе что-то порвать, вопрос — сколько). [tornShare] и [deadShare] — какая доля связей и
 * клеток сцены может быть потеряна; сколько это для удара данной скорости — [hit].
 */
data class Limits(
    val name: String,
    /** Какая доля связей тел сцены может порваться: 0 — ни одной, 1 — сколько угодно. */
    val tornShare: Double = 0.0,
    /** Какая доля клеток и свободных частиц сцены может погибнуть. */
    val deadShare: Double = 0.0,
    /** Допустимо ли срабатывание потолка скорости. */
    val capHits: Boolean = false,
    val energy: Energy = Energy.CLOSED,
    /** К концу сцена обязана успокоиться. */
    val calm: Boolean = true,
    /** К концу всё обязано спать (если допуски разрешили повреждение и оно случилось — не требуется). */
    val sleep: Boolean = true,
    /** К концу целые тела обязаны вернуться к своей форме. */
    val shape: Boolean = true,
    /** Вывернутые треугольники — нарушение. */
    val inversions: Boolean = true,
    /** Дрожь частиц — нарушение. Выключается только там, где дрожать велит сам сценарий (мышца переключается каждые два тика). */
    val jitter: Boolean = true,
) {
    companion object {
        /** Покой и мягкие касания: ничего не рвётся, не гибнет и не разгоняется. */
        val INTACT = Limits("без повреждений")
        /**
         * Удар на пределе: ткань вправе порваться и потерять клетки, но не взорваться и не пропустить
         * чужое. Сон не требуется: оторванная клетка тормозится одной изотропной средой и плывёт
         * тысячи тиков; от сцены нужно только, чтобы движение затухало.
         */
        val CRASH = Limits("разрушение допустимо", tornShare = 1.0, deadShare = 1.0, capHits = true, sleep = false, shape = false, inversions = false)
        /** Мышь, мышцы, рост: энергию вносят извне, повреждений быть не должно. */
        val DRIVEN = Limits("внешняя сила, без повреждений", energy = Energy.DRIVEN)
        /** Набитая полость: стартует сжатой, обязана успокоиться; частицы не гибнут (смерть от касаний выключена). */
        val PACKED = Limits("сжатая сцена успокаивается", energy = Energy.SETTLES, shape = false)

        /** Скорость сближения (связей за тик), ниже которой удар не вправе порвать ни одной связи. */
        const val SAFE_SPEED = 1.0
        /** Скорость сближения, с которой разрушение не ограничено: три четверти потолка скорости. */
        const val WRECK_SPEED = 6.0

        /**
         * Какую долю связей вправе порвать удар на скорости сближения [speed] связей за тик: ноль
         * до SAFE_SPEED, всё с WRECK_SPEED, между ними — по квадрату (как энергия удара): 2 связи
         * за тик — 4%, 3 — 16%, 4 — 36%, 5 — 64%. Это порог тревоги, а не свойство ткани: насколько
         * прочной ткани быть, решает автор игры, и числа эти — первое, что стоит подвинуть.
         */
        fun damageShare(speed: Double): Double = when {
            speed <= SAFE_SPEED -> 0.0
            speed >= WRECK_SPEED -> 1.0
            else -> ((speed - SAFE_SPEED) / (WRECK_SPEED - SAFE_SPEED)).let { it * it }
        }

        /**
         * Допуски удара на скорости сближения [speed]: рваться может доля связей [damageShare],
         * гибнуть — вдвое меньшая доля клеток. Форма у порванного тела не судится (монитор сам
         * пропускает такие тела), потолок скорости вправе сработать только у ударов быстрее его половины.
         */
        fun hit(speed: Double): Limits {
            val share = damageShare(speed)
            if (share <= 0.0) return INTACT
            if (share >= 1.0) return CRASH
            return Limits("удар %.1f: порваться может до %d%% связей".format(speed, Math.round(share * 100)),
                tornShare = share, deadShare = share / 2, capHits = speed > SPEED_CAP / 2, inversions = speed < 3.0)
        }
    }
}

/**
 * СЦЕНА СТЕНДА. [setup] собирает мир и вешает действия по тикам; монитор правил судит прогон
 * по [limits]. [about] и [expect] показываются в окне: что на сцене и что должно произойти —
 * по ним человек сверяет, что сцена поставлена верно.
 */
class Scenario(
    /** Постоянный номер латиницей: семейство/фигура/режим, у вариаций — с окончанием «@вариация». По нему сцену зовут из командной строки. */
    val id: String,
    val family: String,
    val title: String,
    val about: String,
    val expect: String,
    val ticks: Int,
    val limits: Limits,
    /** В какой вариации длин связей и радиусов идёт сцена. */
    val variation: Variation = Variation.BASE,
    /** Номер сцены без окончания вариации: по нему окно собирает вариации одной сцены в строку. */
    val baseId: String = id,
    val setup: StandWorld.() -> Unit,
)
