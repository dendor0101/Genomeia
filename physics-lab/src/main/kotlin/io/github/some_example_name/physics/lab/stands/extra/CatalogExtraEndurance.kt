package io.github.some_example_name.physics.lab.stands

/*
 * СЕМЕЙСТВО «ДОЛГИЕ СЦЕНЫ, СОН И КРАЯ».
 *
 * Короткие сцены не видят того, что вылезает со временем: медленной ползучести, накопления
 * ошибки, тела, которое не может уснуть или просыпается само, потери точности далеко от нуля.
 * Здесь сцены идут до трёх тысяч тиков. Правило для всех долгих сцен: последнее действие стоит
 * на последнем тике (at(ticks - 1) { }). Иначе сцена, в которой всё уснуло раньше, закончилась
 * бы досрочно, и проверки после сна не выполнились бы.
 */

/** Длина самого долгого покоя, тиков (предел сцены). */
private const val XL_REST = 3000

/** С какого тика тело, которое стояло в покое, обязано спать и не просыпаться. */
private const val XL_SLEPT_FROM = 300

/** Все клетки тела по порядку: для проверок «всё тело на месте». */
private fun xlAll(b: StandBody): IntArray = IntArray(b.count) { it }

/** Проба «сколько клеток тела не спит». */
private fun StandWorld.xlAwake(b: StandBody, name: String) {
    probe(name) { awakeCells(b).toDouble() }
}

/** Проба «центр тела ушёл от места, где стоял на тике 0, связей». */
private fun StandWorld.xlDrift(b: StandBody, name: String) {
    val start = centerOf(b)
    probe(name) { val c = centerOf(b); Math.hypot(c[0] - start[0], c[1] - start[1]) / GAME_LINK }
}

/** Проба «длина тела между клетками left и right к исходной»: сжатие и возврат формы. */
private fun StandWorld.xlWidth(b: StandBody, left: Int, right: Int, name: String) {
    val rest = distance(b, left, right)
    probe(name) { distance(b, left, right) / rest }
}

internal fun extraEnduranceFamily(): List<Scenario> {
    val family = Family("19. Доп.: долгие сцены, сон и края")
    val square8 = Shapes.square(8)

    // --- 1. Очень долгий покой: тело не ползёт и не дрожит за три тысячи тиков ---
    val restShapes = listOf(
        "square8" to Shapes.square(8), "disc5" to Shapes.disc(5), "triangle9" to Shapes.triangle(9),
        "ring6_3" to Shapes.ring(6, 3), "brick8" to Shapes.square(8).boneAll(),
    )
    for ((id, shape) in restShapes) {
        family.add("xlong/rest3000/$id", "${shape.name}: покой 3000 тиков",
            "Одно тело стоит в покое три тысячи тиков, без толчков. Сцена держится до конца.",
            "Ни одна клетка не ушла от места дальше сотой связи; тело спит с трёхсотого тика и не просыпается до конца.",
            XL_REST, Limits.INTACT) {
            val b = body(shape, 0.0, 0.0)
            idle("долгий покой: проверяется, что за три тысячи тиков ничего не начинается само")
            at(XL_REST - 1) { }
            expectStill("клетки тела ушли, связей", b, xlAll(b), 0, XL_REST, 0.01)
            xlAwake(b, "не спит клеток тела")
            expectMaxAtMost("тело проснулось после засыпания", "не спит клеток тела", XL_SLEPT_FROM, XL_REST, 0.0)
        }
    }

    // Разные тела рядом: покой не должен зависеть от соседей, даже если они стоят далеко.
    family.add("xlong/rest3000/mixed", "шесть разных тел покоятся рядом три тысячи тиков",
        "Шесть тел разных фигур стоят в ряд, между соседями просвет в три связи: никто никого не касается.",
        "Ни одно тело не сдвинулось с места больше чем на сотую связи по центру и не дрожит; все спят.",
        XL_REST, Limits.INTACT) {
        val row = listOf(Shapes.square(6), Shapes.disc(3), Shapes.rect(10, 3), Shapes.triangle(6), Shapes.ring(5, 2), Shapes.rope(12))
        val bodies = ArrayList<StandBody>()
        var x = 0.0
        for ((i, s) in row.withIndex()) {
            if (i > 0) x += row[i - 1].reach + s.reach + START_GAP
            bodies.add(body(s, x, 0.0))
        }
        idle("долгий покой шести тел рядом: проверяется, что ничего не начинается само")
        val starts = bodies.map { centerOf(it) }
        probe("сдвиг самого подвижного тела, связей") {
            var worst = 0.0
            for (i in bodies.indices) {
                val c = centerOf(bodies[i])
                worst = maxOf(worst, Math.hypot(c[0] - starts[i][0], c[1] - starts[i][1]) / GAME_LINK)
            }
            worst
        }
        expectMaxAtMost("тело уехало с места", "сдвиг самого подвижного тела, связей", 1, XL_REST, 0.01)
        at(XL_REST - 1) { }
    }

    // --- 2. Двадцать ударов подряд по одному телу: после каждого тело возвращает форму ---
    // Тело не успевает уснуть между ударами (остановка занимает сотни тиков), поэтому проверяем не сон,
    // а форму: ширина тела к следующему удару не меньше 0.9 исходной, и каждый удар его сдвигает.
    for ((id, shape) in listOf("square8" to Shapes.square(8), "disc5" to Shapes.disc(5))) {
        val left = shape.extreme(-1.0, 0.0)
        val right = shape.extreme(1.0, 0.0)
        family.add("xlong/hammer20/$id", "${shape.name}: двадцать ударов подряд раз в 120 тиков",
            "Тело стоит; двадцать раз подряд, раз в 120 тиков, в его левый край влетает свободная частица со скоростью 2 связи за тик.",
            "После каждого удара тело сдвигается, а перед следующим его ширина возвращается к исходной (не меньше 0.9); ничего не рвётся и не дрожит.",
            2500, Limits.INTACT) {
            val b = body(shape, 0.0, 0.0)
            xlWidth(b, left, right, "ширина тела к исходной")
            probe("скорость тела, связей") { speedOf(b) }
            for (k in 0 until 20) {
                val t = 100 + 120 * k
                at(t) { val c = centerOf(b); ball(c[0] - shape.halfWidth - 3.0, c[1], 2.0, 0.0) }
                expectMaxAtLeast("удар ${k + 1} сдвинул тело", "скорость тела, связей", t, t + 30, 0.02)
                expectMinAtLeast("перед ударом ${k + 1} форма вернулась", "ширина тела к исходной", t + 100, t + 119, 0.9)
            }
            at(2499) { }
        }
    }

    // --- 3. Десять пробуждений и засыпаний подряд разными способами ---
    family.add("xlong/wake10/worm", "червь засыпает и просыпается пять раз подряд разными способами",
        "Червь 20×4 стоит и спит. Пять циклов по 540 тиков: удар, мышь, команда мышцам, свободная частица — по кругу. В каждом цикле тело будят, и оно должно уснуть до конца цикла.",
        "В каждом цикле тело просыпается от своей причины и снова засыпает; на границах циклов никто не дрожит и не рвёт ткань.",
        3000, Limits.DRIVEN) {
        val worm = Shapes.rect(20, 4).muscleAll()
        val b = body(worm, 0.0, 0.0)
        val cell = worm.extreme(1.0, 0.0)
        xlAwake(b, "не спит клеток червя")
        // Пять циклов по 540 тиков: после самого слабого толчка телу нужно около пятисот тиков, чтобы остановиться и
        // уснуть (среда гасит скорость в e раз за сотню тиков, сон наступает через шестьдесят тиков покоя).
        for (c in 0 until 5) {
            val s = 300 + 540 * c
            when (c % 4) {
                0 -> at(s) { kick(b, 0.05, 0.0) }
                1 -> mousePath(b, cell, s, 3, (0..10).map { doubleArrayOf(worm.x[cell] + 1.5 * it / 10, worm.y[cell]) })
                2 -> {
                    at(s) { muscles(b, 0.5f) }
                    at(s + 40) { muscles(b, 1f) }
                }
                else -> at(s) { val p = centerOf(b); ball(p[0] - worm.halfWidth - 3.0, p[1], 1.0, 0.0) }
            }
            expectMaxAtLeast("цикл ${c + 1}: тело проснулось", "не спит клеток червя", s, s + 30, 1.0)
            expectMinAtMost("цикл ${c + 1}: тело снова уснуло", "не спит клеток червя", s + 440, s + 539, 0.0)
        }
        at(2999) { }
    }

    // --- 4. Толчки у порога покоя: едет и останавливается, либо стоит, но не ползёт вечно ---
    for (v in listOf(0.005, 0.01, 0.02, 0.05)) {
        family.add("xlong/threshold/v$v", "толчок $v связи за тик у порога покоя",
            "Квадрат 8 стоит; на тике 120 ему задают скорость $v связи за тик вправо и больше не трогают. Сцена идёт 1000 тиков.",
            "Тело либо проедет немного и остановится, либо постоит; к концу скорость ниже 0.002 связи за тик, оно спит и не ползёт.",
            1000, Limits.INTACT) {
            val b = body(square8, 0.0, 0.0)
            at(120) { kick(b, v, 0.0) }
            mustMove(b, 0.05, "толчок сдвинул тело хоть на двадцатую долю связи")
            xlDrift(b, "путь тела, связей")
            probe("скорость тела, связей") { speedOf(b) }
            expectMaxAtLeast("тело проехало хоть немного", "путь тела, связей", 121, 999, 0.1)
            expectMaxAtMost("тело ползёт в конце", "скорость тела, связей", 900, 999, 0.002)
            at(999) { }
        }
    }

    // --- 5. Далеко от начала координат: покой, толчок, мышцы и рост — как рядом с нулём ---
    val farWorm = Shapes.rect(12, 4).muscleAll()
    val farSeed = Shapes.disc(3)
    val farSeedCell = farSeed.nearest(0.0, 0.0)
    val farGrowTicks = FAST.ticks(farSeed, farSeedCell) + 400
    for (x in listOf(10000.0, 50000.0, 200000.0)) {
        family.add("xlong/far/${x.toLong()}/rest", "квадрат 8 в ${x.toLong()} единицах от нуля: покой",
            "Квадрат стоит в точке (${x.toLong()}, 0) в позе покоя, без толчков.",
            "Ничего не происходит: тело не ползёт, не дрожит от нехватки точности и засыпает.",
            150, Limits.INTACT) {
            val b = body(square8, x, 0.0)
            idle("покой вдали от начала координат")
            expectStill("клетки ушли, связей", b, xlAll(b), 0, 150, 0.02)
            at(149) { }
        }
        family.add("xlong/far/${x.toLong()}/bump", "толчок вдали от нуля: квадраты 8, скорость 0.6",
            "Два квадрата в ${x.toLong()} единицах от нуля; левый летит в правый со скоростью 0.6 связи за тик.",
            "Как рядом с нулём: тела сталкиваются и отскакивают без разрывов и проникновений, к концу спят.",
            settle(0.6), Limits.INTACT) {
            val apart = separation(square8, square8, CONTACT_DISTANCE) + START_GAP
            val a = body(square8, x - apart / 2, 0.0)
            val b = body(square8, x + apart / 2, 0.0)
            kick(a, 0.6, 0.0)
            expectPushed(b, 0.6, settle(0.6))
        }
        family.add("xlong/far/${x.toLong()}/muscle", "мышечный червь в ${x.toLong()} единицах от нуля: сжатие и возврат",
            "Червь 12×4 стоит в точке (${x.toLong()}, 0); на тике 60 мышцы сокращаются, на тике 160 отпускают.",
            "Червь сжимается не меньше чем до 0.8 исходной длины, после расслабления возвращает форму (не меньше 0.95); ничего не рвётся.",
            500, Limits.DRIVEN) {
            val b = body(farWorm, x, 0.0)
            xlWidth(b, farWorm.extreme(-1.0, 0.0), farWorm.extreme(1.0, 0.0), "длина к исходной")
            at(60) { muscles(b, 0.5f) }
            at(160) { muscles(b, 1f) }
            expectMinAtMost("червь сократился", "длина к исходной", 80, 160, 0.8)
            expectMinAtLeast("червь вернул форму", "длина к исходной", 400, 499, 0.95)
            at(499) { }
        }
        family.add("xlong/far/${x.toLong()}/grow", "круг растёт в ${x.toLong()} единицах от нуля",
            "Круг радиуса 3 растёт из зиготы в точке (${x.toLong()}, 0) темпом FAST; после роста стоит и спит.",
            "Тело вырастает целиком, ни одна клетка не уходит от зиготы дальше, чем у взрослого тела; ничего не рвётся; к концу спит.",
            farGrowTicks, GROW) {
            val b = growing(farSeed, x, 0.0, seed = farSeedCell, start = 0, period = FAST.period, batch = FAST.batch)
            probe("вырос целиком") { if (b.growth?.done == true) 1.0 else 0.0 }
            expectMinAtLeast("тело вырастает целиком", "вырос целиком", farGrowTicks - 200, farGrowTicks - 1, 1.0)
            at(farGrowTicks - 1) { }
        }
    }

    // --- 6. Медленное сближение: 0.02 связи за тик до касания и долгое стояние вплотную ---
    family.add("xlong/creep/approach002", "два квадрата медленно сближаются и долго стоят вплотную",
        "Левый квадрат ведут со скоростью 0.02 связи за тик вправо триста тиков, пока не коснётся правого, потом отпускают. Сцена идёт 2200 тиков.",
        "Касание наступает, тела не проникают друг в друга; к тику 1200 их скорость ниже 0.002 связи за тик, и после касания зазор не растёт дальше полусвязи.",
        2200, Limits.INTACT) {
        val apart = separation(square8, square8, CONTACT_DISTANCE) + START_GAP
        val a = body(square8, -apart / 2, 0.0)
        val b = body(square8, apart / 2, 0.0)
        // Левое тело ведут, только пока оно не коснулось правого: иначе его полтораста тиков вдавливают в соседа,
        // и тот уезжает (15.11: после «касания» зазор вырос до пяти связей).
        during(0, 299) { if (clearance(a, b) > 0.03) kick(a, 0.02, 0.0) }
        expectMet(a, b, 299, 0.02)
        probe("скорость тел, связей") { maxOf(speedOf(a), speedOf(b)) }
        expectMaxAtMost("тела ползут вечно", "скорость тел, связей", 1200, 2199, 0.002)
        probe("зазор после касания, связей") { clearance(a, b) / GAME_LINK }
        expectMaxAtMost("тела разошлись после касания", "зазор после касания, связей", 600, 2199, 0.5)
        at(2199) { }
    }

    // --- 7. Башня: пять тел вплотную, крайнее толкают — волна доходит до последнего ---
    for (v in listOf(0.6, 2.0)) {
        family.add("xlong/tower5/v$v", "пять тел вплотную, левое толкают со скоростью $v",
            "Пять квадратов 8 стоят в ряд вплотную, касаясь соседей; левое толкают вправо со скоростью $v связи за тик.",
            "Толчок идёт по ряду: до последнего тела доходит волна, и оно сдвигается. Без проникновений и гибели; к концу все стоят и спят.",
            settle(v) + 300, if (v < 1.0) TOUCH else Limits.hit(v)) {
            val step = separation(square8, square8, CONTACT_DISTANCE)
            val row = (0 until 5).map { body(square8, it * step, 0.0) }
            val last0 = centerOf(row[4])
            kick(row[0], v, 0.0)
            probe("сдвиг последнего тела, связей") {
                val c = centerOf(row[4]); Math.hypot(c[0] - last0[0], c[1] - last0[1]) / GAME_LINK
            }
            expectMaxAtLeast("волна дошла до последнего тела", "сдвиг последнего тела, связей", 1, settle(v), 0.05)
        }
    }

    // --- 8. Тело зажато между двумя стоящими вплотную соседями и не дрожит ---
    family.add("xlong/sandwich/rest2000", "тело зажато между двумя соседями вплотную, 2000 тиков",
        "Три квадрата 8 стоят в ряд вплотную; крайние никто не трогает, средний тоже. Сцена идёт 2300 тиков.",
        "Средний квадрат не дрожит: после тика 300 ни одна его клетка не уходит от места дальше 0.02 связи; к концу спит.",
        2300, TOUCH) {
        val step = separation(square8, square8, CONTACT_DISTANCE)
        body(square8, -step, 0.0)
        val mid = body(square8, 0.0, 0.0)
        body(square8, step, 0.0)
        expectStill("средний квадрат дрожит, связей", mid, xlAll(mid), 300, 2299, 0.02)
        at(2299) { }
    }

    // --- 9. Качели: толчки туда-обратно, энергия не копится ---
    family.add("xlong/swing30", "качели: тело толкают туда-обратно 30 раз через 60 тиков",
        "Квадрат 8 стоит; каждые 60 тиков его толкают то вправо, то влево со скоростью 0.3 связи за тик — тридцать толчков.",
        "Скорость тела ни разу не выше 0.31 связи за тик: от толчков энергия не копится. Без разрывов и дрожи; к концу спит.",
        1860, Limits.INTACT) {
        val b = body(square8, 0.0, 0.0)
        for (k in 0 until 30) at(60 * k) { kick(b, if (k % 2 == 0) 0.3 else -0.3, 0.0) }
        probe("скорость тела, связей") { speedOf(b) }
        expectMaxAtMost("энергия накопилась", "скорость тела, связей", 1, 1800, 0.31)
        at(1859) { }
    }

    // --- 10. Спящее тело, по которому периодически попадает частица ---
    // Период 600, а не 200: тело после удара стоит сотни тиков, и к следующему удару на 200 тиков
    // оно бы не успело уснуть. Проверка «снова спит» требует хотя бы 500 тиков покоя.
    family.add("xlong/sleep-ball600", "спящее тело, по которому раз в 600 тиков попадает частица",
        "Квадрат 8 стоит и засыпает; на тиках 150, 750, 1350 и 1950 в его левый край влетает свободная частица со скоростью 1 связь за тик.",
        "Каждый раз тело просыпается от удара и снова засыпает до следующего; частица не входит в ткань, ничего не рвётся.",
        2550, Limits.INTACT) {
        val b = body(square8, 0.0, 0.0)
        xlAwake(b, "не спит клеток тела")
        for (k in 0 until 4) {
            val t = 150 + 600 * k
            at(t) { val c = centerOf(b); ball(c[0] - square8.halfWidth - 3.0, c[1], 1.0, 0.0) }
            expectMaxAtLeast("удар ${k + 1} разбудил тело", "не спит клеток тела", t, t + 30, 1.0)
            expectMinAtMost("после удара ${k + 1} тело снова спит", "не спит клеток тела", t + 500, t + 599, 0.0)
        }
        at(2549) { }
    }

    // --- 11. Мышца держит сокращение 2500 тиков, потом отпускает ---
    family.add("xlong/hold2500/worm", "червь сокращён 2500 тиков, потом отпущен",
        "Червь 16×4 сокращается с тика 60 до тика 2560; потом мышцы отпускают и тело стоит в покое до конца сцены.",
        "Пока мышцы сокращены, тело остаётся сжатым (длина не выше 0.9 исходной); после отпускания возвращает форму (не меньше 0.95); без разрывов и дрожи.",
        2960, Limits.DRIVEN) {
        val worm = Shapes.rect(16, 4).muscleAll()
        val b = body(worm, 0.0, 0.0)
        xlWidth(b, worm.extreme(-1.0, 0.0), worm.extreme(1.0, 0.0), "длина к исходной")
        at(60) { muscles(b, 0.5f) }
        at(2560) { muscles(b, 1f) }
        expectMaxAtMost("сжатое тело распрямилось", "длина к исходной", 1000, 2559, 0.9)
        expectMinAtLeast("тело не вернуло форму", "длина к исходной", 2900, 2959, 0.95)
        at(2959) { }
    }

    // --- 12. Долгая гребля бегущей волной: тело уплыло, но не порвалось и не дрожит ---
    family.add("xlong/wave2500/worm", "червь гребёт бегущей волной 2500 тиков",
        "Червь 24×4 с шестью сегментами мышц гребёт волной 2500 тиков, затем мышцы отпускают.",
        "Червь уплывает от старта больше чем на три связи, не рвётся и не дрожит; после расслабления останавливается и засыпает.",
        2800, Limits.DRIVEN) {
        val worm = Shapes.rect(24, 4).muscleSegments(6)
        val b = body(worm, 0.0, 0.0)
        during(0, 2499) { t ->
            for (g in 0 until 6) muscle(b, g, if ((t / 40 + g) % 4 < 2) 0.5f else 1.5f)
        }
        at(2500) { muscles(b, 1f) }
        expectTravelled("червь уплыл, связей", b, xlAll(b), 0, 2500, 3.0, "червь уплыл от старта")
        at(2799) { }
    }

    // --- 13. Тело у стенки рамки мира спит и не просыпается от частицы, пролетающей мимо ---
    family.add("xlong/wall-sleep/flyby", "спящее тело у стенки не просыпается от частицы, летящей мимо",
        "Мир 30×20 со стенкой. Квадрат 8 стоит и спит у правой стенки. Над ним вправо летит частица, не касаясь его, и отскакивает от стенки.",
        "Квадрат не просыпается и не сдвигается ни на сотую связи; частица не входит в стенку и не выходит за рамку.",
        400, Limits.INTACT) {
        arena(30, 20)
        val x0 = 29.0 - square8.halfWidth - GAME_RADIUS - START_GAP
        val b = body(square8, x0, 10.0)
        ball(5.0, 10.0 + square8.halfHeight + 1.5 * START_GAP, 1.0, 0.0)
        // Частица по постановке летит мимо: условие сцены — что она тела не задела.
        mustNever("частица задела спящее тело") { touch.balls(b, extra = 0.0, moving = false) }
        xlAwake(b, "не спит клеток тела")
        expectMaxAtMost("тело проснулось у стенки", "не спит клеток тела", 150, 399, 0.0)
        expectStill("тело сдвинулось у стенки, связей", b, xlAll(b), 150, 399, 0.01)
        expectAllInside(0.0, 0.0, 30.0, 20.0, 399)
        at(399) { }
    }

    // --- 14. Шестьдесят мелких тел спят рядами, одно из них будят ---
    family.add("xlong/crowd60/wake-one", "шестьдесят мелких кругов спят рядами, одного будят",
        "Шестьдесят кругов радиуса 2 стоят решёткой 6×10 с просветом в три связи и спят. На тике 150 круг в середине получает скорость 0.3 связи за тик.",
        "Тронутый круг едет; дальний угол решётки спит всё время и не просыпается. К концу всё снова засыпает.",
        settle(0.3) + 150, Limits.INTACT) {
        val disc = Shapes.disc(2)
        val step = 2 * disc.reach + START_GAP
        val all = ArrayList<StandBody>()
        for (r in 0 until 6) for (c in 0 until 10) all.add(body(disc, c * step, r * step))
        val mid = all[35]
        val far = all.last()
        xlAwake(far, "не спит клеток дальнего круга")
        val midStart = centerOf(mid)
        probe("путь тронутого круга, связей") {
            val c = centerOf(mid); Math.hypot(c[0] - midStart[0], c[1] - midStart[1]) / GAME_LINK
        }
        at(150) { kick(mid, 0.3, 0.0) }
        mustMove(mid, 1.0, "тронутый круг поехал")
        expectMaxAtMost("дальний круг проснулся", "не спит клеток дальнего круга", 120, settle(0.3) + 149, 0.0)
        expectMaxAtLeast("тронутый круг поехал", "путь тронутого круга, связей", 151, 300, 0.1)
        at(settle(0.3) + 149) { }
    }

    // --- 15. Очень маленькие тела в ударах: три и пять клеток ---
    // Сила HIT здесь не берётся: у тела из одной-трёх клеток доля порванных связей даёт ложное срабатывание.
    for (small in listOf(Shapes.disc(1), Shapes.rect(3, 1), Shapes.triangle(3))) for (hit in listOf(TAP, BUMP)) {
        family.add("xlong/small/${small.id}/${hit.id}", "${small.name}: ${hit.title}",
            "Маленькое тело летит в стоящее такое же со скоростью ${hit.speed} связи за тик.",
            hit.expect, settle(hit.speed, !small.hasTissue), hit.limits) {
            val (_, target) = duel(small, small, hit.speed)
            expectPushed(target, hit.speed, settle(hit.speed, !small.hasTissue))
        }
    }

    // --- 16. Два тела вращаются вплотную, как шестерёнки ---
    for (g in listOf(Shapes.gear(5, 6), Shapes.gear(4, 5))) {
        val ticks = settle(1.0) + 200
        family.add("xlong/gears/${g.id}", "две шестерёнки ${g.name}: вращаются вплотную",
            "Две одинаковые шестерёнки касаются зубцами; левая вращается по часовой (0.05 радиана за тик), правая — против.",
            "Каждая вращается на месте: зубцы вправе оттолкнуть шестерёнки друг от друга, но они не разлетаются (центр не уходит дальше трёх связей), ничего не рвётся и не взрывается; к концу обе стоят и спят.",
            ticks, Limits.INTACT) {
            val sep = separation(g, g, CONTACT_DISTANCE)
            val a = body(g, -sep / 2, 0.0)
            val b = body(g, sep / 2, 0.0)
            kick(a, 0.0, 0.0, spin = 0.05)
            kick(b, 0.0, 0.0, spin = -0.05)
            xlDrift(a, "центр левой шестерни, связей")
            xlDrift(b, "центр правой шестерни, связей")
            // Шестерёнки — свободные тела, не на осях: зубцы законно расталкивают их. Требуем только, чтобы они не разлетелись.
            expectMaxAtMost("левая шестерня уехала", "центр левой шестерни, связей", 1, ticks, 3.0)
            expectMaxAtMost("правая шестерня уехала", "центр правой шестерни, связей", 1, ticks, 3.0)
            at(ticks - 1) { }
        }
    }

    return family.list
}
