/**
 * СВЕРХЗАМЕДЛЕНИЕ на клавише [ — в тысячу раз медленнее реального времени.
 *
 * Шаг физики при этом НЕ МЕНЯЕТСЯ: timeScale умножает реальное время, то есть
 * меняется число тиков в секунду, а не их длина. Состояния остаются побитово
 * теми же, их просто показывают на большем числе кадров — поэтому замедление
 * ничего не портит и его можно включать прямо посреди случая.
 */
const val SLOWMO_SCALE = 0.001

/**
 * ПУЛЯ [P] — одиночная клетка, запущенная справа налево на потолке скорости.
 *
 * Проверка непроницаемости в самом злом допустимом случае: быстрее в стенде
 * не летает ничто, потому что clampSpeed режет всё выше. Если пуля прошла
 * насквозь, значит дыра настоящая, а не следствие слишком резкой мыши.
 * Так же сделано в прототипе, откуда переносились контакты.
 */
/**
 * Доля потолка скорости для пули и тарана.
 *
 * Было 0.95, стало 0.8. Девяносто пять процентов оставляли запаса всего
 * пять, а его съедает первая же добавка от ограничений: удар, поправка
 * связи, отклик контакта. Потолок скорости при этом срабатывает, а он
 * правит частицы по одной и импульс не сохраняет — то есть стенд сам
 * создавал ту ошибку, которую призван ловить.
 *
 * Восемь десятых оставляют пятую часть потолка на отклик решателя. Проверка
 * непроницаемости от этого не слабеет: пуля по-прежнему летит быстрее, чем
 * что-либо в симуляции способно двигаться само.
 */
const val BULLET_SPEED_FRACTION = 0.8

/** Радиусы захвата масштабируются от средней связи: тело мельче синтетического. */
const val PICK_FACTOR = 1.2f
