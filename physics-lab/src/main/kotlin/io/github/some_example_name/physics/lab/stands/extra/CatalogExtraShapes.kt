/*
 * МАТРЁШКА. Круг стоит в дыре среднего кольца, среднее кольцо — в дыре внешнего, все три
 * концентрично. Расстояния по клеткам: круг (наружный радиус 1.2) и среднее кольцо (внутренний
 * радиус 2.4) — 1.2 единицы; среднее (наружный 4.2) и внешнее (внутренний 5.4) — тоже 1.2.
 * Порог касания 0.6, значит на старте никто никого не касается.
 * Толкаем круг — он бьёт среднее кольцо изнутри. Толкаем среднее — его внутренняя стенка
 * сметает круг. Главное: круг не выскакивает из дыры сквозь целую стенку.
 */
private fun xgNested(family: Family) {
    val outer = Shapes.ring(12, 9)
    val middle = Shapes.ring(7, 4)
    val core = Shapes.disc(2)
    for (speed in listOf(0.6, 2.0)) {
        val limits = if (speed < 1.0) Limits.INTACT else Limits.hit(speed)
        val ticks = settle(speed)
        family.add("xgeo/nest/core-kick/v$speed", "матрёшка: круг толкнули, скорость $speed",
            "Внешнее кольцо, среднее кольцо и круг в центре стоят концентрично, не касаясь. " +
                "Круг получает скорость $speed связи за тик вправо и бьёт среднее кольцо изнутри.",
            "Круг остаётся в средней дыре: сквозь целую стенку он пройти не может. " +
                (if (speed < 1.0) "Ничего не рвётся; к концу всё стоит и спит."
                else "Стенка вправе порваться в пределах допуска; клетки не входят друг в друга; к концу всё успокаивается."),
            ticks, limits) {
            body(outer, 0.0, 0.0)
            val m = body(middle, 0.0, 0.0)
            val c = body(core, 0.0, 0.0)
            kick(c, speed, 0.0)
            probe("круг от центра средней дыры, единиц") { xgCenterGap(c, m) }
            expectMaxAtMost("круг остался в средней дыре", "круг от центра средней дыры, единиц", 1, ticks, 2.0 * Variation.current.spread)
        }
        family.add("xgeo/nest/middle-kick/v$speed", "матрёшка: среднее кольцо толкнули, скорость $speed",
            "Среднее кольцо получает скорость $speed связи за тик вправо. Его внутренняя стенка проезжает по кругу, " +
                "а внешнее кольцо стоит.",
            "Круг не выскакивает из дыры среднего кольца: стенка либо увлекает его толчком, либо отпускает. " +
                "Клетки не входят в чужую ткань; к концу всё успокаивается.",
            ticks, limits) {
            body(outer, 0.0, 0.0)
            val m = body(middle, 0.0, 0.0)
            val c = body(core, 0.0, 0.0)
            kick(m, speed, 0.0)
            probe("круг от центра средней дыры, единиц") { xgCenterGap(c, m) }
            expectMaxAtMost("круг остался внутри среднего кольца", "круг от центра средней дыры, единиц", 1, ticks, 2.0 * Variation.current.spread)
            expectPushed(c, speed, ticks, share = 0.02, hitterCells = m.count)
        }
    }
}

/*
 * ДВЕ ПОДКОВЫ. Большая подкова 16×9 со стенкой 3 открыта вверх: её чаша внутри по ширине ±3.3
 * (стенки начинаются с |x| = 3.3), дно — на высоте −1.2. Малая подкова 8×5 со стенкой 2 стоит в
 * центре чаши, поднята на 1.8 единицы: её дно на высоте 0.6, зазор до дна чаши 1.8 — как START_GAP.
 * Боковой зазор: наружные клетки малой на |x| = 2.1, стенки большой с |x| = 3.3, то есть 1.2.
 * Растаскиваем вдоль оси: малую вверх, большую вниз. Ни на старте, ни при разъёме контакта нет,
 * так что проверяем проход через горло чаши.
 */
private fun xgHorseshoes(family: Family) {
    val big = Shapes.uShape(16, 9, 3)
    val small = Shapes.uShape(8, 5, 2)
    for (speed in listOf(0.6, 2.0)) {
        val ticks = settle(speed)
        family.add("xgeo/horseshoe/pull-apart/v$speed", "две подковы: малая в чаше большой, растащили, скорость $speed",
            "Большая подкова открыта вверх; меньшая стоит внутри её чаши, не касаясь. Меньшую тянет вверх, " +
                "большую вниз, обе со скоростью $speed связи за тик.",
            "Подковы выходят друг из друга через горло чаши и расходятся; ничего не рвётся и не проходит " +
                "сквозь стенки; к концу всё стоит и спит.",
            ticks, Limits.INTACT) {
            val up = body(small, 0.0, 1.8)
            val down = body(big, 0.0, 0.0)
            kick(up, 0.0, speed)
            kick(down, 0.0, -speed)
            // Подковы по постановке расходятся, не касаясь: условие сцены — что обе уехали.
            mustMove(up, 4.0, "малая подкова уехала"); mustMove(down, 4.0, "большая подкова уехала")
            probe("расстояние между подковами, единиц") { xgCenterGap(up, down) }
            expectMaxAtLeast("подковы разошлись", "расстояние между подковами, единиц", 1, ticks, 6.0)
        }
    }
}

/*
 * ГАНТЕЛЬ С ТОНКОЙ ПЕРЕМЫЧКОЙ. Два круга на перемычке в одну клетку: цепочка без треугольников,
 * её держат только связи, поэтому это самое слабое место тела. Сцены: толчок в круг (перемычка
 * передаёт толчок через себя), вращение (центробежная сила тянет перемычку), мышь за перемычку.
 * Удар перемычкой о столб — в xgBridgePost.
 */
private fun xgDumbbell(family: Family) {
    val db = Shapes.dumbbell(3, 6, 1)
    val small = Shapes.dumbbell(4, 4, 1)
    val disc = Shapes.disc(3)
    for (speed in listOf(0.6, 2.0)) {
        val ticks = settle(speed)
        val limits = if (speed < 1.0) Limits.INTACT
        else Limits.hit(speed).copy(name = "удар $speed; перемычка вправе порваться до 10%", tornShare = 0.1)
        family.add("xgeo/dumbbell/hit/v$speed", "гантель: круг бьёт в край, скорость $speed",
            "Круг радиуса 3 летит вправо со скоростью $speed связи за тик в левый круг гантели. " +
                "Перемычка в одну клетку соединяет круги.",
            "Толчок доходит до правого круга через перемычку; клетки не проходят одна сквозь другую; " +
                "порваться вправе не больше допуска; к концу всё стоит и спит.",
            ticks, limits) {
            val (_, target) = duel(disc, db, speed)
            expectPushed(target, speed, ticks, share = 0.05, hitterCells = disc.count)
        }
    }
    for ((spin, limits) in listOf(
        0.05 to Limits.INTACT,
        0.12 to Limits.INTACT.copy(name = "центробежная сила; перемычка вправе порваться до 50%", tornShare = 0.5),
    )) {
        val ticks = settle(0.6)
        family.add("xgeo/dumbbell/spin/s$spin", "гантель крутится на перемычке, $spin рад за тик",
            "Гантель получает вращение $spin радиана за тик вокруг своего центра, без поступательной скорости.",
            "Круги описывают окружность вокруг центра и не уезжают; центр не сдвигается дальше 0.3 связи; " +
                "перемычка не рвётся сверх допуска; к концу всё стоит и спит.",
            ticks, limits) {
            val b = body(db, 0.0, 0.0)
            val start = centerOf(b)
            kick(b, 0.0, 0.0, spin = spin)
            probe("центр гантели ушёл, связей") { xgLinks(start, centerOf(b)) }
            expectMaxAtMost("центр гантели остался на месте", "центр гантели ушёл, связей", 1, ticks, 0.3)
        }
    }
    // Гантель поменьше: перемычка длиннее относительно кругов, вращение быстрее раскручивает её.
    family.add("xgeo/dumbbell/small/hit", "гантель 4×4 с перемычкой: круг бьёт, скорость 2.0",
        "Круг радиуса 3 летит вправо со скоростью 2.0 связи за тик в левый круг гантели 4×4.",
        "Толчок доходит до правого круга через перемычку; клетки не проходят одна сквозь другую; " +
            "порваться вправе до 10% связей; к концу всё стоит и спит.",
        settle(2.0), Limits.hit(2.0).copy(name = "удар 2.0; перемычка вправе порваться до 10%", tornShare = 0.1)) {
        val ticks = settle(2.0)
        val (_, target) = duel(disc, small, 2.0)
        expectPushed(target, 2.0, ticks, share = 0.05, hitterCells = disc.count)
    }
    family.add("xgeo/dumbbell/small/spin", "гантель 4×4 с перемычкой крутится, 0.05 рад за тик",
        "Гантель 4×4 получает вращение 0.05 радиана за тик вокруг своего центра.",
        "Центр гантели остаётся на месте (не дальше 0.3 связи), перемычка не рвётся; к концу всё стоит и спит.",
        settle(0.6), Limits.INTACT) {
        val b = body(small, 0.0, 0.0)
        val start = centerOf(b)
        kick(b, 0.0, 0.0, spin = 0.05)
        probe("центр гантели ушёл, связей") { xgLinks(start, centerOf(b)) }
        expectMaxAtMost("центр гантели остался на месте", "центр гантели ушёл, связей", 1, settle(0.6), 0.3)
    }
    // Мышь берёт перемычку посередине и тянет вверх: круги едут за ней, перемычка держит.
    val mouseTicks = 140 + settle(0.5)
    family.add("xgeo/dumbbell/bridge-pull", "гантель: мышь тянет за перемычку вверх",
        "Мышь берёт клетку в середине перемычки и плавно тянет её на четыре единицы вверх, затем отпускает.",
        "Круги едут за перемычкой; она вправе порваться не больше чем на пятую часть связей; " +
            "после отпускания всё успокаивается и засыпает.",
        mouseTicks, Limits.DRIVEN.copy(name = "внешняя сила, мышь; перемычка вправе порваться до 20%", tornShare = 0.2)) {
        val b = body(db, 0.0, 0.0)
        val cell = db.nearest(0.0, 0.0)
        val x0 = db.x[cell]
        val y0 = db.y[cell]
        val points = (0..40).map { doubleArrayOf(x0, y0 + 4.0 * it / 40.0) }
        mousePath(b, cell, 10, 3, points)
        val start = centerOf(b)
        probe("центр гантели, подъём, единиц") { centerOf(b)[1] - start[1] }
        expectMaxAtLeast("гантель потянулась за мышью", "центр гантели, подъём, единиц", 1, mouseTicks, 1.0)
    }
}

/*
 * ЗВЁЗДЫ, СЦЕПИВШИЕСЯ ЛУЧАМИ. Пятилучевая звезда (внешний радиус 4.8, впадины 1.8) и её копия,
 * повёрнутая на 36°: лучи второй встают во впадины первой. Касание задано расстоянием 0.5
 * (порог 0.6), то есть лучи слегка прижаты друг к другу. Первая вращается в одну сторону, вторая —
 * навстречу: лучи скользят друг по другу и не должны проходить сквозь соседние. Третий вариант —
 * обе в одну сторону: лучи едут вместе, и трение почти не работает.
 */
private fun xgStars(family: Family) {
    val star = Shapes.star(5, 8, 3)
    val cases = listOf(Triple("opposite", 0.04, -1.0), Triple("opposite-fast", 0.08, -1.0), Triple("same", 0.04, 1.0))
    for ((tag, spin, sign) in cases) {
        val limits = Limits.INTACT.copy(name = "лучи скользят; разрыв до 5% связей", tornShare = 0.05, energy = Energy.SETTLES)
        family.add("xgeo/stars/$tag", "звёзды сцепились лучами, вращение $spin рад за тик",
            "Две пятилучевые звезды касаются лучами; вторая повёрнута на 36°, и её лучи встают во впадины первой. " +
                "Левая крутится на $spin радиана за тик, правая — " + (if (sign < 0) "навстречу." else "в ту же сторону."),
            "Лучи скользят друг по другу, но не проходят сквозь соседние; разрыв не больше 5% связей; " +
                "центры звёзд не сближаются ближе двух единиц; к концу всё стоит и спит.",
            settle(0.3), limits) {
            val gap = separation(star, star, 0.62, 0.0, 0.0, PI / 5)
            val a = body(star, -gap / 2, 0.0, 0.0)
            val b = body(star, gap / 2, 0.0, PI / 5)
            kick(a, 0.0, 0.0, spin = spin)
            kick(b, 0.0, 0.0, spin = sign * spin)
            probe("расстояние между центрами звёзд, единиц") { xgCenterGap(a, b) }
            expectMinAtLeast("звёзды не вошли друг в друга", "расстояние между центрами звёзд, единиц", 1, settle(0.3), 2.0)
        }
    }
}

/*
 * ТЕЛО В ЩЕЛИ МЕЖДУ ДВУМЯ СТОЛБАМИ. Два неподвижных столба (частицы рельефа) стоят на одной
 * вертикали, у каждого радиус 0.5. Брусок 6×3 летит в щель между ними горизонтально. Расстояние
 * от верхней и нижней кромки бруска (клетки на ±0.6, контур 0.3) до столба — 1.0 при широкой
 * щели (столбы на ±2.0) и 1.0 — при узкой (±1.6): порог касания 0.8, зазор есть.
 * Проверяем, что брусок проходит, не касаясь столбов, и что он не набирает лишней энергии.
 */
private fun xgSlitPosts(family: Family) {
    val brick = Shapes.rect(6, 3)
    for ((tag, half, speed) in listOf(Triple("wide", 2.0, 0.6), Triple("narrow", 1.6, 0.6), Triple("wide-fast", 2.0, 1.2))) {
        family.add("xgeo/slit/$tag/v$speed", "брусок 6×3 пролетает щель между столбами, щель $tag, скорость $speed",
            "Два неподвижных столба стоят на одной вертикали, по одному с каждой стороны от щели (столбы на ±${half} единицы по высоте). " +
                "Брусок летит в щель вправо со скоростью $speed связи за тик.",
            "Брусок проходит между столбами, не касаясь их и не проникая в них; столбы не сдвигаются; " +
                "к концу брусок останавливается, стоит и спит.",
            settle(speed), Limits.INTACT) {
            rock(0.0, half)
            rock(0.0, -half)
            val x0 = -(brick.halfWidth + START_GAP)
            val b = body(brick, x0, 0.0)
            kick(b, speed, 0.0)
            mustMove(b, 6.0, "брусок долетел до столбов")
            probe("центр бруска, вдоль хода, единиц") { centerOf(b)[0] }
            expectMaxAtLeast("брусок прошёл за столбы", "центр бруска, вдоль хода, единиц", 1, settle(speed), 4.0)
        }
    }
}

/*
 * КЛИН В ЩЕЛЬ МЕЖДУ ДВУМЯ КВАДРАТАМИ. Квадраты 8 стоят слева и справа, их внутренние столбцы
 * клеток — на ±0.6 от середины, щель 1.2 единицы. Треугольник 9 (его вершина узкая) летит
 * вершиной вверх в щель снизу. По мере подъёма клин расширяется и раздвигает квадраты.
 * Проверяем, что квадраты расходятся (раздвинуты на ширину клина), а клин не проходит сквозь их ткань.
 */
private fun xgWedge(family: Family) {
    val wedge = Shapes.triangle(9)
    val block = Shapes.square(8)
    for (speed in listOf(0.6, 2.0)) {
        val ticks = settle(speed)
        val limits = if (speed < 1.0) Limits.INTACT else Limits.hit(speed)
        family.add("xgeo/wedge/v$speed", "клин в щель между двумя квадратами, скорость $speed",
            "Два квадрата 8 стоят рядом с узкой щелью между ними. Треугольник-клин летит вершиной вверх в щель " +
                "снизу со скоростью $speed связи за тик.",
            "Клин раздвигает квадраты, но не проходит сквозь их ткань: квадраты расходятся на ширину клина; " +
                "порваться вправе только в пределах допуска; к концу всё успокаивается.",
            ticks, limits) {
            val c = block.halfWidth + GAME_LINK
            val left = body(block, -c, 0.0)
            val right = body(block, c, 0.0)
            val apex = wedge.y.max()
            val w = body(wedge, 0.0, -(block.halfHeight + 0.3 + START_GAP) - apex)
            kick(w, 0.0, speed)
            probe("расстояние между квадратами, единиц") { xgCenterGap(left, right) }
            expectMaxAtLeast("клин раздвинул квадраты", "расстояние между квадратами, единиц", 1, ticks, 2 * c + 1.0)
        }
    }
}

/*
 * ЛЕНТА И БРУСОК ОБВИВАЮТ СТОЛБ. Неподвижный столб — одна частица рельефа в начале координат.
 * Тело висит над ним своей нижней полосой клеток в 2.6 единицы от столба (зазор 1.8 — как START_GAP).
 * Мышь берёт самую нижнюю середину тела и медленно тянет вниз, через столб. Клетка не может пройти
 * сквозь столб, поэтому либо обходит его сбоку, либо проходит под ним: и то и другое — проверка,
 * что столб не пропускает ткань насквозь и не выталкивает клетки внутрь.
 */
private fun xgWrapPost(family: Family) {
    val ribbon = Shapes.ribbon(30)
    val slab = Shapes.rect(14, 4)
    val ticks = 130 + settle(0.5)
    for ((tag, shape) in listOf("лента 2×30" to ribbon, "брусок 14×4" to slab)) {
        family.add("xgeo/wrap/${shape.id}", "$tag обвивает столб, мышь тянет нижнюю середину вниз",
            "Неподвижный столб стоит в центре; тело висит над ним. Мышь берёт самую нижнюю клетку середины и " +
                "тянет её вниз через столб на семь единиц.",
            "Ткань огибает столб и не проходит сквозь него; клетки не выталкиваются внутрь столба; " +
                "тело вправе растянуться, но порваться не больше 10% связей; после отпускания всё успокаивается.",
            ticks, Limits.DRIVEN.copy(name = "внешняя сила, мышь; ткань вправе порваться до 10%", tornShare = 0.1)) {
            rock(0.0, 0.0)
            val yc = 2.6 + shape.halfHeight
            val b = body(shape, 0.0, yc)
            val cell = shape.nearest(0.0, -shape.halfHeight)
            val x0 = shape.x[cell]
            val startY = yc + shape.y[cell]
            val points = (0..40).map { doubleArrayOf(x0, startY - 7.0 * it / 40.0) }
            mousePath(b, cell, 10, 3, points)
            probe("сдвиг нижней клетки от столба, единиц") {
                maxOf(abs(gameX(b.particle(cell)) - x0), -gameY(b.particle(cell)))
            }
            expectMaxAtLeast("лента обогнула столб", "сдвиг нижней клетки от столба, единиц", 1, ticks, 0.8)
        }
    }
}

/*
 * ТОНКИЕ ДЛИННЫЕ ТЕЛА ПОД УГЛОМ. Нить 20 (без треугольников) и лента 2×20 (с треугольниками)
 * летят со скоростью 2.0 связи за тик в стоящий квадрат 8. Поворачиваем тонкое тело на 0°, 30°,
 * 60° и 90°: при 0° удар концом, при 90° удар боком. Тонкое тело — самое податливое: допуск на
 * разрыв 10% связей, сверх этого сцена сама считает ткань порванной.
 */
private fun xgThinAngles(family: Family) {
    val block = Shapes.square(8)
    for (angle in listOf(0.0, PI / 6, PI / 3, PI / 2)) for (thin in listOf(Shapes.rope(20), Shapes.ribbon(20))) {
        val deg = Math.round(angle * 180 / PI)
        val ticks = settle(2.0, slow = !thin.hasTissue)
        family.add("xgeo/thin/${thin.id}/deg$deg", "${thin.name}: удар под углом $deg°, скорость 2.0",
            "Тонкое тело (${thin.name}) повёрнуто на $deg° и летит вправо со скоростью 2.0 связи за тик в стоящий квадрат 8.",
            "Удар приходится то концом, то боком. Тонкое тело не проходит сквозь квадрат; клетки не оказываются " +
                "в чужой ткани; порваться вправе не больше 10% связей; энергия не растёт; к концу всё стоит и спит.",
            ticks, Limits.hit(2.0).copy(name = "удар 2.0; тонкое тело вправе порваться до 10%", tornShare = 0.1)) {
            val (_, target) = duel(thin, block, 2.0, angleA = angle)
            expectPushed(target, 2.0, ticks, share = 0.05, hitterCells = thin.count)
        }
    }
}

/*
 * КОЛЬЦО, СЖАТОЕ СНАРУЖИ ЧЕТЫРЬМЯ ТЕЛАМИ. Кольцо 7/4 стоит в центре, с четырёх сторон к нему
 * летят квадраты 6 — с каждой стороны по одному. Расстояние до кольца — его радиус плюс три связи
 * зазора, так что на старте никто никого не касается. Проверяем, что каждый квадрат доходит до
 * кольца (остановлен его тканью), а кольцо не пропускает ни один квадрат внутрь своей дыры.
 */
private fun xgSqueezeRing(family: Family) {
    val ring = Shapes.ring(7, 4)
    val pad = Shapes.square(6)
    for (speed in listOf(0.6, 2.0)) {
        val ticks = settle(speed)
        val limits = if (speed < 1.0) Limits.INTACT else Limits.hit(2.0 * speed)
        family.add("xgeo/squeeze/ring-four/v$speed", "кольцо сжато четырьмя квадратами, скорость $speed",
            "Кольцо 7/4 стоит в центре; с четырёх сторон к нему летят квадраты 6, каждый со скоростью $speed связи за тик.",
            "Квадраты встречаются с кольцом, но не входят в его дыру и не проходят сквозь его ткань; " +
                "к концу всё успокаивается и засыпает.",
            ticks, limits) {
            val d = ring.reach + START_GAP + pad.reach
            val r = body(ring, 0.0, 0.0)
            val dirs = arrayOf(doubleArrayOf(1.0, 0.0), doubleArrayOf(-1.0, 0.0), doubleArrayOf(0.0, 1.0), doubleArrayOf(0.0, -1.0))
            for ((i, dir) in dirs.withIndex()) {
                val b = body(pad, dir[0] * d, dir[1] * d)
                kick(b, -dir[0] * speed, -dir[1] * speed)
                expectMet(b, r, ticks, 2.0 * speed, "зазор до кольца, сторона ${i + 1}, связей")
            }
        }
    }
}

/*
 * ТОНКИЙ БРУСОК В ЩЕЛИ МЕЖДУ ДВУМЯ КВАДРАТАМИ. Квадраты 8 стоят слева и справа, их внутренние
 * столбцы клеток — на ±1.2 единицы от середины щели. Брусок 2×10 (клетки на ±0.3) летит вверх
 * через щель. Зазор до внутренних столбцов — 0.9, порог касания 0.6: брусок проходит, не касаясь.
 * Квадраты при этом стоят на месте — проверяем, что проход через щель их не раздвигает.
 */
private fun xgSlitBlocks(family: Family) {
    val block = Shapes.square(8)
    val thin = Shapes.rect(2, 10)
    for (speed in listOf(0.6, 2.0)) {
        val ticks = settle(speed)
        family.add("xgeo/slit-blocks/v$speed", "тонкий брусок проходит щель между двумя квадратами, скорость $speed",
            "Два квадрата 8 стоят слева и справа с узкой щелью между ближайшими столбцами клеток (1.2 единицы). " +
                "Брусок 2×10 летит вверх через щель со скоростью $speed связи за тик.",
            "Брусок проходит через щель, не касаясь квадратов; квадраты стоят на месте; к концу всё стоит и спит.",
            ticks, Limits.INTACT) {
            val c = block.halfWidth + 1.2
            val left = body(block, -c, 0.0)
            val right = body(block, c, 0.0)
            val y0 = -(block.halfHeight + 0.3 + START_GAP + thin.halfHeight)
            val top = block.halfHeight + thin.halfHeight + 1.0
            val b = body(thin, 0.0, y0)
            kick(b, 0.0, speed)
            probe("центр бруска, вверх, единиц") { centerOf(b)[1] }
            expectMaxAtLeast("брусок прошёл щель", "центр бруска, вверх, единиц", 1, ticks, top)
            probe("расстояние между квадратами, единиц") { xgCenterGap(left, right) }
            expectMaxAtMost("квадраты не раздвинуло", "расстояние между квадратами, единиц", 1, ticks, 2 * c + 1.0)
        }
    }
}

/*
 * КРУГ ЛЕТАЕТ ВНУТРИ РАМКИ, ПОКА РАМКУ ВРАЩАЮТ. Рамка 11 со стенкой 2: внутренний свет
 * ±2.4 единицы от центра, круг радиуса 1.2 в центре, зазор до стенки 1.2. Рамку крутят вокруг
 * её центра (0.05 и 0.15 радиана за тик), круг получает скорость 0.6 связи за тик. Проверяем, что
 * круг, отскакивая от вращающихся стенок, остаётся внутри: его центр не дальше 2.0 единицы от
 * центра рамки (в углах он может быть до 1.7, допуск 0.3).
 */
private fun xgFrame(family: Family) {
    val frame = Shapes.frame(11, 2)
    val disc = Shapes.disc(2)
    for (spin in listOf(0.05, 0.15)) {
        family.add("xgeo/frame/spin$spin", "круг летает внутри рамки, рамку вращают $spin рад за тик",
            "Рамка 11 со стенкой 2 вращается вокруг своего центра; круг 2 внутри получает скорость 0.6 связи " +
                "за тик вправо и 0.3 вверх.",
            "Круг отскакивает от стенок изнутри и остаётся в рамке: сквозь стенку не проходит; рамка не рвётся; " +
                "к концу рамка перестаёт крутиться, засыпает; круг остаётся внутри.",
            settle(0.6), Limits.INTACT) {
            val f = body(frame, 0.0, 0.0)
            val c = body(disc, 0.0, 0.0)
            kick(f, 0.0, 0.0, spin = spin)
            kick(c, 0.6, 0.3)
            probe("круг от центра рамки, единиц") { xgCenterGap(c, f) }
            expectMaxAtMost("круг остался в рамке", "круг от центра рамки, единиц", 1, settle(0.6), 2.0 * Variation.current.spread)
        }
    }
}

/*
 * РАЗОМКНУТОЕ КОЛЬЦО НАДЕТО НА СТОЛБ. Кольцо 7/4 с разрезом справа стоит вокруг неподвижного
 * столба в центре. Столб — внутри дыры (радиус 2.4), и разрез смотрит вправо. Толкаем кольцо
 * вправо: столб оказывается у его левой, сплошной стенки и должен её остановить. Сквозь разрез
 * столб выйти не может, ведь кольцо едет вправо, а разрез — тоже справа. Проверяем, что кольцо
 * проехало не дальше 2.6 единицы: по расчёту стенка упрётся примерно через 1.6.
 */
private fun xgCRingPost(family: Family) {
    val hook = Shapes.cShape(7, 4)
    for (speed in listOf(0.6, 2.0)) {
        family.add("xgeo/c-ring/post/v$speed", "разомкнутое кольцо на столбе, толкнули в сплошную стенку, скорость $speed",
            "Разомкнутое кольцо 7/4 с разрезом справа стоит вокруг неподвижного столба в центре. " +
                "Кольцо толкают вправо со скоростью $speed связи за тик: столб упирается в его левую, сплошную стенку.",
            "Столб останавливает кольцо: столб не уходит в стенку глубже её середины и не проходит сквозь неё; " +
                (if (speed < 1.0) "ничего не рвётся; к концу всё стоит и спит."
                else "стенка вправе порваться в пределах допуска; клетки не входят друг в друга."),
            settle(speed), if (speed < 1.0) Limits.INTACT else Limits.hit(speed)) {
            rock(0.0, 0.0)
            val r = body(hook, 0.0, 0.0)
            val start = centerOf(r)[0]
            kick(r, speed, 0.0)
            probe("кольцо уехало вправо, единиц") { centerOf(r)[0] - start }
            // Дыра — 4 связи (2.4 единицы), стенка — 3 связи (1.8): середина стенки — в 3.3 единицы хода. Прежние 2.6 были
            // оценкой без запаса на упругий прогиб разомкнутой стенки (замер 15.11: 2.8 при скорости 0.6, правила молчат).
            expectMaxAtMost("столб остановил кольцо", "кольцо уехало вправо, единиц", 1, settle(speed), 3.3 * Variation.current.spread)
        }
    }
}

/*
 * ГАНТЕЛЬ ПЕРЕМЫЧКОЙ НА СТОЛБ. Неподвижный столб стоит под перемычкой на 2.8 единицы ниже её
 * (зазор до клетки перемычки 2.0, порог касания 0.8). Гантель летит вниз, перемычка идёт на
 * столб посередине; круги в стороне от столба и сами по нему не ударяют. Проверяем, что столб
 * останавливает перемычку: центр гантели не опускается дальше 3.5 единицы от старта, и тонкая
 * перемычка не проходит сквозь столб.
 */
private fun xgBridgePost(family: Family) {
    val db = Shapes.dumbbell(3, 6, 1)
    for (speed in listOf(0.6, 2.0)) {
        val ticks = settle(speed)
        val limits = if (speed < 1.0) Limits.INTACT
        else Limits.hit(speed).copy(name = "удар $speed; перемычка вправе порваться до 10%", tornShare = 0.1)
        family.add("xgeo/bridge/post/v$speed", "гантель перемычкой на столб, скорость $speed",
            "Гантель с перемычкой в одну клетку летит вниз со скоростью $speed связи за тик; под её серединой " +
                "стоит неподвижный столб.",
            "Перемычка упирается в столб, огибает его или (на большой скорости, в пределах допуска) рвётся об него; " +
                "сквозь столб ничто не проходит; к концу всё стоит и спит.",
            ticks, limits) {
            rock(0.0, -(START_GAP + 1.0))
            val b = body(db, 0.0, 0.0)
            val start = centerOf(b)[1]
            kick(b, 0.0, -speed)
            // Только проба, без ожидания. Прежнее «центр не опускается дальше 3.5» спорило с самим описанием: гантель
            // на одном столбе стоит неустойчиво и законно съезжает вбок (замер 15.11: 5.2 единицы при скорости 0.6),
            // а при скорости 2 клетка перемычки гибнет об столб в пределах допуска, и половины летят дальше (65 единиц).
            // Проход сквозь столб ловят общие правила «ничто не входит в рельеф» и «никто не проходит сквозь ткань».
            probe("опускание центра гантели, единиц") { start - centerOf(b)[1] }
        }
    }
}
