/*
 * СЕМЕЙСТВО «НЕОБЫЧНАЯ ГЕОМЕТРИЯ». Остальные семейства бьют тело в тело или в стену. Здесь фигуры
 * зацепляются друг за друга или за столб: кольцо в кольце, подкова в подкове, мост в одну клетку,
 * звёзды лучами, клин в щели, тонкие длинные тела под углом. Что такие сцены ловят: клетка не
 * оказывается внутри чужой ткани или столба, тонкая перемычка не проходит сквозь препятствие и
 * не рвётся раньше допуска, а тело, которое протиснулось в щель, не получает лишней энергии.
 *
 * Расстановка — арифметикой по связям (связь 0.6 единицы, порог касания 0.6): между ближайшими
 * клетками разных тел на старте всегда больше порога. Числа расписаны в комментарии у каждой серии.
 */

/** Расстояние между центрами двух тел, единиц игры. */
private fun StandWorld.xgCenterGap(a: StandBody, b: StandBody): Double {
    val p = centerOf(a)
    val q = centerOf(b)
    return hypot(p[0] - q[0], p[1] - q[1])
}

/** Расстояние между двумя точками, в связях. */
private fun xgLinks(p: DoubleArray, q: DoubleArray): Double = hypot(q[0] - p[0], q[1] - p[1]) / GAME_LINK

