    /// Учёт импульса за тик под нынешнее число частиц: после дописывания тела заводится заново (`tickMomentum`).
    pub fn tick_momentum(&mut self) -> &mut TickMomentum {
        let fresh = match &self.tick_momentum_state {
            Some(t) => t.n != self.n,
            None => true,
        };
        if fresh {
            self.tick_momentum_state = Some(TickMomentum::new(self.n, SPIN_MIN_ARM * self.link_scale));
        }
        self.tick_momentum_state.as_mut().unwrap()
    }

    /// Учёт отдельно от состояния: стадиям, которые пишут и в учёт, и в массивы частиц. Вернуть — [put_tick_momentum].
    pub fn take_tick_momentum(&mut self) -> TickMomentum {
        self.tick_momentum();
        self.tick_momentum_state.take().unwrap()
    }

    pub fn put_tick_momentum(&mut self, t: TickMomentum) {
        self.tick_momentum_state = Some(t);
    }

    pub fn clear_death_logs(&mut self) {
        self.edge_death_n = 0;
        self.cell_death_n = 0;
    }

    /// `isFixed` (FreeParticles.kt): частица закреплена навсегда.
    #[inline]
    pub fn is_fixed(&self, i: usize) -> bool {
        self.rest_inv_mass[i] == 0.0
    }

