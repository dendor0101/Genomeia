//! Состояние решателя — `model/BodyState.kt` (float, 26.11.2026), без отладочных замеров (`dbg*`, таймеры стадий,
//! журналы для окна) и без островов (`island*`, `scope*`): на мир они не влияют, биты от островов не зависят.
//!
//! ОТЛИЧИЯ РАСКЛАДКИ ОТ KOTLIN (поведение то же):
//! - Kotlin держит общие ссылки на одни массивы из нескольких объектов (LocalSurface.free — это BodyState.isFree,
//!   BoundaryContacts.pressure — contactPressure и т. п.). Здесь у каждого массива один хозяин — BodyState, а
//!   вспомогательные структуры получают его параметром.
//! - `boundA/boundB/boundOpp/boundCount`, `bend*`, `flap*` после первой сборки в Kotlin — ссылки на массивы
//!   LocalBoundaryConstraints (`syncBoundaryArrays`). Здесь код решателя читает `local_boundary` напрямую. Свой список
//!   контура (`bound_*`) — только то, что строит `buildBoundary` для сборки касаний; `buildBend` и `buildFlaps` пишут
//!   списки, которые до первого чтения заменяет синхронизация, — поэтому не переносятся.
//! - `InternalMomentum` и план связей `DistanceSweepOrder` в тике игры не участвуют (только заводятся) и не переносятся.
//! - Учёт импульса заводится заново при смене числа частиц (`tickMomentum`-геттер Kotlin) — `tick_momentum()`.

