package io.github.some_example_name.old.systems.render

import java.util.concurrent.atomic.AtomicInteger

/**
 * Тройной буфер без блокировок: один пишущий поток (симуляция), один читающий (рендер).
 *
 * ЗАЧЕМ ТРИ, А НЕ ДВА
 * -------------------
 * С двумя буферами писатель после публикации сразу начинает писать в тот, который только
 * что отдал читателю, — в прошлый «передний». Если читатель ещё не дочитал его (кадр
 * длиннее тика, или экран и симуляция просто попали в такт неудачно), он получает
 * половину байт одного тика и половину другого: клетки одного организма из разных
 * моментов, оверлей поверх чужих позиций. Ровно так и было до тройного буфера, и при
 * любом соотношении FPS/UPS, кроме удачного, это рано или поздно случалось.
 *
 * С тремя слотами у каждого своя роль, и ни один слот не принадлежит двоим сразу:
 *   - задний — в него пишет симуляция;
 *   - готовый — последний опубликованный, его ещё никто не взял;
 *   - передний — его читает рендер, сколько бы кадров подряд он его ни рисовал.
 *
 * Публикация меняет местами задний и готовый, взятие — готовый и передний. Оба обмена —
 * один getAndSet над [ready], поэтому соотношение частот любое: симуляция в 1000 тиков в
 * секунду перезаписывает готовый слот, не дожидаясь рендера, а рендер в 144 кадра просто
 * рисует передний снова, пока нового нет. Читатель всегда получает самый свежий целый
 * снимок, писатель никогда не ждёт.
 *
 * ВИДИМОСТЬ
 * ---------
 * getAndSet у AtomicInteger — полный барьер: всё, что писатель записал в слот до
 * [publish], видно читателю после [acquire], который этот слот получил. Поэтому в самих
 * снимках нет ни volatile, ни атомиков — обычные поля и массивы.
 *
 * Поля [back] и [front] принадлежат каждое своему потоку и меняются раз в тик и раз в
 * кадр: делить ли им кэш-линию, неважно, разнос на 64 байта здесь ничего бы не дал.
 */
class TripleBuffer<T : Any>(first: T, second: T, third: T) {

    private val slots: Array<Any> = arrayOf(first, second, third)

    /** Номер готового слота в младших битах и флаг [DIRTY]: его опубликовали, но ещё не взяли. */
    private val ready = AtomicInteger(1)

    /** Слот писателя. Трогает только поток симуляции. */
    private var back = 0

    /** Слот читателя. Трогает только поток рендера. */
    private var front = 2

    /** Писатель: слот, в который собирать следующий снимок. */
    @Suppress("UNCHECKED_CAST")
    fun back(): T = slots[back] as T

    /** Писатель: снимок в [back] собран — сделать его готовым, а прежний готовый взять под запись. */
    fun publish() {
        val previous = ready.getAndSet(back or DIRTY)
        back = previous and INDEX_MASK
    }

    /**
     * Читатель: взять самый свежий опубликованный снимок, если с прошлого вызова вышел
     * новый. true — [front] теперь другой слот; false — нового нет, [front] прежний.
     */
    fun acquire(): Boolean {
        // Снять DIRTY может только читатель, поэтому раз он виден здесь, getAndSet ниже
        // получит опубликованный слот — этот же или ещё более свежий.
        if (ready.get() and DIRTY == 0) return false
        val published = ready.getAndSet(front)
        front = published and INDEX_MASK
        return true
    }

    /** Читатель: слот, взятый последним [acquire]. Писатель в него не пишет, пока его не отдадут. */
    @Suppress("UNCHECKED_CAST")
    fun front(): T = slots[front] as T

    private companion object {
        const val INDEX_MASK = 3
        const val DIRTY = 4
    }
}
