package io.github.some_example_name.old.core

/**
 * Отладочные проверки в горячих путях симуляции.
 *
 * Именно const val, а не val и не поле: kotlinc подставляет константу на месте, поэтому
 * при false вся конструкция `if (DEBUG_CHECKS && ...)` выкидывается ещё на этапе
 * компиляции. В байткоде не остаётся ни ветки, ни вычисления условия, ни создания
 * строки сообщения — то есть в релизе такие проверки стоят ровно ноль.
 *
 * Что это даёт горячему коду:
 *  - меньше байткода → метод помещается в лимиты инлайнинга JIT
 *    (FreqInlineSize = 325 байт; repulse и processCell к нему близки);
 *  - нет `throw` внутри цикла, а значит нет обработчиков исключений, мешающих
 *    оптимизациям, и нет лишних записей в таблицу исключений;
 *  - предсказателю ветвлений не нужно держать запись на всегда-ложное условие.
 *
 * Включать вручную при отладке физики или NaN-ов и пересобирать.
 */
const val DEBUG_CHECKS = false

/**
 * Запись профиля тика в консоль и в CSV-файл (sim_profile.csv рядом с рабочей директорией).
 *
 * Само измерение фаз через System.nanoTime идёт всегда — оно нужно для таблицы на экране
 * и стоит ~0.6 мкс на тик (24 вызова nanoTime при тике в тысячи микросекунд). Этот флаг
 * управляет только выводом: строка в лог раз в PROFILE_WINDOW_TICKS тиков плюс сбор
 * статистики занятости сетки в GridManager.rebuild.
 */
const val PROFILE_LOG = false

/**
 * Счётчики объёма работы широкой фазы: пары-кандидаты, реальные пересечения, пропуски
 * по связанности клеток, вызовы onContact.
 *
 * Зачем все четыре, а не только пары: время фазы это сумма трёх разных путей внутри
 * repulse (ранний выход, пересечение без контакта, пересечение с onContact), у которых
 * цена отличается на порядок. Зная объём каждого пути на многих замерах с разным
 * соотношением, можно разложить время фазы по путям и понять, что именно оптимизировать.
 * По одному только числу пар это неразличимо.
 *
 * PAIR_CANDIDATES считается НЕ в repulse, а арифметикой по границам клеток CSR (~4 лишних
 * чтения на непустую клетку). Остальные три инкрементируются в repulse — иначе никак,
 * но каждый инкремент это одна запись в кэш-линию, которой владеет только этот поток,
 * то есть 1-2 такта против ~100 тактов стоимости вызова.
 */
const val PROFILE_COUNTERS = false

/**
 * Замер занятости воркеров внутри параллельной стадии.
 *
 * Время стадии по стенным часам не отличает "вызов дорогой" от "один воркер тащил всё,
 * остальные стояли на барьере". Каждый воркер накапливает своё время внутри drain(),
 * главный поток — время стадии целиком; отношение суммы к (воркеры * стадия) и есть
 * КПД распараллеливания. Стоимость: два nanoTime на воркера на стадию, то есть порядка
 * сотни вызовов за тик — микросекунды при тике в единицы миллисекунд.
 */
const val PROFILE_UTILIZATION = false

/** Длина окна усреднения профиля в тиках. При ~145 UPS это примерно одна строка в секунду. */
const val PROFILE_WINDOW_TICKS = 120

/**
 * Жёсткое ограничение числа воркеров. 0 — как раньше, по availableProcessors().
 *
 * Зачем: число ПРОСТРАНСТВЕННЫХ СЛОТОВ задаётся геометрией мира ((gridHeight/chunkHeight)/2),
 * и при переходе сетки 128 -> 256 оно удваивается с 8 до 16. availableProcessors() на машине
 * с SMT возвращает число ЛОГИЧЕСКИХ ядер (на 8-ядерном Ryzen — 16), поэтому воркеров тоже
 * стало бы 16, по два на физическое ядро. Для спинящих воркеров это плохо вдвойне: они
 * делят один L1/L2 и при этом жгут такты в спин-петле, отбирая их у SMT-соседа, которого
 * же и ждут.
 *
 * Слотов при этом МОЖЕТ быть больше, чем воркеров, и это только на пользу: динамическая
 * раздача начинает реально балансировать нагрузку (см. комментарий в ThreadManager).
 *
 * Ставить равным числу ФИЗИЧЕСКИХ ядер. Отдельно полезно прогнать замер с override = 16
 * на 256-й сетке и сравнить: это прямой ответ на вопрос, помогает ли здесь SMT.
 */
const val WORKER_COUNT_OVERRIDE = 8
