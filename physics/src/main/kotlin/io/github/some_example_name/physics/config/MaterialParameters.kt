package io.github.some_example_name.physics

/**
 * НЕ СТАВИТЬ В НОЛЬ. Ноль раскручивает организм при сокращении мышцы.
 *
 * Сокращение мышцы — воздействие ВНУТРЕННЕЕ, и в точной арифметике оно сохраняет
 * и импульс, и момент: поправка ограничения расстояния идёт вдоль связи, значит
 * плечо у неё нулевое, а поправки площади и проекции кости в сумме дают ноль.
 * Проверено по стадиям — все три действительно сохраняющие.
 *
 * Течёт float. В равновесии невязка `len - rest` это чистое округление float32,
 * порядка 1e-7. При alpha = 0 поправка равна `-(len - rest) / w`, и дальше
 * updateVelocities умножает её на 1/h = 1152. То есть шум округления попадает
 * в скорости с усилением в 1152 раза и копится в настоящий момент импульса.
 *
 * Ненулевая податливость его отфильтровывает: alpha = compliance/h^2 = 1e-4 * 1152^2
 * это 132 против w = 2 в знаменателе, то есть та же невязка даёт поправку в 66 раз
 * меньше. Замер на этом теле, гравитация 0, без вязкости и сопротивления среды,
 * мышца 0 сокращена, 600 кадров:
 *
 *     compliance = 0       ->  момент  -896   (омега около -10 рад/с, видимая раскрутка)
 *     compliance = 1.0e-4  ->  момент   +12   (омега около 0.14 рад/с)
 *
 * Разница в 75 раз. То же самое относится и к движку: compliance = 0 в XPBD на
 * float32 при большом числе подшагов — это усилитель собственного шума, а не
 * «максимальная жёсткость даром».
 */
/**
 * Податливость угла лоскута. Мягче обычной связи: это не форма тела, а
 * страховка от схлопывания в точку, и жёсткой ей быть незачем.
 */
const val FLAP_COMPLIANCE = 1.0e-4

const val SOFT_COMPLIANCE = 1.0e-5

/**
 * ТОЖЕ НЕ СТАВИТЬ В НОЛЬ, по той же причине, что и SOFT_COMPLIANCE.
 *
 * Тут долго стоял ноль — при том что у SOFT_COMPLIANCE прямо написано, что ноль
 * усиливает шум float32. Ограничение площади ровно так же на этом стоит, только
 * утечка у него не линейная, а УГЛОВАЯ: градиент площади направлен по нормали к
 * противолежащей стороне, плечо у него не нулевое, и остаточная невязка уходит
 * не в дрейф, а в РАСКРУТКУ тела.
 *
 * Замер, 600 кадров удержания мышцы, суммарный r x dx по стадии (идеал — ноль):
 *
 *     AREA_COMPLIANCE = 0       ->  +3.4e-03   момент тела L = +1.28
 *     AREA_COMPLIANCE = 3.0e-7  ->  -2.6e-04   L = -0.096      в 13 раз меньше
 *
 * Заодно падает и утечка ограничения РАССТОЯНИЯ (-1.3e-3 -> +9.2e-5): жёсткая
 * площадь подкидывала шум ему на вход.
 *
 * ВЕЛИЧИНА. Сравнивать надо не с SOFT_COMPLIANCE, а со знаменателем своей стадии:
 * у расстояния это w = 2, у площади это сумма w*|grad|^2, то есть порядка
 * 3 * 0.045^2 = 6e-3, в триста раз меньше. Поэтому и податливость должна быть
 * во столько же раз меньше — 1e-4 здесь запёрло бы ткань наглухо.
 *
 * Развёртка (кость уже починена), метрика — ПОВТОРЯЕМОСТЬ гребка, разброс шага
 * центра масс по 6 одинаковым циклам, и тяга за цикл:
 *
 *          0     разброс 6.1%   тяга 0.194
 *      1e-08     разброс 3.8%   тяга 0.180
 *      1e-07     разброс 2.8%   тяга 0.156
 *      3e-07     разброс 2.4%   тяга 0.144
 *      1e-06     разброс 1.0%   тяга 0.137   <- стоит сейчас
 *      3e-06     разброс 4.0%   тяга 0.135
 *      1e-05     разброс 3.3%   тяга 0.133
 *
 * Тяга падает монотонно и полого, разброс имеет чёткий минимум на 1e-6. Часть
 * потерянной «тяги» тягой и не была: при нуле тело вдобавок само раскручивалось,
 * и метрика записывала это себе в плюс.
 */
const val AREA_COMPLIANCE = 1.0e-6

/**
 * Податливость площади для ВЫВЕРНУТЫХ треугольников — отдельная и НУЛЕВАЯ.
 *
 * Лечит застревание сложенной ткани. Ограничение площади вывернутый треугольник
 * выправлять УМЕЕТ: restArea2 положительна, area2 знаковая, значит цель это
 * +restArea2, и для вывернутого невязка огромна, а знак поправки правильный.
 * Мешала ему ровно та податливость, которую мы поставили ради честности счёта:
 * при alpha = 1e-6 знаменатель (denom + alpha) больше самого denom в 55 раз, и
 * выправляющая поправка слабеет во столько же.
 *
 * ПОЧЕМУ РАЗДЕЛЯТЬ ЗАКОННО, а не подгонка. Податливость нужна, чтобы не усиливать
 * шум float32 РЯДОМ С РАВНОВЕСИЕМ: там невязка это чистое округление, и жёсткое
 * ограничение раздувает его в 1/h раз. Вывернутый треугольник от равновесия
 * бесконечно далеко — его невязка порядка удвоенной площади покоя, на четыре
 * порядка больше шума. Фильтровать там нечего, мягкость только вредит. Как только
 * треугольник вывернулся обратно, он снова попадает в мягкую ветку.
 *
 * ЗАМЕР (стенд FoldRecovery: ткань складывается зеркалом, мышцы не активны,
 * считаются вывернутые треугольники; было 399 и 478 сразу после складывания):
 *
 *      сложено 50%                   сразу  0.4с   2с    8с   35с
 *      площадь 1e-6 всем (было)        399    18    2     2     1   ЗАСТРЯЛО
 *      площадь 0 всем                  399     0    0     0     0
 *      раздельно (стоит сейчас)        399     4    0     0     0
 *
 *      сложено 75%
 *      площадь 1e-6 всем (было)        478    14    3     1     1   ЗАСТРЯЛО
 *      раздельно (стоит сейчас)        478     7    0     0     0
 *
 * Единица в последнем столбце и есть та самая застрявшая складка: за 35 секунд
 * она не расходится и дальше не разойдётся. «Площадь 0 всем» её тоже лечит, но
 * возвращает угловую утечку, ради которой податливость и вводилась (замер у
 * AREA_COMPLIANCE: r x dx вырастает с -2.6e-04 до +3.4e-03). Раздельная ветка
 * даёт и то и другое: честное равновесие и распрямление складки.
 *
 * НА ПОЛНОМ КОНВЕЙЕРЕ СТАЛО ЛУЧШЕ И ПО ВРАЩЕНИЮ ТОЖЕ (PhysicsAudit, тест 3,
 * мышца держится сокращённой 2400 кадров):
 *
 *                      вывернутых на 200   на 2400    omega на 2400
 *      было                    7             18          +3.24e-03
 *      раздельно               0              0          +1.08e-04
 *
 * Прежние 18 не просто были — они ЗАСТРЕВАЛИ и не уходили до конца прогона.
 * Теперь их нет вовсе, и вращение заодно в 30 раз меньше: выправленная ткань
 * перестаёт дёргаться, а дёргалась она и подкручивала тело именно из-за складок.
 *
 * ОГОВОРКА, чтобы не удивляться показаниям стенда. В ТЕСТЕ 1 (внешних сил нет
 * вообще, ни вязкости, ни среды) эта ветка даёт угловую утечку заметно ХУЖЕ:
 * omega -0.276 против -1.4e-02. Там ткань без диссипации разбалтывается,
 * вывернутых треугольников становятся десятки и они не уходят, а жёсткая ветка
 * каждому выдаёт большую поправку. Это режим диагностический, а не рабочий:
 * стоит вернуть вязкость и среду, как вывернутых становится ноль и знак выгоды
 * меняется на противоположный. Но если в движке вязкость будет заметно ниже —
 * этот замер стоит повторить, ветка чувствительна именно к числу одновременно
 * вывернутых треугольников.
 */
const val AREA_COMPLIANCE_INVERTED = 0.0

/**
 * ПОТОЛОК на длину поправки одного треугольника за подшаг, в долях средней связи.
 * 0 — выключено.
 *
 * Лечит РЫВОК при распрямлении складки. Жёсткая ветка выправляет вывернутый
 * треугольник за один подшаг ЦЕЛИКОМ, а updateVelocities делит это смещение на
 * h = 1/576 и превращает в скорость, которой взяться неоткуда: ткань выстреливает
 * и потом долго колеблется. Потолок силу не трогает — он растягивает выправление
 * на несколько подшагов.
 *
 * Считается дёшево: длина всей поправки треугольника это |dL| * sqrt(denom), а
 * denom на руках уже есть.
 *
 * ЭТО РУЧКА «ПЛАВНОСТИ», и вот её замер (складка 50%, 8 секунд):
 *
 *      потолок     пик |v|   пик KE   перещёлк.   кадров до нуля
 *      нет           38.4    19969       555            63
 *      0.5           24.2     9613       693            28
 *      0.2           18.6     4663       405            12   <- стоит сейчас
 *      0.05           9.0     1300       423           147
 *
 * Для сравнения, прежнее мягкое поведение давало пик |v| 6.8 и KE 735 — самое
 * гладкое из всех, но складка не расходилась НИКОГДА. Вот против чего торгуемся.
 *
 * Хотите ещё глаже — ставьте 0.05: рывок падает почти до прежнего уровня
 * (KE 1300 против 735), но распрямление растягивается с 12 кадров до 147, то есть
 * до секунды. Если правило «не выпрямился за N тиков — рвём ткань» будет
 * настроено жёстко, этот порог придётся поднимать вместе с потолком.
 */
const val AREA_MAX_STEP = 0.2

/**
 * Плавный переход между мягкой и жёсткой ветками площади вместо ступеньки.
 *
 * Лечит ДРЕБЕЗГ. Ступенька означает разрыв жёсткости в 55 раз ровно на нулевой
 * площади, и треугольник, болтающийся около неё, каждый подшаг попадает то в
 * одну ветку, то в другую. Замер числа перещёлкиваний знака площади за
 * распрямление: 895 со ступенькой против 405 с плавным переходом при том же
 * потолке 0.2, то есть вдвое меньше. Заодно распрямление идёт быстрее (12 кадров
 * против 13) — ткань не тратит время на дрожь около нуля.
 *
 * Форма перехода квадратичная по доле площади: t = clamp(area2/restArea2, 0, 1),
 * alpha = alphaInv + (alpha - alphaInv) * t^2. Квадрат, а не линия, чтобы
 * жёсткость нарастала не сразу и почти вырожденные треугольники (площадь близка
 * к нулю, но ещё положительна) тоже получали защиту — так они реже успевают
 * вывернуться вообще.
 */
const val AREA_SMOOTH_RAMP = true

/**
 * ПОТОЛОК НА СМЕЩЕНИЕ ВЕРШИНЫ ПРОЕКЦИЕЙ КОСТИ за подшаг, в долях средней связи.
 *
 * НУЖЕН НЕ ДЛЯ ПЛАВНОСТИ, А ДЛЯ КОРРЕКТНОСТИ КОЛЛИЗИЙ. Широкую фазу в движке
 * правильно строить РАЗ В ТИК и расширять радиус запроса на максимальный путь
 * за тик, `v_max * dt`. Эта оценка верна только пока каждая стадия, двигающая
 * позиции напрямую, ограничена сверху: у площадей есть AREA_MAX_STEP, у тяги
 * MAX_DRAG_SPEED, у ограничения расстояния поправка не больше собственной
 * невязки. А проекция кости не ограничена ничем и может дёрнуть вершину сколь
 * угодно далеко, если кость разошлась с позой покоя, — например после удара.
 * Тогда частица проскочит мимо построенной сетки, и контакт будет потерян.
 *
 * ЗНАЧЕНИЕ. 0.5 средней связи выбрано намеренно с запасом: в обычной работе
 * кость от позы покоя почти не отходит, и потолок не срабатывает вовсе. Это
 * проверяется побитовой сверкой в SwimTuner — если бы он срабатывал, копия
 * разошлась бы с демо. Плюс счётчик boneCapHits в HUD показывает, сколько раз
 * он вмешался: у здорового тела там ноль, ненулевое значит удар или разрыв.
 *
 * Ограничение НЕ ломает сохранение импульса: масштабируется весь набор поправок
 * одним множителем, а их сумма уже обнулена — ноль остаётся нулём.
 */
/**
 * ПРОБОВАЛ СНИЗИТЬ ДО 0.25 — СТАЛО ХУЖЕ, оставлено 0.5.
 *
 * Рассуждение было такое: потолок поправки за подшаг превращается в потолок
 * скорости умножением на число подшагов, 0.5 при 16 подшагах даёт ровно 8
 * клеток за тик, то есть впритык к MAX_SPEED_CELLS_PER_TICK. Логика верна
 * для контакта, где она и сработала, но здесь замер её опроверг: при тряске
 * за кость пик вырос с 8.5 до 9.5, а срабатываний clampSpeed стало вдвое
 * больше, 8 против 4.
 *
 * Причина в том, что кость с меньшим шагом ХУЖЕ СХОДИТСЯ к жёсткой позе,
 * ошибка накапливается, и разбирать её приходится связям вокруг — а они
 * дают поправки крупнее той, что мы сэкономили. Пик у мягкой ткани, а не у
 * самой кости.
 */
const val BONE_MAX_STEP = 0.5

/**
 * ТОТ ЖЕ ПОТОЛОК, НО ДЛЯ ЖЁСТКОЙ СТАДИИ ПРЕДЕЛА ДЛИНЫ. Отдельная константа.
 *
 * Раньше обе стадии делили одно число, и это была ошибка: у них разные задачи.
 * Контакту потолок обязан быть НЕ МЕНЬШЕ хода клетки за подшаг, иначе клетка
 * физически не может быть остановлена. Стадии предела длины наоборот нужен
 * потолок ПОМЕНЬШЕ: она снимает перерастяжение целиком за один подшаг, и
 * updateVelocities делит поправку на крошечное h.
 *
 * ЗАМЕР, ПОЧЕМУ ИХ НЕЛЬЗЯ ДЕРЖАТЬ РАВНЫМИ. Поднятие общего числа с 0.25 до 0.5
 * лечило протаскивание клетки рукой, но ломало таран двух тел навстречу: они
 * проходили друг сквозь друга на 2.34 связи при пределе 1.0, а на 0.375 — на
 * 101 связь. Виновата была именно стадия длины: ослабленная, она на удар
 * отвечает выбросом скорости, и тела продавливаются. Разделённые, обе дают
 * 27/27 и ноль подшагов внутри ткани.
 */
val LINK_MAX_STEP = 0.25

/**
 * МАКСИМАЛЬНОЕ РАСТЯЖЕНИЕ СВЯЗИ в долях её СОБСТВЕННОЙ ДЛИНЫ ПОКОЯ.
 *
 * В стенде связь БЕСКОНЕЧНО КРЕПКАЯ: при достижении предела она жёстко
 * ограничивается, податливость ноль. В движке это же условие — сигнал к
 * РАЗРЫВУ связи; здесь рвать нечем, поэтому держим.
 *
 * РАНЬШЕ СЧИТАЛОСЬ ОТ СУММЫ РАДИУСОВ, и это было ошибкой того же рода, что
 * и радиус контакта: радиус клетки рисовальный, его задаёт игрок в редакторе,
 * и к длине связи он отношения не имеет. В теле с клетками 0.5 и 0.2 при шаге
 * решётки 0.6 предел для пары мелких выходил 0.4 при длине покоя 0.6 — то есть
 * 49 связей (1.9%) нарушали предел УЖЕ В ПОЗЕ ПОКОЯ. Жёсткая стадия воевала с
 * длиной покоя каждый подшаг, тело не могло прийти в равновесие вовсе: дрейф
 * в покое 3 клетки за 20 секунд и момент импульса, растущий до 13.
 *
 * ОТКУДА 1.05. Это не вкус, а то же условие сшивания мембраны, что и у
 * contactRadius: круги соседей по контуру имеют радиус в половину длины покоя
 * с запасом CONTACT_SEAL, поэтому перекрываться они перестают ровно когда
 * связь растянулась сверх этого запаса. Числа обязаны совпадать.
 *
 * Следствие для движка: связь может растянуться лишь на 5% сверх покоя, иначе
 * мембрана течёт. Хочешь ткань тянучее — придётся сталкиваться с РЕБРОМ как с
 * отрезком, а не кругами на вершинах. Запас на этом теле всего 1.15x.
 */
const val LINK_MAX_STRETCH = 1.05

/**
 * ЗВАТЬ ЛИ ПРЕДЕЛ ДЛИНЫ СРАЗУ ПОСЛЕ СТАДИИ СВЯЗЕЙ. Переменная RB_MAXLEN_EARLY.
 *
 * Стадия предела длины зовётся чаще всех — девять раз за подшаг против четырёх у
 * связей, и это 23–27% тика. Слить её со стадией связей НЕЛЬЗЯ: она на то и
 * поставлена, чтобы идти ПОСЛЕ тех стадий, которые связь растягивают (площади,
 * изгиб, проекция кости, контакт). Сразу после решения связей она почти всегда
 * ничего не делает: связь только что поставлена на длину покоя.
 * Я попробовал выключить первый из двух заходов: девять заходов за подшаг
 * становятся пятью, тик 10.5 -> 9.0 мс, то есть −13%. И ЭТО ОТВЕРГНУТО: проверка
 * «тело не трогают, оно не должно ехать» падает с запасом 2.7 против 1.0 — без
 * раннего захода остаток стадий складывается со смещением, и покоящееся тело
 * начинает ползти. Тринадцать процентов такой цены не стоят.
 * Ускорять стадию надо не выбрасывая заходы, а убирая из неё корень — см. ниже.
 */
val MAXLEN_EARLY = true

/**
 * ИЗГИБ ГРАНИЧНОГО КОНТУРА — податливости, которые перебирает клавиша E.
 * -1 — стадия выключена. ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНА, см. почему ниже.
 *
 * ЗАЧЕМ. Единственное дешёвое, что вообще способно сделать дорогим заворот
 * ткани, при котором НИ ОДИН треугольник не вывернулся. Знаковая площадь —
