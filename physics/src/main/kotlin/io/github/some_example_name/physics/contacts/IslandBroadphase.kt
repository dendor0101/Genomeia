package io.github.some_example_name.physics

/**
 * ШИРОКАЯ ФАЗА ОСТРОВА МЕЖДУ ТИКАМИ (26.11.2026, IslandRun.kt, docs/physics/islands.md).
 *
 * Копия касаний острова (BoundaryContacts.islandFork) собирала широкую фазу с нуля на первом подшаге каждого тика: все
 * вершины острова — в сетку, каждой — поиск пар. У мира она идёт по ходу: перекладываются только вершины, уехавшие от
 * привязки дальше половины запаса. На ПК это было около 7% работы островов (профиль JFR 25.11: queryVertex и сборка
 * сетки). Здесь у острова свой запас между тиками: сетка (со следами по местным номерам вершин — массив на весь мир
 * каждому острову не по карману), список пар, подвижные вершины. Воркер, взявший остров, берёт в копию касаний его
 * запас и после острова отдаёт обратно; острова идут на разных воркерах от тика к тику, запас ходит с островом.
 *
 * БИТЫ ТЕ ЖЕ: полная пересборка и пересчёт по ходу дают одну сумму мира (опыт 25.11), список пар канонический. Запас
 * годится, только если остров в прошлом тике отработал с ним без отката (привязки его вершин писал он, а не мир), его
 * вершины контура те же и в том же порядке, а широкая фаза мира с тех пор не сбрасывалась (BoundaryContacts.bpEpoch —
 * пересборка, дописывание тела, пары покоя, обновление контура, сон, гибель, группы касаний) и топология та же
 * (structureVersion). Иначе — с нуля, как раньше.
 *
 * ОБЪЁМ (прикидка, не замер): на вершину контура острова — след в сетке 1–2 записи по 20 байт, ячейки сетки (ключ,
 * занятость, голова — 13 байт на слот при заполнении до половины), пары по 12 байт (несколько на вершину), свои номера
 * и подвижные 12 байт — около 100–150 байт. Остров из пары сотен клеток с контуром порядка 100 вершин — 10–15 КБ, в L1–L2
 * воркера; на мире тел до 1000 клеток (около 90 островов) — 1–1.5 МБ на все острова, но воркер за раз трогает один.
 */
internal class IslandBroadphase {
    /** Сетка с местными номерами вершин (AnchoredContactGrid.resetLocal); массив из одной сетки — поле копии касаний. */
    val grid = AnchoredContactGrid(0, 64)
    val shards = arrayOf(grid)
    var pairA = IntArray(64); var pairB = IntArray(64); var pairN = 0
    var nearRestSlot = IntArray(64); var nearN = 0
    var movers = IntArray(64); var moverCount = 0
    /** Вершины контура, при которых запас собран: на следующем тике — сверка. */
    var verts = IntArray(64); var vertN = 0
    /** Тик (BodyState.islandPhysTick), в котором остров с этим запасом отработал без отката; -1 — запас не годен. */
    var tick = -1L
    var epoch = -1L
    var structure = -1
    var n = -1
    /** Широкая фаза к концу острова собрана (bpValid и staticValid копии). */
    var valid = false
    /** Тик, в котором запас взял остров (разбиение); запас прошлого тика, никем не взятый, уходит в пул. */
    var claimed = -1L

    /** Тот же список вершин контура, что items[from until to]. */
    fun sameVerts(items: IntArray, from: Int, to: Int): Boolean {
        if (vertN != to - from) return false
        for (x in 0 until vertN) if (verts[x] != items[from + x]) return false
        return true
    }

    /** Запомнить, при чём запас собран: остров отработал без отката в тике [tick]. */
    fun remember(items: IntArray, from: Int, to: Int, tick: Long, epoch: Long, structure: Int, n: Int) {
        val m = to - from
        if (verts.size < m) verts = IntArray(maxOf(m, verts.size * 2))
        System.arraycopy(items, from, verts, 0, m); vertN = m
        this.tick = tick; this.epoch = epoch; this.structure = structure; this.n = n
    }

    /** Запас не годен (откат острова, остров ушёл в мир). */
    fun forget() { tick = -1L; valid = false }
}
