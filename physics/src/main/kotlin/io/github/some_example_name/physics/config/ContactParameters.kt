/** Включён ли самоконтакт. Клавиша K переключает на ходу. */
const val CONTACTS_ON = true

/**
 * Доля суммы радиусов, на которой срабатывает контакт.
 *
 * ЕДИНИЦУ СТАВИТЬ НЕЛЬЗЯ, и вот почему. В покое соседние клетки стоят на 0.6
 * при сумме радиусов 1.0 — они ПЕРЕКРЫВАЮТСЯ на 40%. Связанные пары из
 * контактов исключены, но вторые соседи по сетке стоят на 1.04..1.2, то есть
 * практически на пороге. При сокращении мышцы до 0.2 длины покоя они сходятся
 * ещё ближе, и контакт начал бы бороться с мышцей.
 *
 * 0.6 — это ровно расстояние между соседями в позе покоя: контакт срабатывает,
 * когда несвязанные клетки сблизились до расстояния связанных, то есть когда
 * ткань действительно налезла сама на себя.
 *
 * Меньше делать опасно: вершины должны расталкиваться РАНЬШЕ, чем пересекутся
 * отрезки контура между ними, иначе граница проскочит сквозь себя между
 * частицами.
 */
const val CONTACT_SCALE = 0.6

/**
 * «Ядро» для CCD: глубже этой доли суммы радиусов проникать нельзя.
 * Перенесено из прототипа как есть. Мягкое проникновение до ядра разрешено —
 * им занимается позиционный решатель, а CCD ловит только сквозной пролёт.
 */
/**
 * ПОТОЛОК ПОПРАВКИ КОНТАКТА ЗА ПОДШАГ, в долях средней длины связи.
 *
 * Контакт жёсткий, и без потолка глубокое проникновение разгребается целиком
 * за один подшаг. updateVelocities делит поправку на h, h крошечное, и из
 * загиба тела в себя получался выброс скорости под 84 клетки за тик при
 * рабочем уровне около трёх. Дальше он гасился потолком скорости, а тот
 * правит каждую частицу отдельно и импульс не сохраняет — так загиб и
 * превращался в вечное блуждание.
 *
 * ЗАКОН, А НЕ ВКУС: ПОТОЛОК НЕ МОЖЕТ БЫТЬ МЕНЬШЕ ХОДА КЛЕТКИ ЗА ПОДШАГ.
 *
 * Здесь была настоящая дыра, и она стоила разбора по подшагам. Потолок режет
 * смещение клетки от ВСЕХ её контактов вместе. Стояло 0.25, а потолок скорости
 * к тому времени подняли до 8 клеток за тик, то есть 8/16 = 0.5 длины связи за
 * подшаг. Контакт физически не мог остановить клетку: она уходила вперёд на
 * 0.5, её отжимали назад на 0.25, и каждый подшаг она продвигалась на 0.25
 * внутрь чужого тела. Четыре связи за тик. Рукой так протаскивалась свободная
 * клетка сквозь всю медузу, и мембрана при этом даже не должна была рваться —
 * прорыв шёл не силой, а переигрыванием по шагу.
 *
 * Поэтому значение ВЫВОДИТСЯ из потолка скорости, а не выбирается. Матрица
 * замеров на журнале игрока (подшагов внутри ткани из 3360): при 0.25 и vmax 8
 * — 47, при 0.25 и vmax 4 — ноль, при 0.5 и vmax 8 — ноль. Пробой есть ровно
 * тогда, когда MAX_SPEED_CELLS_PER_TICK / SUBSTEPS > этого потолка. Меняешь
 * SUBSTEPS или потолок скорости — здесь всё съезжает само и правильно.
 *
 * ДВОЙКА (06.10): сравнивать надо не с ходом ОДНОЙ клетки, а со ВЗАИМНЫМ
 * сближением. Потолок ограничивает поправку ПАРЫ: доля клетки выходит
 * cap * w_её / (w_i + w_j), то есть у двух равных по 0.25 каждой, а сумма всё
 * равно cap. А навстречу идут ДВЕ клетки, каждая по потолку скорости, значит
 * сближение за подшаг доходит до 2 * vmax / SUBSTEPS. При cap = vmax/SUBSTEPS
 * контакт отменял ровно половину — и свободную частицу у тяжёлого тела (вся
 * поправка на ней, партнёр неподвижен) ткань просто проходила насквозь. Так
 * внутрь попала клетка #1796 из журнала игрока: связей у неё ноль, решатель её
 * не толкал, по ней прошла мембрана.
 * Замер на таране медузы: тиков с проникновением 23 из 90 при 0.5 против 16 из
 * 90 при 1.0, осталось внутри 0 в обоих, пробоев 5 против 1.
 *
 * Стадию предела длины пришлось отвязать: см. LINK_MAX_STEP.
 */
val CONTACT_MAX_STEP = (2.0 * MAX_SPEED_CELLS_PER_TICK / SUBSTEPS)

const val CCD_CORE = 0.4

/** Отскок. Меньше единицы — энергия не растёт никогда. */
const val CONTACT_RESTITUTION = 0.1

/** Трение в контакте, ограничено накопленным нормальным импульсом. */
const val CONTACT_FRICTION = 0.3

/**
 * ПОТОЛОК НА СКОРОСТЬ, в средних длинах связи ЗА ТИК.
 *
 * Не физическая величина, а гарантия для коллизий: DDA обходит все ячейки пути,
 * но буфер ddaX конечен, и растущий без предела путь однажды в него не влезет.
 * Плюс это верхняя граница, на которой держится вся оценка «широкую фазу можно
 * строить раз в тик» при переносе в движок.
 *
 * Выражено в клетках за тик, а не в единицах в секунду, потому что именно это
 * отношение и важно для сетки — оно не зависит ни от UPS, ни от масштаба тела.
 */
/**
 * Поднято с 4.0 до 8.0, и это не ослабление, а разведение двух механизмов.
 *
 * Потолок скорости правит КАЖДУЮ частицу отдельно и потому импульс не
 * сохраняет — как аварийная сетка это нормально, как рабочий ограничитель
 * это источник блуждания. Раньше он и работал ограничителем: при загибе тела
 * в себя срабатывал 243 раза за одно перетаскивание.
 *
 * Теперь скорость держит CONTACT_MAX_STEP — потолок ПОПРАВКИ, симметричный
 * по паре. ВАЖНО: «двукратный запас», которым восьмёрка обосновывалась здесь
 * раньше, был прямой дырой. Потолок поправки стоял на 0.25 длины связи за
 * подшаг, а восьмёрка разрешает ход 0.5 — и клетка побеждала контакт по
 * арифметике, продвигаясь внутрь чужого тела на 0.25 каждый подшаг. Запаса
 * тут быть не может: потолок поправки обязан быть НЕ МЕНЬШЕ хода за подшаг,
 * поэтому он теперь из этой константы и выводится.
 *
 * Проскок при этом по-прежнему невозможен: 8 клеток за тик при 16 подшагах
 * это полклетки за подшаг, а ядро контакта — две трети клетки. Встречной паре
 * на полном ходу пара десятых не хватит, и там сработает обрезка CCD — ровно
 * тот редкий случай, ради которого она и оставлена.
 */
const val MAX_SPEED_CELLS_PER_TICK = 8.0

/** Прикладывать контакт к скорости до интегрирования. См. toVelocity. */
const val CONTACT_BEFORE_INTEGRATE = false
