/** Сон тел по умолчанию включён. Выключить для A/B: RB_SLEEP=0. См. BodySleep. */
const val SLEEP_ON = true

/** Сколько тиков подряд организм должен быть спокоен, чтобы уснуть: 60 — 2 секунды. */
const val SLEEP_TICKS = 60

/**
 * ПОКОЙ — ЭТО МЕСТО, А НЕ СКОРОСТЬ: за серию в SLEEP_TICKS тиков ни одна живая клетка
 * не ушла от места, где серия началась, дальше этого, в средних длинах связи.
 * 0.06 связи за 60 тиков — прежний порог 0.001 связи за тик, но по месту.
 *
 * По скорости тело не засыпало: лёгкие клетки дрожат с частотой подшагов, а на
 * записи 22.10 нашлось и колебание с периодом три тика (средняя скорость клетки
 * 0.0021 -> 0.0006 -> 0.0025 связи за тик при неподвижном центре масс). Любое
 * колебание на месте с размахом меньше порога тело теперь усыпляет, а медленный
 * уход (0.002 связи за тик) — нет: он выводит клетку за порог за 30 тиков.
 */
const val SLEEP_DRIFT_CELLS = 0.06

/**
 * Будит спящего только касание клетки, которая С НАЧАЛА ТИКА ушла дальше этого, в
 * средних длинах связи.
 *
 * Ради цепочек: рельеф лежит кусками вплотную, и если бы будило любое касание
 * бодрствующего тела, проснувшийся кусок тут же будил бы соседей, а те своих — вся
 * карта просыпалась бы от одного толчка. Проснувшийся кусок стоит, и соседей он не
 * трогает, пока его самого не толкнули по-настоящему.
 *
 * МЕСТО, А НЕ СКОРОСТЬ, и порог с запасом над дребезгом: мгновенная скорость дрожащей
 * лёгкой клетки — до 0.15 клетки за тик при неподвижном теле (запись 22.10), размах
 * этого дребезга ~0.005 связи. По скорости (прежний порог 0.005 клетки за тик) два
 * соседних куска будили бы друг друга вечно. Таран и пуля проходят клетки за тик.
 */
const val WAKE_DRIFT_CELLS = 0.02

/** Мышца считается работающей, пока активация отличается от цели или от прошлого тика больше этого. */
const val SLEEP_MUSCLE_EPS = 1e-4

/**
 * ПОРОГ ПРОБУЖДЕНИЯ КАСАНИЕМ ДЛЯ СПЯЩЕГО С ОПОРОЙ О ДНО (террейн: пружина к месту, Grip.kt) — в
 * связях за тик, как WAKE_DRIFT_CELLS. Спящий кусок террейна для касающегося — твёрдая опора;
 * будит его удар, а не ползущий или лежащий на нём организм. Иначе куски у живых организмов
 * будились и засыпали без конца, и каждое пробуждение перестраивало широкую фазу по всей
 * поверхности пещер (замер в игре 04.11: подготовка касаний — 16–35 мс тика из 40–56).
 */
const val GROUND_WAKE_DRIFT_CELLS = 0.25
