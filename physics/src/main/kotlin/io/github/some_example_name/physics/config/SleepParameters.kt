package io.github.some_example_name.physics

/** Сон тел по умолчанию включён. Выключить для A/B: RB_SLEEP=0. См. BodySleep. */
const val SLEEP_ON = true

/**
 * Порог покоя: самая быстрая живая клетка организма медленнее этого, в средних длинах
 * связи за тик. 0.001 связи за тик — 0.03 связи в секунду, клетка за полминуты.
 * Медленный накат после гребка обрывается при засыпании, поэтому порог низкий.
 */
const val SLEEP_SPEED_CELLS_PER_TICK = 0.001

/** Сколько тиков подряд организм должен быть спокоен, чтобы уснуть: 60 — 2 секунды. */
const val SLEEP_TICKS = 60

/**
 * Будит спящего только касание клетки быстрее этого, в длинах связи за тик.
 *
 * Впятеро выше порога сна ради цепочек. Рельеф лежит кусками вплотную: если бы
 * будило любое касание бодрствующего тела, проснувшийся кусок тут же будил бы
 * соседей, а те своих, и вся карта просыпалась бы от одного толчка. Проснувшийся
 * кусок стоит, его клетки медленнее порога, и соседей он не трогает, пока его самого
 * не толкнули по-настоящему.
 */
const val WAKE_SPEED_CELLS_PER_TICK = 0.005

/** Мышца считается работающей, пока активация отличается от цели или от прошлого тика больше этого. */
const val SLEEP_MUSCLE_EPS = 1e-4
