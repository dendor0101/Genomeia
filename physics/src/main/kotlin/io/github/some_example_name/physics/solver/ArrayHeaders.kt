package io.github.some_example_name.physics

/**
 * ДЛИНЫ МАССИВОВ — ДО ЦИКЛА. Это не стиль, а четверть тика на телефоне (docs/physics/reference.md, находка 37).
 *
 * Обращение `a[i]` сверяет индекс с длиной массива, а длина лежит в заголовке массива — в его начале.
 * Android (ART) кладёт каждый массив от 12 КБ (у нас это любой массив по частицам от 3 тысяч частиц) в
 * начало страницы памяти, поэтому заголовки всех больших массивов стоят на одном и том же месте
 * страницы. У Cortex-A55 в кэше L1 такому месту достаётся два набора по четыре линии (чётная и нечётная страница).
 * Цикл физики ходит сразу в десяток массивов и, если компилятор оставил чтение длины внутри цикла,
 * выбивает заголовки друг другом: на каждой частице длины заново достаются из медленной памяти.
 * На ПК массивы лежат подряд, и этого нет.
 *
 * Замеры на Galaxy A21s (Cortex-A55, Android 10), толпа 5.4 тысячи клеток, один поток:
 *   тот же код с массивами не по границе страницы (ключ ART, только для опыта) — тик 116.7 → 81.8 мс;
 *   при том же сдвиге данных массивы по 6 страниц (заголовки в одном наборе) — проход 72.6 нс на
 *   частицу, по 7 страниц — 31.5; чтение длин до цикла на худшем размещении — 77.3 → 38.7.
 *
 * ЧТО ДЕЛАТЬ В ГОРЯЧЕМ ЦИКЛЕ (частицы, связи, треугольники, контакты):
 *   1. Массив — в локальную переменную до цикла (`val px = px`), а не поле на каждом проходе.
 *   2. До цикла — [lengthsBeforeLoop] со всеми массивами цикла. После неё компилятору известно, что
 *      массивы не null, и чтение длины он выносит из цикла сам; проверка границ остаётся, но сверяет
 *      с длиной в регистре.
 *   3. Массив, которого может не быть, — не `null` с проверкой в цикле (после проверки на null
 *      компилятор читает длину заново внутри цикла), а пустой массив ([NO_FLOATS]) и признак в
 *      локальной переменной; либо отдельный цикл на каждый случай.
 *   4. Тело цикла — в том же методе: ядро на один элемент либо `inline` с массивами в параметрах,
 *      либо написано прямо в цикле. Вызов метода на каждый элемент читает заголовки заново.
 *
 * Битов правка не меняет: те же операции над теми же числами в том же порядке.
 * Отвергнуто: один общий массив на все поля («арена») и запись на частицу лечат то же самое, но это
 * правка каждого обращения к частице; на Android позже придёт ядро на Rust, где заголовков нет.
 */
@Suppress("NOTHING_TO_INLINE")
internal inline fun lengthsBeforeLoop(lengths: Int) {
    if (lengths < 0) negativeArrayLength()
}

/** Недостижимо: длина массива не бывает отрицательной. Отдельным методом, чтобы не раздувать ядро. */
internal fun negativeArrayLength(): Nothing = throw IllegalStateException("отрицательная длина массива")

/** Пустые массивы вместо `null` в горячих циклах: см. [lengthsBeforeLoop], пункт 3. */
@JvmField internal val NO_FLOATS = FloatArray(0)
@JvmField internal val NO_DOUBLES = DoubleArray(0)
@JvmField internal val NO_BOOLEANS = BooleanArray(0)
