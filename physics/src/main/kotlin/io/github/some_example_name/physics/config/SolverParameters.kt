 *
 * КУДА ЖАТЬ, ЕСЛИ ПОНАДОБИТСЯ ВЕРНУТЬ ВРЕМЯ. По убыванию отдачи:
 *
 *   1. Не гонять ВСЕ стадии каждый заход. Сходимости мешает пара
 *      «связи против контакта», а площади, изгиб и проекция кости внутри
