package io.github.some_example_name.physics

/**
 * СРЕДА МИРА, КОТОРУЮ КЛИЕНТ МЕНЯЕТ НА ХОДУ (игра: окно «Настройки мира», 22.11.2026) — то, что
 * раньше было только константами материала. Клиент ставит её раз в тик до шага
 * (PhysicsWorld.setEnvironment); в снимок мира она не входит — её хранит и хэширует клиент, как
 * рамку и команды мышц.
 *
 * ПО УМОЛЧАНИЮ — РОВНО КОНСТАНТЫ. Ядра читают поле вместо константы, а множитель 1.0 при
 * переводе точен, поэтому стенды, записи и проверки считаются теми же битами, пока игрок ничего
 * не трогал. Цена — чтение поля раз на вызов стадии (у сопротивления рёбер — раз на ребро, объект
 * лежит в L1).
 *
 * Что НЕ вынесено сюда: число подшагов, пороги разрушения и всё, от чего зависит сходимость, —
 * их игрок крутить не должен; решение о материале остаётся за подбором на стендах.
 */
class WorldEnvironment {
    /**
     * Гравитация по y, единиц мира в секунду в квадрате; 0 — мир сверху, как всегда был.
     * Прикладывается внешней силой по скоростям (applyGravity) — в окне учёта импульса, иначе
     * учёт счёл бы её внутренней и снял (TickMomentum). Константа GRAVITY — пол стенда, не она.
     */
    var gravityY = 0.0

    /** Изотропное сопротивление среды, 1/сек. См. MEDIUM_DRAG. */
    var mediumDrag = MEDIUM_DRAG

    /** Сопротивление рёбер контура — линейная и квадратичная части. См. NORMAL_DRAG. */
    var normalDrag = NORMAL_DRAG
    var normalDragQuadratic = NORMAL_DRAG_QUADRATIC

    /** Податливость связей и площадей ткани. Больше — мягче. См. SOFT_COMPLIANCE, AREA_COMPLIANCE. */
    var softCompliance = SOFT_COMPLIANCE
    var areaCompliance = AREA_COMPLIANCE

    /** Кулоново трение касания тел (и стенки), доля нормальной поправки. См. CONTACT_FRICTION. */
    var contactFriction = CONTACT_FRICTION
}
