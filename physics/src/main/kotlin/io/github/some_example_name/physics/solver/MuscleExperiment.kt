package io.github.some_example_name.physics

/*
 * ВРЕМЕННО, опыт 19.11.2026: три варианта мышц по просьбе автора («Давай попробуем все 3 варианта и потом
 * когда будет готово я попрошу запустить стенды по каждому»). Переключатели — ключи настроек мира
 * (стенды: -Pconfig=MX_…=…); без ключей мир идёт побитово как до опыта. После решения автора принятый
 * вариант переписывается законом, остальное убирается целиком.
 *
 * 1. MX_STRENGTH = k — мышцы слабее: команда сокращения s даёт 1 − k·(1 − s) (k = 0.8: 0.5 → 0.6).
 *    Расслабление (s > 1) не трогается.
 * 2. MX_FIBER — мышца с волокном: 20.11.2026 стала законом (config/FiberParameters.kt, solver/MuscleFiber.kt);
 *    волокно задаёт клиент по клетке, ключ MX_FIBER = k остался для замеров.
 * 3. MX_SPLIT = 1 и MX_PULL — без раскачки мышцей и с потолком тяги ниже. Раскачку в сценах «дёрганья» давал сам
 *    потолок тяги (MUSCLE_MAX_PULL): он резал весь недобор связи под сокращённой мышцей, вместе с упругостью
 *    ткани, растянутой сверх длины покоя. Сокращённая мышца становилась мягкой на растяжение, отпущенная — снова
 *    жёсткой; переключение каждые два тика раскачивало тело (cappedPull). MX_PULL — сам потолок (0.1 — как было).
 * 4. MX_OPEN = 1 (20.11.2026) — потолок на разжатие: команда мышцы растёт не быстрее MUSCLE_MAX_PULL за тик
 *    (см. openingRateLimit ниже).
 */

/** Вариант 1: доля глубины сокращения команды (1 — как было). */
@JvmField var MX_STRENGTH = 1.0f

/**
 * Вариант 3: потолок тяги — только на работу мышцы. 1 — растяжение связи сверх длины покоя держит ткань целиком,
 * потолком ограничена лишь тяга от покоя к цели. 0 — как было (потолок на весь недобор).
 */
@JvmField var MX_SPLIT = 0

/** Недобор связи длиной [len] под мышцей с целью [target] < [rest], уже больше потолка. */
internal fun cappedPull(len: Float, rest: Float, target: Float): Float {
    val cap = MUSCLE_MAX_PULL * rest
    if (MX_SPLIT < 1 || len <= rest) return cap
    val muscle = rest - target
    return (len - rest) + (if (muscle < cap) muscle else cap)
}

/**
 * Ключи физики для игры: её мир собирается с пустыми настройками, поэтому — запасной путь через свойство процесса, для
 * сравнений на глаз (`gradlew --no-daemon :lwjgl3:run "-Dgenomeia.physics=MX_OPEN=1"`; лаунчер прокидывает в игру все
 * genomeia.*, как genomeia.substeps). В отчёт .bug эти ключи не попадают: отчёт, снятый с ними, без них не повторится.
 * До 24.11 тем же путём шли ключи гашения QD_* — гашение убрано вместе с клином (находка 40).
 */
private val GAME_KEYS: Map<String, String> = System.getProperty("genomeia.physics").orEmpty().split(',')
    .mapNotNull { val kv = it.split('='); if (kv.size == 2 && kv[0].isNotBlank()) kv[0].trim() to kv[1].trim() else null }.toMap()
private var gameKeysAnnounced = false

/** Ключи опыта — из настроек мира. Все миры процесса стенда собраны с одними настройками. */
internal fun configureMuscleExperiment(c: PhysicsConfig) {
    if (GAME_KEYS.isNotEmpty() && !gameKeysAnnounced) {
        gameKeysAnnounced = true
        println("Ключи физики из genomeia.physics (не закон мира, только для сравнения): $GAME_KEYS")
    }
    MX_STRENGTH = c["MX_STRENGTH"]?.toFloatOrNull() ?: 1.0f
    MUSCLE_MAX_PULL = c["MX_PULL"]?.toFloatOrNull() ?: 0.1f
    MX_SPLIT = c["MX_SPLIT"]?.toIntOrNull() ?: 0
    MX_OPEN = (c["MX_OPEN"] ?: GAME_KEYS["MX_OPEN"])?.toIntOrNull() ?: 0 // потолок разжатия мышцы: ключ и для игры
}

/** Вариант 1: команда клетки после ослабления. */
internal fun weakenedCommand(scale: Float): Float =
    if (MX_STRENGTH == 1.0f || scale >= 1f) scale else (1.0f - MX_STRENGTH * (1.0f - scale)).toFloat()

/**
 * ВРЕМЕННО, опыт 20.11.2026 (MX_OPEN = 1). Автор: «Давай потолок на разжатие также как и с сжатием».
 *
 * ПОЧЕМУ. Сокращение ограничено MUSCLE_MAX_PULL: связь мышцы тянет не сильнее связи, растянутой на эту долю длины
 * покоя, — мышца сжимается примерно за 5 тиков. Разжатие ничем не ограничено: сжатая ткань распрямляется к выросшей
 * цели с полной жёсткостью (≈43% остатка за подшаг — почти вся за тик), а команда «расслабиться» проводит множитель
 * через 1 за два тика (0.5 → 0.79 → 1.07). Ткань по инерции перелетает длину покоя, расслабленная мышца (+1) вчетверо
 * мягче на растяжении и перелёт не тормозит, и обычная ткань рядом рвётся уже на 5%.
 *
 * ЗАКОН. Команда на разжатие (множитель клетки растёт) растёт не быстрее MUSCLE_MAX_PULL за тик: вместе с ней медленно
 * растут длина и площадь покоя и порог раздавливания, ткань успевает, распор за тик — не больше этой доли длины покоя,
 * удар по мышце держится полной жёсткостью. Сокращение — как было. Мышцы-кластеры (muscleScaleOf, старые проверки) не
 * трогаются: у стендов и игры мышца — множитель клетки.
 *
 * ОТВЕРГНУТО (находка 28): потолок на сам распор — пока множитель растёт, связь и треугольник мышцы толкают не сильнее
 * связи, сжатой на MUSCLE_MAX_PULL, как тяга при сокращении. Порог раздавливания (0.35 × длина покоя × множитель) при этом
 * поднимается с командой за два тика, а распираемая потолком ткань за ним не успевает — связи рвутся «сжатием», хотя их
 * никто не давит: отбор — разрывов сжатием 8 → 50 тысяч, разрушение 186 → 324, смещение мышцы за волну 4.21 → 3.18.
 */
@JvmField var MX_OPEN = 0

/** Шаг множителя клетки к команде: на разжатии — не больше MUSCLE_MAX_PULL за тик (MX_OPEN = 1). */
internal fun openingRateLimit(cur: Float, next: Float): Float {
    if (MX_OPEN != 1 || next <= cur) return next
    val lim = (cur + MUSCLE_MAX_PULL).toFloat()
    return if (next > lim) lim else next
}
