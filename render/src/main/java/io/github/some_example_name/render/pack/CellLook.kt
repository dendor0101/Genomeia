package io.github.some_example_name.render.pack

/**
 * Как клетка выглядит в отладочном режиме — четвёртое поле инстанса (CellInstanceBuffer,
 * атрибут a_look в shaders/debug_view/cell.vert):
 *
 *   look = pattern | action<<8 | transparency<<16 | filter<<24
 *
 *  - pattern — схематический рисунок, константы ниже. Рендер знает только рисунки, а не
 *    типы клеток: какой клетке какой рисунок, решает :core (DebugCellPalette). Имена
 *    взяты по тому, что нарисовано, а клетка-образец указана в комментарии.
 *  - action — сигнал действия клетки −1..1 знаковым байтом (round(s·127)): от него
 *    анимация мышц, присосок, хвоста и прочих клеток, которые что-то ДЕЛАЮТ по нейросигналу.
 *  - transparency — 0 непрозрачная, 255 невидимая. Нужна «призраку» в редакторе генома —
 *    клетке, которая появится на следующей стадии.
 *  - filter — значение для фильтра отладки (DebugFilter): заполненность энергией
 *    ([energyFilterByte]) или нормализованный нейросигнал ([signalFilterByte]). Какой из них
 *    лежит в байте, решает тот, кто упаковал кадр: фильтр выбран один на кадр и едет с ним.
 *
 * Ноль во всех байтах — непрозрачная клетка без рисунка и без сигнала, то есть ровно
 * прежний вид. Его и пишут все, кто про поле не знает (реалистичный и ностальгический
 * режимы, превью геномов, старые дампы).
 *
 * Номера рисунков дублируются константами P_* в shaders/debug_view/cell_look.glsl —
 * менять только вместе. Это не формат файла: в дампах сцен номер живёт только как
 * снимок кадра.
 */
object CellLook {

    /** Плоская клетка цвета типа — прежний вид отладки. */
    const val PLAIN = 0

    /** Лист: прозрачная клетка, ядро и хлоропласты, бегущие группами вдоль края. */
    const val CHLOROPLASTS = 1

    /** Жир: светло-жёлтая капля почти на весь объём и маленькое ядро у края. */
    const val FAT_DROPLET = 2

    /** Кость: остеон — канал, неровные ламеллы, редкие лакуны; соседи сливаются. */
    const val OSTEON = 3

    /** Хвост: тело с базальным тельцем; сам жгутик — фигура оверлея KIND_FLAGELLUM. */
    const val FLAGELLUM_BASE = 4

    /** Нейрон: тёмный сгусток, ветвящаяся сеть отростков, фиолетовые гранулы. */
    const val NEURON = 5

    /** Мышца: поперечный срез волокон; темнеет при сжатии, светлеет при растяжении. */
    const val MUSCLE = 6

    /** Присоска-поглотитель: зернистость и короткие реснички, бьющие к поверхности. */
    const val CILIA_INWARD = 7

    /** Стволовая: крупное тёплое ядро, неровная оболочка, медленная пульсация. */
    const val STEM = 8

    /** Выделитель: ядро у мембраны по направлению и выходящие наружу частицы. */
    const val EXCRETA = 9

    /** Присоска: 5–8 вложенных неровных колец, ритмично сжимаются. */
    const val SUCTION_RINGS = 10

    /** Липкая: бугристая колышущаяся поверхность, мягкое нутро. */
    const val STICKY_BUMPS = 11

    /** Насос: короткие иглы по периметру, ритмично сокращающиеся камеры внутри. */
    const val PUMP_NEEDLES = 12

    /** Хамелеон: пигментные включения, переливающиеся зелёным, красным и синим. */
    const val PIGMENTS = 13

    /** Глаз: овальное ядро и синие ветвящиеся капилляры. */
    const val EYE = 14

    /** Синапс: два сближающихся ядра, у каждого своя сеть отростков. */
    const val SYNAPSE = 15

    /** Сенсор касания: маленькое ядро и сеть отростков до самой мембраны. */
    const val TOUCH_NET = 16

    /** Зигота: светлая клетка с одним большим ядром, медленная пульсация. */
    const val ZYGOTE = 17

    /** Продюсер: два соприкасающихся ядра, как при делении. */
    const val DIVIDING = 18

    /** Источник феромона: мелкие разноцветные гранулы, выходящие наружу. */
    const val EMITTER_GRANULES = 19

    /** Сенсор феромона: длинные тонкие колышущиеся реснички. */
    const val LONG_CILIA = 20

    /** Каратель: плотная клетка с неровными шипами и красными включениями. */
    const val SPIKES = 21

    /** Сенсор скорости: множество очень коротких подвижных ресничек. */
    const val SHORT_CILIA = 22

    /** Контроллер: микрочип с антенной в центре и волокна от него. */
    const val CHIP = 23

    /** Рисунков всего; номера 0 until COUNT. */
    const val COUNT = 24

    /** Сигнал −1..1 знаковым байтом; NaN — ноль. */
    fun actionByte(signal: Float): Int {
        val clamped = if (signal > 1f) 1f else if (signal < -1f) -1f else if (signal == signal) signal else 0f
        return Math.round(clamped * 127f) and 0xFF
    }

    /** Прозрачность 0..1 (1 — невидимая) в байт. */
    fun transparencyByte(transparency: Float): Int =
        (transparency * 255f + 0.5f).toInt().coerceIn(0, 255)

    fun look(pattern: Int, action: Float = 0f, transparency: Float = 0f, filter: Int = 0): Int =
        (pattern and 0xFF) or
            (actionByte(action) shl 8) or
            (transparencyByte(transparency) shl 16) or
            ((filter and 0xFF) shl 24)

    /**
     * Фильтр «энергия»: заполненность клетки 0..1 (энергия / её максимум) в байт.
     *
     * Заполненность, а не энергия как есть: максимум у клеток разный (жир держит больше), и
     * в абсолютных числах жир светился бы всегда, а голодная клетка с малым запасом — нет.
     * Голод виден одинаково у любой клетки: синяя — пустая, пурпурная — полная.
     */
    fun energyFilterByte(energy: Float, maxEnergy: Float): Int {
        if (!(maxEnergy > 0f)) return 0
        val fullness = energy / maxEnergy
        return if (fullness > 0f) (minOf(fullness, 1f) * 255f + 0.5f).toInt() else 0
    }

    /**
     * Фильтр «нейросигнал»: выход клетки, сжатый в −1..1 как s / (|s| + [SIGNAL_KNEE]),
     * знаковым байтом.
     *
     * ПОЧЕМУ ТАК
     * ----------
     * Сигнал не ограничен: у формул бывают и сотые, и десятки. Линейный зажим в −1..1
     * сливает всё, что больше единицы, в одно, а слабые сигналы (0.02–0.1) почти не
     * отличает от нуля — именно их и ищут, разбираясь, куда пропадает сигнал. Логарифм не
     * определён в нуле и несимметричен по знаку. s / (|s| + k) — монотонная, симметричная,
     * ноль остаётся ровно нулём, большие сигналы не сливаются (1 → 0.8, 4 → 0.94), а
     * половина шкалы приходится на |s| = k: 0.05 даёт уже 0.17, то есть заметно синее нуля.
     * tanh похож, но насыщается быстрее: 2 и 10 у него неразличимы.
     */
    fun signalFilterByte(signal: Float): Int {
        if (signal != signal) return 0
        val normalized = signal / (Math.abs(signal) + SIGNAL_KNEE)
        return Math.round(normalized * 127f) and 0xFF
    }

    /** |сигнал|, при котором фильтр «нейросигнал» проходит половину шкалы. */
    const val SIGNAL_KNEE = 0.25f
}
