package io.github.some_example_name.render

/**
 * Фильтр отладочного режима: чем закрашивать клетки вместо цвета их типа.
 *
 * Едет с кадром (RenderFrame.debugFilter) и читается только в [RenderMode.DEBUG]. Значение
 * для клетки — четвёртый байт её поля look (CellLook.filterByte), его готовит :core под
 * тот фильтр, что выбран сейчас.
 *
 * Имена констант — формат файла: фильтр выбирают командой, и она лежит в журнале .bug
 * по имени. Не переименовывать.
 */
enum class DebugFilter {

    /** Цвет и рисунок типа — обычный отладочный вид. */
    ORIGINAL,

    /** Заполненность энергией: пустая клетка синяя (0, 0, 1), полная — пурпурная (1, 0, 1). */
    ENERGY,

    /**
     * Нейросигнал на выходе клетки: ноль синий, положительный уходит в пурпурный (1, 0, 1),
     * отрицательный — в голубой (0, 1, 1). Нормализация — CellLook.signalFilterByte.
     */
    SIGNAL
}
