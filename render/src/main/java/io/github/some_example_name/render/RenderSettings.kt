package io.github.some_example_name.render

/**
 * Глобальные переключатели рендера, живущие дольше одного кадра.
 *
 * ПРО @Volatile
 * -------------
 * [usePostProcess] пишет GL-поток (кнопка «показывать связи» в экране симуляции), а
 * читает его в том числе поток симуляции: сборщик снимка по нему решает, заполнять ли
 * буфер связей и направляющие углы. Раньше это была обычная глобальная `var` в
 * ShaderManager.kt — то есть запись из одного потока и чтение из другого без всякой
 * синхронизации. Практически это выражалось в том, что переключение иногда «не
 * срабатывало» до следующего тика; формально же поток симуляции имел полное право не
 * увидеть новое значение никогда.
 *
 * Флаг переключают руками раз в несколько минут, так что цена volatile-чтения здесь
 * не обсуждается.
 */
object RenderSettings {

    @Volatile
    var usePostProcess: Boolean = true
}
